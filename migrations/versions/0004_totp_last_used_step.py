"""Последний принятый шаг TOTP: колонка `totp_enrollments.last_used_step` (T-103, срез `0004`).

Что появляется:

1. **`last_used_step` (`BIGINT`, nullable)** — номер шага, на котором принят последний код
   (TZ §8.2 «Коды принимаются один раз (защита от повторного использования окна)», ADR-013 п. 4).
   `NULL` = ни один код ещё не принят. Форма выбрана заказчиком (ask
   `865f677f-46b6-4acd-ae9c-40c522ab9b1d`, 2026-11-21) ровно так, как предлагал ADR-013; обходные
   варианты — `rate_buckets` с новой областью или вывод шага из `sessions.last_seen_at` — отклонены
   тем же решением, потому что счётчик попыток не отвечает на «какой шаг уже израсходован», а
   активность сеанса подменяет смысл колонки и даёт ложные отказы на границе шага.
2. **`ck_totp_enrollments_last_used_step_not_negative`** (`last_used_step >= 0`). Шаг — это
   `unix_time // 30`, то есть секунды с эпохи 1970 года; отрицательного шага не бывает, а `-1` —
   типичный «sentinel», который выглядит как «значение есть» и стирает различие с `NULL`. На этом
   различии держится всё правило §8.2: после `-1` нельзя отличить «кода не было» от «был шаг -1».

**Слот цепи.** `0004` занимает `T-103` — так решил заказчик (ask
`a4f68e3c-9dfb-4941-ad2d-34575db67415`, 2026-11-21). Цепочка Alembic линейна, и «взять `0005`»,
не имея `0004`, технически невозможно: `down_revision` обязан ссылаться на существующую ревизию.
`T-116` (`web_audit_outbox`) переносится на `0005`; самой задачи в `tasks/todo.md` пока нет — номер
ставится при её оформлении.

Что сознательно не появляется:

- **Ограничения на монотонность.** «Принятым считается только шаг строго больше ранее принятого»
  (RFC 6238 §5.2, ADR-013 п. 4) декларативным `CHECK` не выражается: сравнивать нужно со значением
  этой же строки, то есть нужен триггер. Триггер здесь противоречит принятому решению схемы
  («append-only держат права, а не триггеры» — ревизия `0002` п. 3): кусался бы молча при любой
  правке строки, включая отзыв привязки и восстановление из дампа. Поэтому страж — форма запроса
  среза `R4c`:

      UPDATE totp_enrollments SET last_used_step = %(шаг)s
       WHERE id = %(привязка)s AND (last_used_step IS NULL OR last_used_step < %(шаг)s)

  и `rowcount = 0` означает «код уже израсходован». Живая проверка
  `tests/integration/test_identity_schema_db.py` фиксирует ровно это: база монотонность не держит
  (безусловный `UPDATE` откатывает шаг назад), условная форма — держит.
- **`server_default`.** Без явного значения колонка и так `NULL`; подставлять `0` нельзя, потому
  что шаг `0` — это 1970 год и «один код уже израсходован», то есть привязка рождалась бы с
  украденным первым окном.
- **`NOT NULL`.** Потребитель (запись и проверка шага) появляется в `R4c`; `NOT NULL` до этого
  сделал бы невозможной саму строку привязки, у которой кода ещё не было.
- **Индексов.** Колонка читается вместе со строкой привязки по её PK; отдельных выборок по шагу
  нет — путь поиска привязки держит `ix_totp_enrollments_user_active`.
- **Правок предыдущих ревизий.** Колонка не дописывается в `0003`: та ревизия уже применена
  dev-стендом CI, и окно возможности править применённую ревизию для неё закрыто (ADR-007,
  `docs/HANDOFF.md §1.27`).

Тип выбран `BIGINT`, а не `INTEGER`: заказчик задал именно эту форму, и она переживает смену единиц
(если счётчик когда-нибудь начнут считать в миллисекундах, `int4` кончится на 2038 годе, а RFC
6238 §4.2 прямо требует держать `T` шире 32 бит), плюс это тот же тип, что у `audit_log.id`.

Разрыв площадки остаётся открытым и после этой ревизии: на `tbot.rusiksoft.ru` база стоит на `0002`,
в репозитории теперь `0004`. Автоматической сверки «головная ревизия = применённая на площадке» в
проекте нет (`docs/HANDOFF.md §1.36`), поэтому перед следующим деплоем обязательны пересъём пары
«run → commit» по digest и `run --rm migrate`.

Проверки: `upgrade head → downgrade base → upgrade head` (CI job `миграции`), офлайн-соответствие
моделей и ревизии — `tests/contract/test_identity_schema.py` (в разборе офлайн-SQL добавлена
поддержка `ALTER TABLE … ADD COLUMN`, иначе колонка, добавленная более поздней ревизией, в сверке
невидима и модели с ревизией «расходятся» в одну сторону), поведение на живой базе — шаг job'а
`миграции` «поведение схемы на живой базе» (`tests/integration/test_identity_schema_db.py`).
"""

