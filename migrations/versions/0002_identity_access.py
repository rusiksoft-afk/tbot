def _totp_enrollments() -> None:
    op.create_table(
        "totp_enrollments",
        sa.Column("id", sa.Uuid(), nullable=False),
        sa.Column("user_id", sa.Uuid(), nullable=False),
        sa.Column(
            "secret_enc",
            sa.LargeBinary(),
            nullable=False,
            comment="AES-256-GCM (nonce + тег + шифртекст); KEK вне БД, TZ §8.4",
        ),
        sa.Column(
            "issuer",
            sa.Text(),
            nullable=False,
            comment="метка URI otpauth://; без неё QR-код не собрать",
        ),
        sa.Column("enrolled_at", _timestamptz(), server_default=sa.text("now()"), nullable=False),
        sa.Column("confirmed_at", _timestamptz(), nullable=True),
        sa.Column("revoked_at", _timestamptz(), nullable=True),
        sa.Column("verify_window", sa.Integer(), server_default=sa.text("1"), nullable=False),
        sa.PrimaryKeyConstraint("id", name=op.f("pk_totp_enrollments")),
        sa.CheckConstraint(
            "verify_window BETWEEN 0 AND 2", name=op.f("ck_totp_enrollments_verify_window")
        ),
        sa.CheckConstraint(
            "confirmed_at >= enrolled_at",
            name=op.f("ck_totp_enrollments_confirmed_after_enrolled"),
        ),
        sa.CheckConstraint(
            "revoked_at >= enrolled_at", name=op.f("ck_totp_enrollments_revoked_after_enrolled")
        ),
        sa.ForeignKeyConstraint(
            ["user_id"],
            ["users.id"],
            name=op.f("fk_totp_enrollments_user_id_users"),
            ondelete="RESTRICT",
        ),
        comment=(
            "Привязки TOTP (TZ §8.2). Секрет — AES-256-GCM шифртекст, KEK вне БД (§8.4). "
            "Подтверждение — два последовательных кода, окно не выше ±2 шагов."
        ),
    )
    # Одна действующая привязка на пользователя: частичный уникальный индекс по §8.2
    # (отзыв = `revoked_at`, а не новая строка, иначе «действующих» станет две).
    op.create_index(
        "ix_totp_enrollments_user_active",
        "totp_enrollments",
        ["user_id"],
        unique=True,
        postgresql_where=sa.text("revoked_at IS NULL"),
    )


