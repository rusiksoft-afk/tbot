"""Идентичность и доступ: таблицы §4.1 техзадания (T-009, веха M1).

Что появляется: `users`, `invitations`, `totp_enrollments`, `backup_codes`, `totp_failures`,
`sessions`, `ip_allowlist`, `audit_log`. До этой ревизии в базе был только `app_meta`, поэтому
ни входа, ни 2FA, ни хранения токенов не было — это узкое место «рабочего варианта» (M1).

Решения, которые приняты здесь и которые обязан видеть ревьюер:

1. **`citext` для логина и e-mail** (§4.1). Расширение создаёт миграция, а не оператор: иначе
   `upgrade head` на чистой базе падает на первой же колонке. В `downgrade` расширение снимается
   последним — на момент удаления ни одна колонка на него не опирается.
2. **`bigserial` → `BIGINT GENERATED BY DEFAULT AS IDENTITY`** для `audit_log.id`. В PG16
   `serial` — это и есть identity (документированный эквивалент); явная форма видна в `\\d+` и
   не принимает посторонний id без `OVERRIDING SYSTEM VALUE`, что нужно восстановлению из дампа.
3. **Аппенд-only держат права, а не триггер.** `audit_log` получает запрет `UPDATE`/`DELETE` в
   `deploy/postgres/roles.sql` (следующий шаг T-009), а цепочка `hash_prev`/`hash` обязана найти
   разрыв, если запись правили правами владельца схемы (`AC-identity-04`). Триггер «запрети
   любую правку» противоречил бы самому критерию: изменённую вручную копию дампа нужно именно
   найти, а не сделать невозможной.
4. **Состояния — текстовые колонки с `CHECK`, а не PG-enum** — ровно как записано в §4.1
   (`role text check (…)`). Расширение домена потом не требует пересоздания колонки.
5. **`app_meta.schema_baseline` остаётся '0001'.** Ключ описывает базовую ревизию схемы, а не
   текущую: текущая — в `alembic_version`. CI-шаг «контрольная запись базовой ревизии» поэтому
   не правится.

Индексы заведены только там, где таблица растёт неограниченно (сессии, попытки 2FA, аудит) или
где индекс держит целость (одна активная привязка TOTP). Таблицы из нескольких строк
(`users`, `invitations`, `ip_allowlist`, `backup_codes`) индексов для выборок не имеют —
последовательное сканирование для них дешевле поддержки индекса, а путь проверки определят
T-105/T-110.

Проверки: `upgrade head → downgrade base → upgrade head` (CI job `migrations`), соответствие
моделям — `alembic check` там же, структурные проверки без базы —
`tests/contract/test_identity_schema.py`.
"""

