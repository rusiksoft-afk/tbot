def _audit_log() -> None:
    op.create_table(
        "audit_log",
        # `bigserial` из §4.1 в форме PG16: serial определён как identity. Явный identity
        # не принимает посторонний id без OVERRIDING SYSTEM VALUE — ровно то, что делает pg_dump.
        sa.Column("id", sa.BigInteger(), sa.Identity(always=False), nullable=False),
        sa.Column("at", _timestamptz(), server_default=sa.text("now()"), nullable=False),
        sa.Column("actor", sa.Uuid(), nullable=True),
        sa.Column("action", sa.Text(), nullable=False),
        sa.Column("entity", sa.Text(), nullable=True),
        sa.Column("entity_id", sa.Text(), nullable=True),
        sa.Column("details", postgresql.JSONB(), nullable=True),
        sa.Column("ip", postgresql.INET(), nullable=True),
        sa.Column("request_id", sa.Uuid(), nullable=True),
        sa.Column(
            "hash_prev",
            sa.Text(),
            nullable=True,
            comment="хэш предыдущей записи цепочки; NULL у первой записи",
        ),
        sa.Column(
            "hash",
            sa.Text(),
            nullable=False,
            comment="SHA-256 от канонического JSON записи + hash_prev",
        ),
        sa.PrimaryKeyConstraint("id", name=op.f("pk_audit_log")),
        sa.CheckConstraint(f"hash ~ '{_SHA256_HEX}'", name=op.f("ck_audit_log_hash_sha256")),
        sa.CheckConstraint(
            f"hash_prev IS NULL OR hash_prev ~ '{_SHA256_HEX}'",
            name=op.f("ck_audit_log_hash_prev_sha256"),
        ),
        sa.ForeignKeyConstraint(
            ["actor"], ["users.id"], name=op.f("fk_audit_log_actor_users"), ondelete="RESTRICT"
        ),
        comment=(
            "Append-only журнал (TZ §4.1, §8.7). Права приложения: SELECT + INSERT. "
            "Целостность цепочки — `make audit-verify` (T-109)."
        ),
    )
    op.create_index("ix_audit_log_at", "audit_log", ["at"])
    op.create_index("ix_audit_log_actor_at", "audit_log", ["actor", "at"])
    op.create_index("ix_audit_log_entity", "audit_log", ["entity", "entity_id"])
