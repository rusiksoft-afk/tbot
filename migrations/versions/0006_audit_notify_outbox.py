"""Журнал решений порога уведомлений `web_audit_outbox` (TZ §8.7, `T-116`, `ADR-028`).

Что появляется.

Одна таблица `web_audit_outbox` — переходник между журналом `audit_log` и каналом доставки
уведомлений администратору, который требует §8.7 вторым абзацем: «вход нового пользователя
(новый IP/устройство), расход резервного кода, изменение лимитов риска, отзыв токена,
включение kill-switch». Таблицы нет в перечне §4.1: §4.8 техзадания описывает очередь доставки
`notification_outbox` для вехи Telegram (`T-408`, §10.1), а здесь заводится ровно то, что
требуется §8.7 уже сейчас и что не обещает несуществующий канал. Обоснование имени и отличий —
`docs/adr/ADR-028` п. 1–2; контрактная карта обоснований — `_OPERATIONAL_TABLES` в
`tests/contract/test_identity_schema.py`.

Состав колонок и что каждая держит:

* `id` — `BIGINT GENERATED BY DEFAULT AS IDENTITY`, как у `audit_log` (§4.8 для
  `notification_outbox` задаёт `bigserial`; решение пишут разные процессы, и порядок вставок
  в нём важнее идентификатора);
* `at` — момент решения; снимается **один раз на событие** и передаётся из кода порога, а не
  берётся `now()` повторно: иначе решение «отсталось» от события, которое его породило
  (`ADR-025` п. 2 о той же зависимости для журнала);
* `ground` — повод §8.7, домен замкнут проверкой `ck_web_audit_outbox_ground` по пяти именам
  второго абзаца §8.7. Замкнутость домена — часть условия «остаток зафиксирован явно»:
  `risk.limits_changed`, `token.revoked` и `risk.kill_switch_changed` стоят в домене, хотя
  производителей у них нет (вехи M2/M3), и удалить их «как неиспользуемые» не даст база;
* `outcome` — `notify` (уведомить, когда канал появится) или `muted` (порог решил промолчать);
* `reason` — код причины, формат `ck_web_audit_outbox_reason_code`: словарь кодов живёт в
  `packages/identity/notify.py`, а свободный текст сделал бы перечень причин нечитаемым;
* `audit_id` → `audit_log(id) ON DELETE RESTRICT` — строка журнала, породившая решение. Адрес,
  субъект и `request_id` разбора читаются оттуда, второй копии этих значений в таблице нет;
* `user_id` → `users(id) ON DELETE RESTRICT` — учётная запись повода; `NULL` для оснований
  общего уровня (лимиты риска, kill-switch);
* `dedup_key` — ключ деидентификации повода («этот адрес/устройство уже уведомляли», «этот код
  уже истрачен»). Частичный уникальный индекс `ix_web_audit_outbox_dedup_key` — страж повторной
  рассылки: двух строк `notify` на одно основание и тот же объект не существует. Частичность
  нужна, что у `muted`-строк ключа нет намеренно (иначе порог молчал бы в одном экземпляре за
  всё время), а `NULL` в уникальном индексе участвовать не должен — тот же приём, что у
  `ix_audit_log_hash_prev_linked` в `0007`;
* `details` — целые счётчики, коды и идентификаторы; политика значений та же, что у журнала
  (`ADR-025` п. 2): значений учётных данных и адреса как значения там не бывает.

Индексы: `ix_web_audit_outbox_at` (разбор «что накопилось»),
`ix_web_audit_outbox_user_ground` (вопрос порога «когда по этому основанию уже уведомляли эту
запись»). Других нет: страница раздела администрирования читает последние строки по первичному
ключу (`id` растёт вместе с вставками).

Что сознательно не появляется.

- **Колонок очереди доставки** (`state` со «sent», `attempts`, `next_try_at`, `sent_at`, `error`,
  `channel`, `template`). Их берёт на себя §4.8 `notification_outbox` — таблица вехи Telegram,
  которой в этом срезе нет: канала доставки нет (`tgbot` не поднят и упирается в `T-714`,
  почтового транспорта в репозитории нет), а колонка `channel` с перечнем «telegram, email»
  означала бы обещание двух несуществующих каналов. Состояние здесь — **решение порога**, а не
  прогресс доставки, и append-only это закрепляет: транспорт дописывает собственные строки
  (§4.9 `telegram_messages_log`), а не правит эти (`ADR-028` п. 4).
- **`hash`/`hash_prev`**: цепочка одна — в `audit_log`. Вторая цепочка поверх того же множества
  событий создаёт расхождение, которое надо обнаруживать, а не плодить (`ADR-025` п. 3, `0007` о
  том же).
- **Триггеров и `CHECK` по списку причин**: причины — деталь реализации, их словарь держит код
  и контракт; домен в базе замкнут только для оснований и решений.
- **Права на `UPDATE`/`DELETE` приложению**: см. `ADR-028` п. 4; обязательный шаг — имя в
  `APPEND_ONLY_TABLES` (`packages/storage/base.py`), `ALTER TABLE … OWNER TO CURRENT_USER`
  (п. 2.1) и `GRANT SELECT, INSERT` + `REVOKE UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER`
  (п. 4) `deploy/postgres/roles.sql`, и **повторный идемпотентный запуск файла прав ролью
  `tbot`** на площадке (`AGENTS.md`, `ADR-022` п. 3). Признак обязательности шага — наличие
  `op.create_table` в `upgrade()`: в этой ревизии оно есть, в отличие от `0007`.
- **Отдельного права `CREATE` на схему**: роль приложения его отозвана (`ADR-018`), таблицу
  создаёт роль-мигратор и остаётся её владельцем; выдача по умолчанию из п. 5 файла прав делает
  таблицу видимой приложению сразу, а п. 2.1 и п. 4 возвращают владение и сужают права.

**Слот цепи и родство.** `0006` занимает `web_audit_outbox` для `T-116` — так решил заказчик
(`ADR-022` п. 3: «`0006` за `T-116` не двигается», резерв номера тянется ещё из `ADR-010`,
`ADR-013` и `ADR-019`). `0005` остаётся занятой `T-105` и остаётся пустой: файла нет и не
появится. Родство — `0004 → 0006 → 0007`: у `0007_…` правится `down_revision` на `"0006"`, то
есть ревизия журнала **перерождается** в цепи (она уже применена на площадке — см. ниже).
Гейт `tests/contract/test_identity_schema.py::test_цепочка_ревизий_линейна_и_без_развилок`
(`heads == ["0007"]`, состав `{0001…0004, 0006, 0007}`, пары родства `parents["0006"] == "0004"`
и `parents["0007"] == "0006"`) правится **в этом же коммите** (`ADR-022`, `ADR-026` п. 6):
отдельный «починить гейт» коммит означал бы красный CI и соблазн ослабить проверку.

Последствие для площадки (важно: это не рядовая «следующая ревизия»). На `tbot.rusiksoft.ru`
схема уже на `0007` (применена 2026-11-24, протокол
`docs/acceptance/prod-deploy-0007-audit-chain.md`), а `alembic_version` хранит **одну** строку —
голову. Перерождение меняет только `down_revision` внутри уже записанных файлов: для базы,
стоящей на `0007`, история остаётся линейной и непрерывной (`0001…0004 → 0006 → 0007` содержит
все пройденные ступени), поэтому `upgrade head` дойдёт до `0006` и создаст таблицу. Дамп перед
этим не снимается — решение заказчика (ask `128ac2e2-877d-45ec-8e6d-d8b63cab8f53`, вариант
`keep_no_dump`, прежняя формулировка — ask `0797afbe-c666-418c-87e2-40c76d528577`): новая
таблица пуста, `downgrade()` её снимает целиком, данных существующих объектов ревизия не
касается, откат приложения — прежние digest. Применение `0006` на живой ВМ — отдельный
деплой-срез с отдельной авторизацией; в этом срезе площадка не трогается.

Проверки: `upgrade head → downgrade base → upgrade head` (CI job `миграции`) плюс офлайн-DDL —
`tests/contract/test_identity_schema.py` (модели ↔ ревизия по колонкам, ограничениям и индексам;
обратная миграция обязана снять таблицу и оба индекса; домены `ground`/`outcome` закреплены в
DDL). Поведение на живой базе — шаг job'а «журнал решений порога уведомлений на живой базе»
(`tests/integration/test_audit_notify_db.py`): ссылочная целостность на `audit_log` с
`23503`, отказ стража деидентификации с `23505` и тот же отказ через `ON CONFLICT DO NOTHING`
без строки, отказ домена `ground`/`outcome`/формы причины, append-only права роли приложения
(`INSERT`+`SELECT` проходят, `UPDATE`/`DELETE`/`TRUNCATE` — `42501`) и то, что индекс-страж
держится и для роли-владельца схемы. Оффлайновые половинки —
`tests/unit/test_audit_notify.py` (пороги, ключи, коды причин) и
`tests/integration/test_audit_notify_web.py` (маршрут → решение → строка в памяти), контракт —
`tests/contract/test_audit_notify_contract.py`.
"""

