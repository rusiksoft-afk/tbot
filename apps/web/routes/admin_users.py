"""Раздел администрирования (§9.3 п. 6–10): пока только допуск, а не содержимое (`T-106`, `R6`).

Зачем в приложении появляется адрес, у которого нет страницы. Правило `AC-identity-01` называет
сценарий проверки буквальным адресом: «`operator` пытается открыть `/admin/users` → ответ `403` без
утечки списка пользователей (ни имён, ни счётчиков в error-шаблоне)». Пока такого адреса нет,
сценарий приёмки можно проверить только на тестовом щупе — как это делал `/probe-full` для матрицы
§8.2 в срезе `R3a` (щуп в производственном перечне маршрутов запрещён контрактной проверкой, и
жить он вечно не должен). Адрес, занятый сейчас, означает, что страницы `T-105` (пользователи,
приглашения, одобрение), `T-110` (IP-allowlist, kill-switch) и `T-603` (`/admin/limits`,
`/admin/instruments`) попадают за уже проверенный допуск, а не заводят свою охрану заново: типовая
дыра этого дизайна — не «плохая проверка роли», а «маршрут без проверки роли», и она закрывается
перечнем покрытия, а не количеством страниц.

Что честный ответ на этом адресе означает. Администратор видит `200` с прямым указанием, что
содержимое строит `T-105`: это тот же приём, что у корневой страницы каркаса `M0` в `apps/web/main.py`
(«веб-консоль будет добавлена на вехе M1»). Пустой страницы-заглушки с таблицей без данных тут быть
не должно: колонки «последний вход», «2FA» и «Telegram» (§9.3 п. 6) — данные чужих задач (`T-109`,
`T-103`, `T-409`), и выдумывать их источник сейчас означало бы решить их молча.

Чего здесь нет специально. Ни одной мутации: блокировка/разблокировка и сброс 2FA (§9.3 п. 6) —
это `T-105`/`T-103`, и завести их «заодно» означало бы написать обработчик, которому неоткуда взять
объект (списка пользователей тоже ещё нет). Ни `audit_log`-записей о попытках входа в раздел —
имена событий и цепочка хэшей относятся к `T-109` (перенос зафиксирован `ADR-009`); сейчас факт
отказа несёт только строка журнала `access_denied`.
"""

from __future__ import annotations

from typing import Final

from fastapi import APIRouter, Depends
from fastapi.responses import JSONResponse

from apps.web.security.authorization import require_admin_role

router = APIRouter()

#: Адрес раздела из карты §9.3 п. 6. Литерал живёт здесь, а не в реестре адресов
#: (`security/sessions.py`), потому что на него пока никто не ссылается: ссылок в разметке нет,
#: и в общий реестр адрес попадает вместе со страницей, которая его построит (`T-105`).
ADMIN_USERS_PATH: Final = "/admin/users"

#: Что видит администратор вместо списка. Формулировка обязана называть задачу, а не прятаться за
#: «в разработке»: человек, который открыл адрес по ссылке из карты страниц, вправе узнать, когда
#: страница появится и почему её нет сейчас.
ADMIN_USERS_NOTE: Final = (
    "адрес занят допуском раздела администратора; список пользователей, приглашения, одобрение, "
    "блокировка и сброс 2FA (§9.3 п. 6) строит задача T-105"
)


#: Охрана маршрута: живой сеанс полного входа (§8.2) и роль `admin` (§9.3 п. 6–10). Порядок
#: «шаг входа → роль → содержимое» держит `ADR-017` п. 3: отказ наступает до всякого обращения к
#: данным пользователей, поэтому ответ не может быть оракулом ни про список, ни про то, существует
#: ли вообще такой раздел.
#:
#: Зависимость объявлена у маршрута, а не параметром обработчика: содержимое ответа ни роль,
#: ни сеанс пока не читают, а названный и не использованный параметр был бы мёртвым кодом
#: (даже если он и приводит в действие охрану). `T-105`, которому понадобится учётная запись
#: администратора, возьмёт её параметром `principal: AdminSession`.
@router.get(
    ADMIN_USERS_PATH,
    response_class=JSONResponse,
    dependencies=[Depends(require_admin_role)],
)
def admin_users_page() -> JSONResponse:
    """Раздел администрирования: допуск есть, содержимого ещё нет.

    Ответ не содержит ни имён, ни счётчиков пользователей — не потому, что их нечего показать, а
    потому, что этот же ответ был бы утечкой, стоя он на отказной ветке. Отказная ветка держится
    отдельно и отвечает одним и тем же телом (`security/authorization.DENIAL_BODY`), а проверка
    `tests/integration/test_web_role_matrix.py` смотрит, что в нём нет ни логинов, ни числа
    учётных записей: `AC-identity-01` формулирует требование именно так.

    Роль в ответ не подставляется: человеку её показывает его собственный профиль (§9.3 п. 4), а
    здесь она ничего не объясняет.
    """
    return JSONResponse({"status": "not_built", "section": "admin", "note": ADMIN_USERS_NOTE})
