"""Раздел администрирования: чем кончился порог уведомлений (§9.3 п. 6–10, `T-116`, `ADR-028`).

Страница читает журнал решений `web_audit_outbox` (ревизия `0006`): по какому основанию §8.7
событие было спрошено, что решил порог (`уведомить` / `промолчать`), по какой причине и к какой
учётной записи это относится. Носитель — строка журнала, на которую ссылается `audit_id`: адрес,
субъект и `request_id` разбора читаются оттуда, второй копии этих значений в таблице нет
(`ADR-028` п. 2).

**Зачем страница нужна, если канала доставки нет.** Решение заказчика (ask
`128ac2e2-877d-45ec-8e6d-d8b63cab8f53`, вариант `outbox_admin_read`): пока `tgbot` не поднят и
упирается в `T-714`, а почтового транспорта в репозитории нет, исполненной половиной §8.7
считается зафиксированное решение порога, которое администратор может перечитать. Без чтения
таблица была бы книгой, которую никто не открывает: «уведомлений нет» и «порог промолчал»
неотличимы, а именно это различие и держит строка `muted` (`ADR-028` п. 4).

**Чего здесь сознательно нет.**

* **Надписи про отправку.** Шапка страницы прямо говорит, что канал не заведён: раздел не имеет
  права выглядеть как «уведомления уже приходят». Отдельная проверка следит, что в ответе нет
  обещаний «отправлено»/«доставлено» (`tests/contract/test_audit_notify_contract.py`).
* **Мутаций.** Страница читает: `GET`, форм нет, поэтому CSRF-токен в формах не участвует
  (`ADR-008`: токен нужен мутирующим методам). Повторный `GET` ничего не меняет и не может
  «повторно уведомить» — рассылки здесь нет вовсе. Вторая причина важнее первой: страница,
  которая умеет отправлять, превратила бы просмотр в действие и обошла бы лимиты §10.1.
* **Значения `details`.** В таблице — коды, идентификаторы и учётная запись повода. `details`
  (и `dedup_key`) наружу не выводятся: произвольный `jsonb` стал бы второй поверхностью утечки
  после журнала (§8.4), а `dedup_key` — материал стража повторной рассылки, а не сведения для
  администратора. Адрес и устройство остаются в строке журнала: их показывают страницы сеансов
  (§8.3), а не этот раздел.
* **Ссылок на сами строки журнала.** Их нет: отдельной страницы просмотра `audit_log` в репозитории
  нет, разбор делает внепроцессная команда `make audit-verify` (`ADR-025` п. 7), а ссылка вида
  «показать запись журнала» обязана была бы охранять доступ к журналу целиком (§8.4). В таблице
  стоит `id` строки — его администратор передаёт тому, кто запускает разбор.
* **Пагинации и фильтра.** Показываются последние `NOTIFY_PAGE_ROWS` строк: таблица append-only и
  растёт без участия приложения, поэтому «прочитать всё» означало бы выборку на порядок больше
  страницы (`read_notify_decisions` требует `limit`). Граница отсекает по `id`, то есть по самым
  свежим решениям; интервалы по времени разбирает команда вне процесса, а не страница.

Допуск — роль `admin` (§9.3 п. 6–10): без живого сеанса страница уходит на `/login`, с сеансом
человека без роли отвечает `403` телом `DENIAL_BODY` без имён ролей и без объяснения причины
(`ADR-017`, `AC-identity-01`). Человек на шаге `'password'` уходит на страницу кода, а не получает
`403`: его вход не завершён, и утверждать, что прав нет, значит сообщить лишнее о состоянии сеанса
(`ADR-017` п. 3). Маршрут стоит строкой в матрице допуска
`tests/integration/test_web_role_matrix.py`: новый адрес обязан появиться там, а не «дожить до
приёмки».
"""

from __future__ import annotations

from typing import Annotated, Final

from fastapi import APIRouter, Depends, Request
from fastapi.responses import HTMLResponse

from apps.web.security.authorization import require_admin_role
from apps.web.security.csrf import csrf_context
from apps.web.security.sessions import Principal, StoreDep
from packages.common.clock import to_msk
from packages.storage.audit_store import NotifyDecisionRow

router = APIRouter()

#: Адрес раздела. Литерал живёт здесь, а не в реестре `security/sessions.py`: на него ссылается
#: только этот раздел (переходов между адресами у него нет) — тот же порядок, что у адресов
#: раздела `routes/admin_users.py`.
ADMIN_NOTIFICATIONS_PATH: Final = "/admin/notifications"

#: Зависимость раздела: живой сеанс полного входа + роль `admin`. Мутационной версии нет
#: намеренно: страница не меняет ничего (`ADR-008`: токен нужен мутирующим методам).
AdminSession = Annotated[Principal, Depends(require_admin_role)]

#: Сколько решений показывает страница. Число — размер страницы, а не «всё»: таблица растёт без
#: участия приложения, и чтение без границы через год на площадке вытащило бы на порядок больше
#: строк, чем помещается. Остальное разбирает внепроцессная команда, а не раздел (§8.4).
NOTIFY_PAGE_ROWS: Final = 50

#: Постоянная шапка над списком. Она обязана сказать правду про канал: раздел показывает
#: решения порога, а не отправленные сообщения, и не имеет права создавать у администратора
#: ощущение, что уведомление уже ушло (`ADR-028` п. 8).
CHANNEL_NOTE: Final = (
    "Раздел показывает решения порога уведомлений (§8.7): по какому поводу событие было "
    "спрошено и что решил порог. Канал доставки не заведён: страница ничего не отправляет и не "
    "обещает, что сообщение уйдёт."
)

#: Пустой список — тоже состояние, а не «ошибки нет». Формулировка называет причины пустоты
#: обеими поводами, у которых есть производитель, иначе пустая таблица читается как «защита не
#: работает».
EMPTY_NOTE: Final = (
    "Решений порога ещё нет: ни одного входа с новым сочетанием адрес/устройство и ни одного "
    "расхода резервного кода."
)

#: Подписи вердиктов. Домен замкнут базой (`ck_web_audit_outbox_outcome`), и отображение обязано
#: быть полным: `KeyError` здесь лучше, чем молчаливая подпись неизвестного вердикта, потому что
#: третья колонка состояния означала бы расхождение с `ADR-028` п. 4.
OUTCOME_LABELS: Final[dict[str, str]] = {"notify": "уведомить", "muted": "промолчать"}

#: Подпись «у повода нет учётной записи»: основания общего уровня (лимиты риска, kill-switch)
#: учётной записи не имеют вовсе (`web_audit_outbox.user_id` допускает `NULL`).
NO_ACCOUNT_NOTE: Final = "— (основание общего уровня)"

#: Формат момента в таблице (§9.1: время показывается подписанным по часам площадки).
_MOMENT_FORMAT: Final = "%d.%m.%Y %H:%M"


def _row_of(decision: NotifyDecisionRow) -> dict[str, str]:
    """Строка таблицы: коды, вердикт и учётная запись повода.

    Значений `details` и ключа деидентификации здесь нет намеренно (§8.4): раздел показывает
    решения, а не материал стража повтора. Адрес и устройство не выводятся вторым местом: их
    носит строка журнала, на которую ссылается `audit_id` (`ADR-028` п. 2).
    """
    return {
        "at": to_msk(decision.at).strftime(_MOMENT_FORMAT),
        "ground": decision.ground,
        "outcome": OUTCOME_LABELS[decision.outcome],
        "reason": decision.reason,
        "account": decision.login if decision.login is not None else NO_ACCOUNT_NOTE,
        "audit_id": str(decision.audit_id),
    }


@router.get(ADMIN_NOTIFICATIONS_PATH, response_class=HTMLResponse)
def notifications_page(
    request: Request,
    principal: AdminSession,
    store: StoreDep,
) -> HTMLResponse:
    """Журнал решений порога — последние `NOTIFY_PAGE_ROWS` строк, newest-first.

    Чтение одно (`Store.notify_decisions` → `read_notify_decisions` общего слоя): ручная сверка и
    ежедневная проверка читают те же колонки, что и страница, иначе «раздел сказал „пусто“, а
    разбор нашёл строки» было бы расхождением двух путей чтения (тот же порядок, что у
    `read_audit_journal`, `ADR-025` п. 7).
    """
    decisions = store.notify_decisions(limit=NOTIFY_PAGE_ROWS)
    context = {
        "page_title": "Уведомления администратору",
        "section_note": CHANNEL_NOTE,
        "empty_note": EMPTY_NOTE,
        "rows": tuple(_row_of(decision) for decision in decisions),
        "limit": NOTIFY_PAGE_ROWS,
    } | csrf_context(principal)
    response: HTMLResponse = request.app.state.templates.TemplateResponse(
        request, "notifications.html", context
    )
    return response
