"""Адрес клиента: единственная точка разбора `X-Forwarded-For` (TZ §8.3, `docs/adr/ADR-007`).

Зачем отдельный модуль: адрес нужен трём местам — записи сессии (`sessions.ip`, §8.3 показывает её
в списке устройств), окну перебора `ip_ban` и лимитам частоты запросов (`login_ip`, `totp_ip`). Если
бы каждый считал адрес сам, они разошлись бы: «заблокировали» один адрес, а «смотрим» другой, и
бан из §8.2 не срабатывал бы вообще.

**Берётся правый элемент списка, а не левый.** Это не придирка к стилю: Caddy по умолчанию не
перезаписывает `X-Forwarded-For`, а **дописывает** адрес соединения в конец цепочки. Значит левый
элемент — то, что прислал клиент (или прошлый прокси), и он подделываем; правый — то, что увидел
наш Caddy. Наивный «левый элемент» превращает лимит «10 запросов в минуту на IP» в лимит на
вымышленный адрес: подставил заголовок — и счётчик чистый.

Обратная сторона та же, что в ADR-007: если `web` когда-нибудь начнёт принимать соединения мимо
Caddy, правый элемент станет адресом того, кто прислал запрос, и подделка снова станет возможной.
Проверка «`web` наружу не публикуется» входит в контрактные тесты деплой-артефактов и сниматься не
должна.

**Тем же модулем разбирается и `X-Forwarded-Proto` (`ADR-024`, `T-117`).** Правило выбора то же —
правый элемент, то есть тот, что поставил наш прокси; `deploy/caddy/Caddyfile` ставит
`X-Forwarded-Proto {scheme}` через `header_up`, поэтому значение от клиента перезаписывается ещё до
того, как дойдёт до приложения. Отдельная точка нужна потому, что сравнение источника в `csrf.py`
строит схему из ASGI-области, а её uvicorn правит только для пира из `forwarded_allow_ips` — на
боевом стенде пир не входит в этот список, и схема остаётся `http`.

**Значение возвращается каноническим текстом.** Колонка `sessions.ip` — `INET`, а
`rate_buckets.bucket_key` ограничена длиной 1..64 символов: значение, которое не является адресом,
должно быть отброшено до похода в базу, иначе отказ даст схема, а не приложение, и отличить
подделку от порчи данных будет нельзя.
"""

from __future__ import annotations

import ipaddress
from typing import Final

from fastapi import Request

#: Имя заголовка, которое проставляет наш обратный прокси (TZ §8.3, ADR-007).
FORWARDED_FOR_HEADER: Final = "X-Forwarded-For"

#: Схема наружного запроса: её проставляет тот же прокси (`ADR-024`).
FORWARDED_PROTO_HEADER: Final = "X-Forwarded-Proto"

#: Известные схемы; вебсокетная пара приводуется к http/https, потому что сравнивается с `Origin`.
_PROTO_SCHEMES: Final = {"http": "http", "https": "https", "ws": "http", "wss": "https"}


def forwarded_scheme(request: Request) -> str | None:
    """Схема наружного запроса либо `None`, если заголовка нет или значение неразборимо.

    Порядок: правый элемент `X-Forwarded-Proto` — его дописал наш прокси; левые элементы прислал
    клиент, и они подделываемы (то же правило, что у адреса выше). Регистр не значим. Неизвестное
    значение даёт `None`, а не отказ: иначе испорченный заголовок ломал бы легитимный вход,
    и отличить подделку от порчи было бы нельзя — вызывающий остаётся на честной ASGI-схеме.
    """
    header = request.headers.get(FORWARDED_PROTO_HEADER)
    if not header:
        return None
    parts = [part.strip().lower() for part in header.split(",") if part.strip()]
    if not parts:
        return None
    return _PROTO_SCHEMES.get(parts[-1])


def client_address(request: Request) -> str | None:
    """Канонический текст адреса клиента либо `None`, если адреса нет.

    Порядок: правый элемент `X-Forwarded-For`, который добавил наш прокси; если заголовка нет или
    правые элементы не разбираются — адрес TCP-соединения. Для боевого стенда второе означает
    адрес Caddy, и это хуже, чем честный `None`: лимит по «адресу Caddy» сливается в один общий
    лимит на прокси (ADR-007), поэтому значение не подставляется, а остаётся пустым.
    """
    header = request.headers.get(FORWARDED_FOR_HEADER)
    if header:
        for candidate in reversed([part.strip() for part in header.split(",") if part.strip()]):
            canonical = _canonical(candidate)
            if canonical is not None:
                return canonical
    if request.client is None:
        return None
    return _canonical(request.client.host)


def _canonical(value: str) -> str | None:
    """Каноническая форма адреса (`compressed`) либо `None`, если это не адрес.

    `compressed` выбран не ради красоты: IPv6 допускает несколько текстов одного адреса
    (`2001:db8::1` и `2001:0DB8:0000:0000:0000:0000:0000:0001`), а ключ счётчика — текст. Без
    нормализации переборщик получил бы столько независимых счётчиков, сколько написаний адреса он
    придумает, и окно `ip_ban` из §8.2 перестал бы считать неудачи вместе.
    """
    try:
        return ipaddress.ip_address(value).compressed
    except ValueError:
        return None
