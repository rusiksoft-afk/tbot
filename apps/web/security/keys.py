"""Файл ключей KEK в процессе `web`: где лежит, как читается и что показывать при отказе.

Материала ключей этот модуль не производит и не хранит: он только открывает файл, который описан
`ADR-014` п. 5 и `docs/runbook/kek-keys.md` (`/etc/tbot/keys/kek.json`, права `640 root:gid 10001`,
создаётся инструментом `deploy/vps/keys_setup.py`), и передаёт его в
`packages/common/crypto.py`. Проверка прав и формата живёт внутри `load_key_ring` — здесь нет и не
может быть «своей» политики прав, иначе два места разошлись бы, а виноватым оказался бы файл.

Два правила, которые держит этот файл:

* **набор ключей читается на каждый запрос, а не один раз на процесс.** Казалось бы, лишнее
  обращение к диску; на деле это единственный способ, чтобы проверка прав (`kek_file_mode_error`) и
  проверка версии ключа выполнялись в момент использования. Кэш в памяти процесса пережил бы
  `--remed`, перезапись файла и смену активной версии, а при следующем `docker restart` всё равно
  пропал бы — то есть дал бы ровно то поведение, которое труднее всего объяснить оператору.
  Стенд — консоль с несколькими пользователями в минуту, стоимость незначима.
* **отказ не превращается в «неверный код».** Файл ключей отсутствует или повреждён — это
  неисправность площадки, а не подозрение на пользователя: ответ `503` с объяснением, что
  двухфакторная проверка временно недоступна, а не `401`, не `403` и не редирект на страницу входа.
  Иначе сломанный файл ключей выглядел бы как «вы неправильно ввели код», а счётчик неудач (§8.2)
  начал бы блокировать учётные записи из-за операционной проблемы.

Пользователю показывается фиксированный текст без деталей; причина (путь, режим файла, признак
разбора) уходит в лог процесса: `ADR-014` прямо перечисляет признаки, и в них нет ни ключа, ни
секрета привязки, но есть внутренняя подробность площадки, которой делать нечего в HTML-ответе.
"""

from __future__ import annotations

from typing import Final

from fastapi import Request

from packages.common.crypto import CryptoError, KeyRing, load_key_ring

#: Имя атрибута `app.state`, в котором процесс держит путь файла ключей. Значение кладёт
#: `create_app` из настроек (`Settings.kek_file`), а интеграционные проверки подменяют его
#: временным файлом: путь — единственное, что маршруту нужно от конфигурации.
KEK_FILE_STATE: Final = "kek_file"

#: Что видит человек на странице, когда файл ключей недоступен. Фиксированная формулировка: в ней
#: нет ни пути, ни режима файла, ни текста причины — только состояние и действие («скажите
#: администратору»), потому что чинит это оператор, а не пользователь.
TWO_FACTOR_UNAVAILABLE_DETAIL: Final = (
    "Двухфакторная проверка временно недоступна: файл ключей шифрования не найден или не годится. "
    "Вход по паролю работает, доступ в консоль закрыт. Сообщите администратору: состояние описано "
    "в `docs/runbook/kek-keys.md`."
)


class TwoFactorUnavailableError(RuntimeError):
    """Двухфакторная операция невозможна: файл ключей недоступен или не разобран.

    Текст исключения — причина для оператора (её печатает лог), а не для ответа: наружу идёт
    `TWO_FACTOR_UNAVAILABLE_DETAIL`. Обработчик ответа живёт в `create_app`: у отказа один код
    (`503`) и одна разметка, и давать каждой странице свой способ объяснить это состояние нельзя.
    """


def request_key_ring(request: Request) -> KeyRing:
    """Набор ключей для текущего запроса; иначе `TwoFactorUnavailableError`.

    Порядок внутри `load_key_ring` — «нет файла → права → чтение → разбор», и текст отказа
    отвечает на вопрос «что делать»: доставить файл, поправить права или починить JSON
    (`docs/runbook/kek-keys.md §Диагностика`). Здесь порядок только дополняется случаем «процесс
    запущен без пути файла ключей» — это конфигурационная поломка сборки, а не площадки.
    """
    path = getattr(request.app.state, KEK_FILE_STATE, None)
    if path is None:
        raise TwoFactorUnavailableError(
            f"путь файла ключей не настроен (в состоянии процесса нет {KEK_FILE_STATE!r})"
        )
    try:
        ring = load_key_ring(path)
    except CryptoError as exc:
        raise TwoFactorUnavailableError(str(exc)) from exc
    return ring
