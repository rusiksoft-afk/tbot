#: Фиксированный текст отказа. В нём нет ни требуемой роли, ни имени маршрута, ни счётчиков:
#: `AC-identity-01` требует `403` без утечки списка пользователей, а матрица §8.8 — «`operator` к
#: чужим данным → 403/404 без утечки». Класс отказа («недостаточно прав») человеку назвать нужно:
#: без него отказ выглядел бы сбоем, а §9 требует внятных состояний. Подробности — в логе процесса
#: и в `audit_log` (`auth.access_denied`, §8.7): посетителю различие причин недоступно намеренно,
#: разбор делает журнал (`ADR-009` п. 4, запись — срез `R2` задачи `T-109`).
DENIAL_DETAIL: Final = "недостаточно прав для этого действия"


def _record_denial(
    store: StoreDep, principal: Principal, *, reason: str, required: str | None = None
) -> None:
    """Строка `auth.access_denied` (§8.7, `ADR-009` п. 4, `ADR-017` п. 4).

    Пишется на той же точке, где решена причина отказа, а не в обработчике `403`: к моменту, когда
    `apps/web/main.py` получает `AccessDeniedError`, слой доступа запроса уже закрыт (FastAPI
    выходит из зависимостей запроса раньше, чем исключение доходит до обработчика исключений), а
    отдельное соединение ради одной строки журнала означало бы второй путь добавления в цепочку —
    ровно то, чего `ADR-025` п. 6 не допускает.

    `actor` — учётная запись, чей сеанс принёс запрос: §8.7 требует субъекта, а отказа без субъекта
    в этом слое не бывает (до аутентификации работают отказы частоты и CSRF, у них `actor` пустой).
    `required` в `details` нужен разбору: без требуемой роли «роль ниже требуемой» неотличима от
    «человек залез не туда». `DENIAL_BODY` оба значения посетителю не выдаёт — различие живёт
    только в журнале.

    Каждая причина записывается ровно один раз: `no_account` — забота `load_account`, роли —
    забота `enforce_role`, и второй строки на ту же причину `enforce_role` не плодит.
    """
    details: dict[str, str] = {"reason": reason}
    if required is not None:
        details["required"] = required
    store.append_audit(
        action="auth.access_denied",
        at=utc_now(),
        actor=principal.session.user_id,
        entity="user",
        entity_id=principal.session.user_id,
        details=details,
        commit_now=True,
    )


#: Тело ответа отказа — одно на все причины (`DENIAL_REASONS`): роль ниже требуемой, роль вне
#: закрытого набора, учётной записи сеанса нет. Различать их ответом означало бы сообщить
#: посетителю состояние данных, а не только факт отказа.
DENIAL_BODY: Final[dict[str, str]] = {"status": "forbidden", "detail": DENIAL_DETAIL}


#: Один ответ на «такого идентификатора нет», «идентификатор кривой» и «объект уже
#: закрыт» (§8.8: «чужие данные → 403/404 без утечки»). Различие этих случаев ответом не выдаётся
#: намеренно: иначе раздел стал бы способом проверять, какие идентификаторы
#: существуют. Текст отличается от `GONE_DETAIL` раздела сеансов (§8.8 просто не объекта),
#: но форма ответа одина: «объекта нет» — `404`, а не безликий `403`, потому что
#: роль проверяет зависимость до тела обработчика: два разных смысла,
#: смешанные в одном коде, ломают и матрицу допуска, и правило «не быть
#: оракулом».
OBJECT_GONE_DETAIL: Final = "объекта с таким идентификатором нет"

OBJECT_GONE_BODY: Final[dict[str, str]] = {
    "status": "not_found",
    "detail": OBJECT_GONE_DETAIL,
}


def object_gone_response() -> JSONResponse:
    """`404` без подробностей: чужой, кривой и несуществующий `id` — один ответ.

    Тот приём, что держит `_session_gone` в `routes/sessions.py`, и той же формы: смысл правила
    «один ответ на несколько случаев» в слое один, а текст описывает свой объект.
    Ответ не содержит ни причины, ни того, что именно было запрошено: по телу
    нельзя отличить учётную запись от приглашения — поэтому тело одно
    на объекты всего раздела.
    """
    return JSONResponse(OBJECT_GONE_BODY, status_code=404)


def role_denial_response() -> JSONResponse:
    """Ответ `403` для любого отказа допуска: один ответ на все причины и все маршруты.

    Страницы «вам отказано, потому что вы не администратор» нет сознательно: она была бы картой
    границ доступа (§8.7 «ответ без лика и причины»). Объяснение состояния учётной записи —
    другая поверхность, и оно существует: `handle_account_state`. Граница проходит по тому, чьи
    данные оказались под вопросом. Отказ по роли касается чужих объектов и поэтому обязан
    оставаться безликим; объяснение состояния касается собственной учётной записи человека и
    поэтому содержит текст. `/session-expired` объясняет третье — сеанс, а не права и не состояние
    записи. Тело отказа по роли не зависит ни от маршрута, ни от причины, поэтому для посетителя
    без прав множество ответов «такая страница есть / такой страницы нет» схлопывается в одно
    значение.
    """
    return JSONResponse(DENIAL_BODY, status_code=403)


def load_account(store: StoreDep, principal: Principal) -> User:
    """Строка учётной записи сеанса; иначе — тот же отказ, что и у нехватки роли.

    Нужна обработчикам, которым сама учётная запись нужна по делу (сравнить текущий пароль,
    §9.3 п. 4 показать роль и e-mail). Тип возвращаемого значения — `User`, а не `User | None`:
    состояние «строчки нет» здесь уже превращено в отказ, поэтому обработчику нельзя получить
    `None` и решить его по-своему. На одной SQLAlchemy-сессии запроса второй вызов читает тот же
    объект из identity map, так что «охрана видела одно, обработчик — другое» не возникает.
    """
    account = store.user_of_id(principal.session.user_id)
    if account is None:
        _record_denial(store, principal, reason=DENIAL_NO_ACCOUNT)
        raise AccessDeniedError(DENIAL_NO_ACCOUNT)
    return account


def enforce_role(store: StoreDep, principal: Principal, *, required: str) -> str:
    """Проверить роль учётной записи сеанса; иначе — `AccessDeniedError`.

    Отдельная функция, а не тело каждой зависимости: у мутаций цепочка своя (токен → счётчик →
    шаг `'full'`, см. `require_full_mutation` в `routes/sessions.py`), и роль вставляется в неё
    последним шагом. Второй копии проверок сеанса здесь быть не должно — два обращения к строке
    сеанса могли бы увидеть разное состояние (отзыв другим входом между ними).

    Роль читается из базы на каждый охраняемый запрос — осознанная цена (`ADR-017` п. 7): смена
    роли администратором обязана применяться немедленно, по той же причине, по которой §8.3 требует
    немедленной видимости отзыва сеанса. Кэш роли в памяти процесса дал бы окно, в котором
    уже снятый с прав человек оставался бы администратором до перезапуска `web`.
    """
    try:
        account = load_account(store, principal)
        role = ensure_account_role(account, required=required)
    except AccessDeniedError as exc:
        # `DENIAL_NO_ACCOUNT` записан в `load_account`: вторая строка на ту же причину удвоила бы
        # событие и соврала бы при разборе о числе отказов.
        if exc.reason != DENIAL_NO_ACCOUNT:
            _record_denial(store, principal, reason=exc.reason, required=required)
        raise
    # Состояние учётной записи проверяется **после** роли и до любого обращения к объекту
    # (`ADR-020` п. 6, `ADR-017` п. 3). Порядок принципиален: отказ по роли обязан оставаться
    # безликим (`DENIAL_BODY`, `AC-identity-01`), а объяснение состояния относится к самому
    # человеку и его учётной записи, а не к чужим данным. Роль при этом читается из репозитория
    # на каждый запрос — ровно так же, как шаг входа и отзыв сеанса: блокировка и архивирование
    # обязаны применяться немедленно, а не после перезапуска `web`.
    ensure_console_access(account)
    return role


def require_console_role(request: Request, store: StoreDep) -> Principal:
    """GET раздела «Профиль и безопасность»: живой сеанс полного входа и любая из трёх ролей.

    Уровень — `CONSOLE_TIER` (§9.3 п. 4–5: «любая роль»). Это не «проверки нет»: проверка обязана
    отвергнуть значение роли вне закрытого набора (§1.1 «ровно три роли») и сеанс без учётной
    записи. Смысл уровня в том, что роли он не различает, — и поэтому маршрут не может про него
    «забыть»: зависимость либо стоит в сигнатуре, либо её отсутствие ловит контрактная проверка
    покрытия (`ADR-017` п. 3).
    """
    principal = require_full_session(request, store)
    enforce_role(store, principal, required=CONSOLE_TIER)
    return principal


def require_admin_role(request: Request, store: StoreDep) -> Principal:
    """GET раздела «Администрирование» (§9.3 п. 6–10): требуется роль `admin`.

    Порядок «сначала полный вход, потом роль» выбран по той же причине, что у остальных охран:
    человек на шаге `'password'` обязан уйти на страницу кода (§8.2), а не получить `403`: его вход
    не завершён, и утверждать, что у него нет прав, — значит сообщить лишнее о состоянии сеанса.
    """
    principal = require_full_session(request, store)
    enforce_role(store, principal, required=ADMIN_TIER)
    return principal


def handle_access_denied(request: Request, exc: AccessDeniedError) -> JSONResponse:
    """Обработчик отказа допуска для фабрики приложения.

    `AccessDeniedError` поднимается из зависимостей, то есть до тела обработчика: своего `try` ни у
    одного маршрута нет, поэтому «забыли перехватить» в этом дизайне невозможно — ответ даёт
    обработчик исключения, а заголовки §8.3 на него навешивает middleware (тот же порядок, что у
    отказов CSRF и `413`).

    В лог уходят путь запроса и причина (`reason` из закрытого `DENIAL_REASONS`) — этого достаточно
    оператору, чтобы отличить попытку залезть в раздел администратора от сеанса, у которого пропала
    строка учётной записи. В ответ не уходит ничего из этого (§8.4).
    """
    log.warning("access_denied", path=request.url.path, reason=exc.reason)
    return role_denial_response()


# ─── объяснение закрытого доступа по состоянию учётной записи ─────────────────────────────


#: Объяснения кодов состояния (§9.3 «объяснение состояния», `ADR-020` п. 6). Набор кодов закрыт
#: `packages.identity.users.ACCESS_CODES`, полноту набора проверяет
#: `tests/integration/test_web_account_states_page.py`.
#:
#: Тексты не содержат имени администратора и не обещают срока: §9.3 требует, чтобы объяснение
#: состояния было, а §8.11 не требует обещать, когда одобрение придёт. Отличаются ли эти тексты
#: от безликого `DENIAL_BODY`? Да, и это разные поверхности: отказ по роли (§8.7 «ответ без лика и
#: причины») получает человек, не добравшийся до чужих данных; объяснение состояния получает
#: владелец собственной учётной записи, которой вход закрыт. Смешивать их нельзя: безликий `404`
#: нужен ровно там, где иначе проставился бы лик (`403`, `DENIAL_BODY`).
#:
#: `outside_domain` здесь тоже есть, хотя живой CHECK §4.1 таких значений не пропускает: колонка
#: может быть испорчена правкой мимо приложения, и «молча не пускать» без объяснения было бы
#: хуже, чем сказать человеку, что это повреждение данных, а не его ошибка.
ACCOUNT_STATE_EXPLANATIONS: Final[Mapping[str, str]] = MappingProxyType(
    {
        "invited": (
            "Учётная запись создана приглашением и ещё не прошла первый вход. Страницы консоли "
            "откроются после второго фактора и одобрения администратором."
        ),
        "awaiting_approval": (
            "Учётная запись ждёт одобрения администратора (§1.2: «приглашение без одобрения не "
            "даёт ни сессии, ни прав»). Страницы консоли откроются после одобрения."
        ),
        "suspended": (
            "Учётная запись заблокирована администратором. Разблокировать может администратор; "
            "вход и страницы консоли закрыты до разблокировки."
        ),
        "archived": (
            "Учётная запись архивирована. Архивирование — конец жизни учётной записи: обратный "
            "переход не предусмотрен, доступ открыт не будет."
        ),
        "no_account": (
            "Учётной записи нет: сеанс указывает на удалённую учётную запись. Нужно войти заново "
            "или обратиться к администратору."
        ),
        "outside_domain": (
            "Состояние учётной записи вне описанного набора §4.1. Это повреждение данных, а не "
            "ваша ошибка: вход закрыт до разбора администратором."
        ),
    }
)


def handle_account_state(request: Request, exc: AccountAccessError) -> HTMLResponse:
    """Страница «доступ закрыт состоянием учётной записи» (§9.3 «объяснение состояния»).

    Отдельный ответ, а не `role_denial_response()`: безликий `403` защищает от простановки ликов
    чужих учётных записей, а здесь человеку объясняют состояние **его** записи. Разница видна и в
    коде ответа: это `200` со внятной страницей, а не `403` с пустым телом.

    В лог уходят путь и код из закрытого набора `ACCESS_CODES` — оператору важно отличить
    «заблокировали» от «забыли одобрить»; в ответ код не уходит вовсе, уходит только текст:
    человек не обязан разбирать внутреннюю нумерацию состояний (§9.3).
    """
    log.info("account_state_denial", path=request.url.path, code=exc.code)
    explanation = (
        ACCOUNT_STATE_EXPLANATIONS.get(exc.code) or ACCOUNT_STATE_EXPLANATIONS["outside_domain"]
    )
    # `csrf_token` пустой: формы на странице нет, а значение meta в `base.html` обязано
    # существовать (`StrictUndefined`). Значение даёт `csrf_context(None)` — тот же источник,
    # что и у всех охраняемых страниц: «токена нет» определяется в одном месте, а не копией
    # литерала в обработчике.
    context: dict[str, object] = {
        **csrf_context(None),
        "page_title": "Доступ закрыт",
        "explanation": explanation,
        "login_url": LOGIN_PATH,
    }
    # Аннотация обязательна: `app.state` типизирован как `Any`, и без неё mypy возвращал бы `Any`
    # (тот же приём, что в `routes/login.py` и `routes/sessions.py`).
    response: HTMLResponse = request.app.state.templates.TemplateResponse(
        request, "account_state.html", context
    )
    return response
