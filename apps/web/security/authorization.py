"""Допуск по роли на уровне сервиса: зависимости маршрутов и единый ответ отказа (TZ §1.1, `T-106`).

Правило `REQ-identity-01` «проверка роли — на уровне сервиса, а не шаблона» реализовано здесь одной
парой: зависимость, которая решает, и обработчик исключения, который отвечает. Шаблон роли не видит
ни в каком виде: ни `if role == "admin"` в разметке, ни «скрыть кнопку для `operator`». Причина не в
стиле: скрытая кнопка оставляет маршрут открытым, а проверка в разметке расходится с маршрутом при
первой же правке, и поймать это можно только руками.

Уровни допуска взяты из карты страниц §9.3, а не из формулировки §1.1 «ни одной кнопки изменения»:
карта держит раздел «Профиль и безопасность (любая роль)» (п. 4–5) и раздел
«Администрирование (`admin`)» (п. 6–10). Различие принципиально для `viewer`: смена собственного
пароля и отзыв собственных сеансов остаются ему доступны, потому что это не кнопки изменения
продукта (стратегии, счета, заявки), а обслуживание собственной учётной записи. Обоснование и
принятые следствия — `docs/adr/ADR-017` п. 5.

```
GET-маршрут:   живой сеанс → шаг `'full'` → роль                  (`require_console_role`, …)
мутация:       токен CSRF → счётчик частоты → шаг `'full'` → роль   (`enforce_role` в цепочке)
```

Порядок зафиксирован и он не «как получилось» (`ADR-017` п. 3):

1. токен и счётчик — раньше роли, иначе запрос без токена расходовал бы лимит пользователя и
   обращался к базе (`ADR-008`, `ADR-007`);
2. роль — раньше любого обращения к объекту, ради которого маршрут существует. Это и есть ответ на
   «`403` без утечки»: отказ, вынесенный **до** поиска объекта, физически не может быть оракулом
   существования объекта. Тот же принцип, что `ADR-016` п. 5 применяет к резервным кодам («чужой»,
   «потраченный» и «никогда не выпущенный» отвечают одинаково).

Чего здесь нет. Правила перехода состояний (§1.2) здесь не решаются: `enforce_role` только
спрашивает у домена `ensure_console_access`, открыт ли вход состоянием, — и обязана это делать,
иначе блокировка или архивирование переживали бы перезапуск `web`. Решение о состоянии принимает
`packages/identity/users.py`, слой допуска его вызывает (`ADR-017` п. 10, `ADR-020` п. 6).
Порядок внутри зависимости фиксированный: сначала роль, потом состояние, — отказ по роли обязан
оставаться безликим (§8.7), а объяснение состояния относится к собственной учётной записи
человека и чужих данных не касается (`handle_account_state`). Отдельной проверки «роль напечатана
в профиле» тоже нет: печать роли §9.3 п. 4 требует показать человеку, а не решить; решение
принимает зависимость.
"""

