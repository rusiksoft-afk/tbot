"""QR-картинка привязки TOTP: матрица модулей превращается в геометрию ответа (`T-103`, `R4d`).

Модуль маленький нарочно. Всё, что в нём есть ценного, — это отказ от двух способов «просто
показать QR», каждый из которых ломает уже принятые правила, и одна проверка целостности.

**Почему картинка встроена в ответ, а не отдаётся ссылкой `<img>`.**

1. `data:image/...;base64,` потребовал бы `img-src 'self' data:`. CSP берётся из ТЗ §8.3 и
   живёт побайтово в двух артефактах (`apps/web/security/headers.py` и `Caddyfile`), а
   `tests/integration/test_compose_prod_contract.py` прямо запрещает `data:` в `img-src`.
   Ослабление политики ради одной картинки — это решение заказчика, а не оформителя.
2. Отдельный адрес вида `GET /mfa-enroll/qr` означал бы **вторую точку вывода секрета**
   (`ADR-015` п. 6): такой адрес виден в исходном коде страницы,
   ответ кешируется браузером и оседает в access-логе Caddy. Кроме того, картинку пришлось бы собирать повторным расшифровыванием
   `secret_enc`, а это ровно тот путь, который `ADR-014` п. 6 и `ADR-015` п. 6 запрещают.
   Поэтому QR живёт ровно в том одном ответе, где показан секрет, и нигде больше.

**Почему `segno` даёт только матрицу, а прямоугольники рисует этот модуль.** Кодирование QR —
сотни строк алгоритма (полиномы ГФ(256), маски, выравнивающие паттерны), и собственный
кодировщик отклонён `ADR-013` п. 10: его некому аудировать. Здесь остаётся только геометрия —
пробежать по матрице и склеить тёмные прогоны в один `path`. Причина ровно та же, что и у
`ADR-009` про разбор формы: `segno` умеет отдавать готовый SVG, но вставить его в шаблон можно
только через `|safe`, а `tests/contract/test_web_security_contract.py` запрещает `|safe` во
всех шаблонах слоя (§8.8: автоэкранирование обязательное). Строка путей проходит через
обычный `{{ qr_path }}` и экранируется, а её алфавит проверяется здесь же — в разметку не
может попасть ничего, кроме букв команд, цифр и пробелов.

**Что бывает, если картинка не собралась.** Страница привязки остаётся рабочей: секрет и
инструкция для ручного ввода показываются всегда, потому что ТЗ §8.2 требует «QR **и** ручной
ввод секрета», а не вместо. Отказ кодировщика — это отсутствующая картинка и строка в логе без
полезной нагрузки, а не `500` и не «привязка не началась».
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Final

import segno

#: Уровень исправления ошибок QR. `M` (~15 %) — обычная рекомендация для `otpauth://`: картинка
#: сканируется с экрана монитора телефоном, и запас на блик/небольшое повреждение нужен, а
#: максимальный `H` стоит ещё одного-двух версий размера. Значение держится константой, потому
#: что номер версии (и размер картинки) от него зависит напрямую.
QR_ERROR_LEVEL: Final = "M"

#: Ширина «спокойной зоны» в модулях — светлая рамка вокруг квадрата. Четыре — минимум по
#: ISO/IEC 18004, и ровно столько по умолчанию добавляет `segno` (`QRCode.default_border_size`),
#: поэтому здесь он назван константой, а не унаследован из библиотеки молча: светлый фон этого
#: квадрата дорисует шаблон, и обе половины должны сходиться. Меньше — часть генераторов
#: отказывается читать картинку, и человек видит «код не подходит», не понимая почему.
QR_QUIET_ZONE_MODULES: Final = 4

#: Предельная длина полезной нагрузки. Служебная часть `otpauth://`-ссылки (~82 знака: метка,
#: `secret=`, `issuer`, `algorithm`, `digits`, `period`) и секрет (32 знака base32,
#: `TOTP_SECRET_BYTES` = 20) почти не зависят от учётной записи, поэтому почти вся граница
#: приходится на логин, а длину логина схема не ограничивает (`citext` без CHECK — проверка
#: формата появится вместе с ролями и приглашениями, `T-105`/`T-106`).
#: Граница выбрана по размеру картинки, а не по пределу ёмкости QR. Замер 2026-11-22
#: (`segno` 1.6.6, уровень `M`): 114 знаков — реальная привязка с логином из восьми знаков →
#: версия 7, 45 модулей; 256 знаков → версия 14, 73 модуля. Дальше картинка перестаёт
#: умещаться в видоискатель телефона с разумного расстояния, и вместо неё остаётся ручной
#: ключ (§8.2: QR и ручной ввод, а не вместо).
#: Верхняя граница ёмкости QR при этом не используется вовсе: `segno` при перегрузке ёмкости
#: бросает своё исключение, и его текст переводится здесь же.
QR_MAX_PAYLOAD_CHARS: Final = 256

#: Алфавит строки путей: абсолютные команды `M`/`H`/`V`/`Z`, целые
#: координаты и пробелы. Минус в набор не входит намеренно: прямоугольник
#: замыкается обратной абсолютной же командой, поэтому в строке нет ни
#: отрицательных чисел, ни точек, ни экспонент. Ни `<`, ни `"`, ни `&` сюда попасть
#: не могут, поэтому значение безопасно проходит автоэкранирование Jinja2 и
#: остаётся геометрией.
_PATH_ALPHABET: Final = re.compile(r"[MHVZ0-9 ]+")


class QrBuildError(ValueError):
    """Картинку собрать нельзя: нагрузка пуста, слишком длинная или не помещается в QR.

    Сообщение никогда не содержит полезную нагрузку: в `otpauth://`-ссылке лежит секрет привязки,
    а строка исключения уходит в лог (§8.4).
    """


@dataclass(frozen=True)
class QrGraphic:
    """Готовая к вставке картинка: сторона квадрата в модулях и строка путей.

    `path_d` — только геометрия тёмных модулей; светлый фон и размеры вывода задаёт шаблон.
    Поле не содержит полезную нагрузку и не может её содержать: сборщик не сохраняет URI.
    """

    modules: int
    path_d: str


def qr_graphic(payload: str) -> QrGraphic:
    """Полезная нагрузка → картинка. Сейчас это `otpauth://`-ссылка привязки (§8.2, `R4d`).

    Кодирование делает `segno` (уровень исправления фиксирован константой), маски он выбирает сам
    детерминированно: одинаковая нагрузка даёт одинаковую картинку, поэтому проверка геометрии
    не «плывёт» между прогонами.

    Порядок проверок значим: пустая и слишком длинная нагрузка отклоняются **до** обращения к
    кодировщику. Без границы на длине `segno` молча выдал бы квадрат на 100+ модулей, а страница
    привязки превратилась бы в полотно на сотни килобайт; при перегрузке ёмкости QR летело бы
    чужое исключение (`segno.DataOverflowError`), текст которого содержит предъявленные данные.
    """
    if not payload:
        raise QrBuildError("полезная нагрузка QR-картинки пуста")
    if len(payload) > QR_MAX_PAYLOAD_CHARS:
        raise QrBuildError(
            f"полезная нагрузка {len(payload)} знаков больше предела "
            f"{QR_MAX_PAYLOAD_CHARS} знаков"
        )
    try:
        code = segno.make(payload, error=QR_ERROR_LEVEL)
    except segno.DataOverflowError as exc:
        raise QrBuildError(f"полезная нагрузка {len(payload)} знаков не помещается в QR") from exc

    matrix = code.matrix
    side = len(matrix[0])
    parts: list[str] = []
    for y, row in enumerate(matrix):
        if len(row) != side:
            raise QrBuildError(f"матрица QR не квадратная: {len(matrix)}×{len(row)}")
        x = 0
        while x < side:
            if not row[x]:
                x += 1
                continue
            start = x
            while x < side and row[x]:
                x += 1
            # Прямоугольник прогона — четыре абсолютные команды. Относительные (`h`/`v`)
            # дали бы отрицательные числа на замыкающей стороне и ещё одну границу
            # алфавита; здесь же строка описывается набором `[MHVZ0-9 ]`, и тест
            # разбирает её обратно по тому же шаблону.
            x0 = start + QR_QUIET_ZONE_MODULES
            y0 = y + QR_QUIET_ZONE_MODULES
            parts.append(f"M{x0} {y0}H{x + QR_QUIET_ZONE_MODULES}V{y0 + 1}H{x0}Z")

    modules = side + 2 * QR_QUIET_ZONE_MODULES
    path_d = "".join(parts)
    if not path_d or not _PATH_ALPHABET.fullmatch(path_d):
        raise QrBuildError("строка путей QR содержит что-то кроме геометрии")
    return QrGraphic(modules=modules, path_d=path_d)
