"""QR-кодировщик слоя представления: что именно попадает в картинку привязки (`T-103`, `R4d`).

HTTP-поведение страницы привязки проверяет офлайновая интеграция
`tests/integration/test_web_totp_page.py`; здесь — то, что из-за HTTP не видно: картинка несёт
ровно ту матрицу, которую выдал кодировщик, строка путей остаётся геометрией, а граница длины
срабатывает до обращения к кодировщику.

Главная проверка — обратная. Строка путей разбирается тестом обратно во множество тёмных модулей
и сравнивается с матрицей `segno`. Это не «функция вернула что-то похожее на путь»: так видно,
что в картинку попали ровно те модули, которые закодировал кодировщик. Сдвиг на модуль, потеря
ряда или перепутанные оси дают QR, который генератор читает неверно или не читает вовсе, — и
замечает это человек с телефоном у экрана, а не тест.

Замеры этого файла привязаны к фиксированной полезной нагрузке: кодирование `segno`
детерминировано (маску кодировщик выбирает по собственному критерию, не случайно), поэтому
числа воспроизводимы и закреплены проверкой.
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from typing import ClassVar, Final

import pytest
import segno

from apps.web import qrcode as qrcode_module
from apps.web.qrcode import (
    QR_ERROR_LEVEL,
    QR_MAX_PAYLOAD_CHARS,
    QR_QUIET_ZONE_MODULES,
    QrBuildError,
    qr_graphic,
)
from packages.identity.totp import totp_provisioning_uri

#: Фикстура полезной нагрузки: конкретная `otpauth://`-ссылка привязки, а не случайная строка.
FIXED_URI: Final = (
    "otpauth://totp/tbot:op.srez-r3?secret=JBSWY3DPEHPK3PXP&issuer=tbot"
    "&algorithm=SHA1&digits=6&period=30"
)

#: Замер 2026-11-22 (`segno` 1.6.6, `QR_ERROR_LEVEL` = `M`, `FIXED_URI`): версия 6, 41 модуль
#: в стороне, 49 с спокойной зоной, 830 тёмных модулей, длина ссылки 100 знаков. Числа
#: закреплены проверкой: поднять уровень исправления, сдвинуть границу или править сборку
#: `otpauth://` — значит изменить картинку, и это должно стать красным, а не тихим.
FIXED_MODULES: Final = 49
FIXED_DARK_MODULES: Final = 830
FIXED_URI_CHARS: Final = 100

#: Один прогон: `M{x} {y}H{правый}V{низ}H{x}Z`. Обратная ссылка `\1` в конце держит замыкание
#: ровно на левый край прогона — незамкнутый или «разъехавшийся» прямоугольник тестом не
#: разбирается и превращает проверку в молчаливое сравнение части картинки.
_RECT: Final = re.compile(r"M([0-9]+) ([0-9]+)H([0-9]+)V([0-9]+)H\1Z")

#: Алфавит, который разрешает сам модуль (см. `_PATH_ALPHABET` в `apps/web/qrcode.py`).
_ALPHABET: Final = re.compile(r"[MHVZ0-9 ]+")


def _модули_картинки(path_d: str) -> set[tuple[int, int]]:
    """Разобрать строку путей обратно во множество тёмных модулей.

    Разбор обязан покрыть всю строку: остаток означает, что генератор выдал команду, которую
    тест не понимает, — молча её проигнорировать значило бы проверить часть картинки.
    """
    cells: set[tuple[int, int]] = set()
    for match in _RECT.finditer(path_d):
        left, y, right, bottom = (int(match.group(i)) for i in range(1, 5))
        assert bottom == y + 1, f"прогон высотой {bottom - y} модуля вместо одного"
        assert right > left, f"прогон замкнут в обратную сторону: {match.group(0)}"
        cells.update((left + offset, y) for offset in range(right - left))
    remainder = _RECT.sub("", path_d)
    assert remainder == "", f"строка путей разобрана не целиком: остаток {remainder[:80]!r}"
    return cells


def _модули_кодировщика(payload: str) -> set[tuple[int, int]]:
    """Тёмные модули матрицы `segno` — уже со сдвигом на спокойную зону."""
    matrix: Iterable[bytearray] = segno.make(payload, error=QR_ERROR_LEVEL).matrix
    return {
        (x + QR_QUIET_ZONE_MODULES, y + QR_QUIET_ZONE_MODULES)
        for y, row in enumerate(matrix)
        for x, cell in enumerate(row)
        if cell
    }


def test_картинка_несёт_ровно_матрицу_кодировщика() -> None:
    """Геометрия слоя представления не имеет права отличаться от матрицы `segno`.

    Собирающий картинку модуль не кодирует QR — он только раскладывает тёмные прогоны по
    координатам. Проверяется именно эта тонкая прослойка: если кодировщик выдаёт одну картинку,
    а в ответ уходит другая (сдвиг, потерянный ряд, перепутанные `x`/`y`), привязка ломается на
    глазах у пользователя при полностью зелёных тестах кодирования.
    """
    graphic = qr_graphic(FIXED_URI)
    expected = _модули_кодировщика(FIXED_URI)

    assert _модули_картинки(graphic.path_d) == expected
    assert len(expected) == FIXED_DARK_MODULES, "замер числа тёмных модулей устарел"
    assert graphic.modules == FIXED_MODULES, "замер размера картинки устарел"
    # Все координаты лежат внутри холста: вышедший за границу модуль генератор не дочитывает.
    assert all(0 <= x < graphic.modules and 0 <= y < graphic.modules for x, y in expected)
    сторона_без_рамки = len(segno.make(FIXED_URI, error=QR_ERROR_LEVEL).matrix[0])
    assert graphic.modules == сторона_без_рамки + 2 * QR_QUIET_ZONE_MODULES, (
        "спокойная зона учтена с одной стороны: картинка прижимается к краю, и часть "
        "генераторов её не читает"
    )


def test_размер_картинки_задают_уровень_исправления_и_граница() -> None:
    """Константы модуля — единственные ручки, которые меняют картинку.

    `QR_ERROR_LEVEL` обязан входить в закрытый набор `segno`, спокойная зона — быть не меньше
    минимума ISO/IEC 18004 (четыре модуля), а картинка — расти вместе с нагрузкой. Иначе
    «уровень повыше» и «граница подальше» превращаются в тихо подъедаемый размер страницы.
    """
    assert QR_ERROR_LEVEL in {"L", "M", "Q", "H"}
    assert QR_QUIET_ZONE_MODULES >= 4

    размеры = [qr_graphic("a" * длина).modules for длина in (16, 64, QR_MAX_PAYLOAD_CHARS)]
    assert размеры == sorted(размеры), f"размер картинки не растёт вместе с нагрузкой: {размеры}"
    assert len(set(размеры)) == 3, f"размер картинки не меняется с нагрузкой: {размеры}"


def test_строка_путей_остаётся_геометрией() -> None:
    """Значение уходит в атрибут `d` как есть, без `|safe`.

    Автоэкранирование Jinja2 (§8.8) не спасает от «геометрии», в которой оказался символ
    разметки: оно экранирует, а не запрещает. Поэтому алфавит закрыт здесь: команды `M`/`H`/`V`/
    `Z`, целые координаты и пробелы. Любая угловая скобка, кавычка или перевод строки в строке
    путей означает, что в шаблон уходит что-то кроме прямоугольников.
    """
    graphic = qr_graphic(FIXED_URI)
    assert _ALPHABET.fullmatch(graphic.path_d), "в строке путей появились чужие знаки"
    for forbidden in ("<", '"', "&", "\n", "-"):
        assert forbidden not in graphic.path_d, f"в геометрии появился знак {forbidden!r}"


def test_граница_длины_срабатывает_до_кодировщика_и_не_выдаёт_нагрузку() -> None:
    """Пустая и слишком длинная нагрузка отклоняются, а сообщение не содержит саму нагрузку.

    Длина — это размер страницы и размер картинки: без границы `segno` выдал бы квадрат на сто с
    лишним модулей. Сообщение об отказе уходит в лог, а в `otpauth://`-ссылке лежит секрет
    привязки (§8.4 «красное правило»), поэтому проверка проверяет и текст отказа.
    """
    with pytest.raises(QrBuildError) as пустая:
        qr_graphic("")
    assert "пуста" in str(пустая.value)

    нагрузка = "A" * (QR_MAX_PAYLOAD_CHARS + 1)
    with pytest.raises(QrBuildError) as длинная:
        qr_graphic(нагрузка)
    текст = str(длинная.value)
    assert "A" * 20 not in текст, "сообщение об отказе содержит полезную нагрузку"
    assert str(QR_MAX_PAYLOAD_CHARS) in текст, "в отказе не названа граница, о которую он упёрся"


def test_граница_ниже_ёмкости_qr_и_проходит_на_реальной_ссылке() -> None:
    """Граница стоит так, что перегрузки ёмкости QR не бывает, а реальная привязка проходит.

    Первая часть проверяет, что нагрузка ровно на границе всё ещё кодируется: значит, отказ по
    длине — это охрана размера страницы, а не попытка угнаться за ёмкостью формата, и исключение
    `segno` о перегрузке остаётся страховкой, а не рабочим путём. Вторая часть держит обратное:
    граница не должна оказаться ниже реальной ссылки привязки, иначе страница молча лишится
    картинки уже на площадке.
    """
    предельная = qr_graphic("a" * QR_MAX_PAYLOAD_CHARS)
    assert предельная.modules < 100, f"картинка на границе выросла до {предельная.modules} модулей"

    ссылка = totp_provisioning_uri("JBSWY3DPEHPK3PXP", account_name="op.srez-r3", issuer="tbot")
    assert ссылка == FIXED_URI, (
        "реальная `otpauth://`-ссылка перестала совпадать с фикстурой замеров: проверки размера "
        "больше не описывают живую страницу"
    )
    assert (
        len(ссылка) == FIXED_URI_CHARS
    ), f"длина ссылки {len(ссылка)} не совпала с фикстурой {FIXED_URI_CHARS}"
    assert qr_graphic(ссылка).modules == FIXED_MODULES


def test_одинаковая_нагрузка_даёт_идентичную_картинку() -> None:
    """Кодирование детерминировано: одна и та же ссылка — один и тот же путь.

    Проверка нужна не для красоты: интеграционные тесты сравнивают `d` из ответа с ожиданием,
    собранным из показанного секрета. Зависел бы выбор маски от случайности — сравнение было бы
    красным наполовину, и честного вывода о картинке получить было бы нельзя.
    """
    assert qr_graphic(FIXED_URI) == qr_graphic(FIXED_URI)


def test_перегрузка_ёмкости_qr_переводится_в_свой_отказ_и_не_несёт_нагрузку(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Чужое исключение кодировщика переводится в `QrBuildError`, а текст нагрузки не выводит.

    Граница на длине стоит ниже ёмкости формата, поэтому ветка — страховка, а не рабочий путь.
    Проверять её всё равно нужно: текст `segno.DataOverflowError` содержит предъявленные данные,
    а страница привязки передаёт причину отказа в лог. Если перевод исчезнет или станет
    «пробросим как есть», в лог уходит `otpauth://`-ссылка с секретом привязки (§8.4).
    """

    def перегрузка(*_args: object, **_kwargs: object) -> object:
        raise segno.DataOverflowError(f"не влезает: {_args[0]!r}")

    monkeypatch.setattr(segno, "make", перегрузка)
    with pytest.raises(QrBuildError) as перехват:
        qr_graphic(FIXED_URI)
    текст = str(перехват.value)
    assert "не помещается в QR" in текст, "отказ кодировщика не переведён в понятный"
    assert "secret=" not in текст, "текст отказа содержит полезную нагрузку"
    assert FIXED_URI not in текст, "текст отказа повторяет `otpauth://`-ссылку целиком"


def test_матрица_кодировщика_проверяется_на_квадратность(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Матрицу кодировщика проверяем, а не принимаем на веру: ряд другой длины — битая картинка.

    Сборщик идёт по строкам и считает координаты по длине первого ряда. Если ряд короткий или
    длинный, геометрия разъезжается по вертикали: генератор читает другой код, и человек получает
    «код не подходит» без объяснения. Молчаливый обход короткого ряда стоил бы проверки, поэтому
    отказ назван явно.
    """

    class Ряды:
        matrix: ClassVar[list[list[int]]] = [[1, 1, 0], [1, 0], [0, 1, 1]]

    monkeypatch.setattr(segno, "make", lambda *_args, **_kwargs: Ряды())
    with pytest.raises(QrBuildError) as отказ:
        qr_graphic(FIXED_URI)
    assert "не квадратная" in str(отказ.value), "разная длина рядов осталась незамеченной"


def test_проверка_алфавита_ловит_геометрию_за_пределами_набора(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Проверка алфавита — не «на всякий случай»: её срабатывание проверено на месте.

    За набор `[MHVZ0-9 ]` геометрия уходит в двух случаях: знак у координаты (отрицательная
    спокойная зона) и дробная координата. Первый случай вызывается прямо здесь — ширина рамки
    подменяется на отрицательную, координата первого тёмного модуля уходит в минус, в строке
    появляется дефис, и сборщик отказывает вместо того, чтобы отдать в разметку строку с
    знаком. Дробных координат сборщик не производит вовсе: все координаты целые.
    """
    monkeypatch.setattr(qrcode_module, "QR_QUIET_ZONE_MODULES", -1)
    with pytest.raises(QrBuildError) as отказ:
        qr_graphic("a" * 8)
    assert "кроме геометрии" in str(отказ.value), "строка с дефисом прошла как геометрия"
