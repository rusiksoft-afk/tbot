"""Контракт церемонии приглашения: порядок шагов, адрес ссылки и закрытые наборы объяснений
(`ADR-021`, задача `T-105`, срез `R7b`).

Офлайновая проверка без базы и без HTTP-запросов: она держит то, что иначе расходится молча,
потому что живёт в разных файлах.

1. **Порядок шагов приёма ссылки** (`ADR-021` п. 4). Ссылка одноразовая, и заявка выпуска
   (`pending → used`) для человека необратима: опечатка в пароле, заявившая выпуск, стоит ему
   нового письма и нового выпуска, а параллельный приём без проверки заявки оставил бы учётную
   запись по закрытой ссылке. Порядок «источник → частота → ссылка → значения полей → заявка →
   учётная запись → фиксация» закрепляется проверкой исходного кода обработчика: поведение
   проверяет `tests/integration/test_invitation_flow.py`, а перестановку двух строк в обработчике
   поведение ловит не всегда — оба ответа могут быть `400`.
2. **`claimed=True` после guarded-`UPDATE`** — иначе домен отказал бы законному обработчику.
3. **Порядок закрывающего действия** (`ADR-020` п. 6): счёт живых администраторов обязан быть снят
   **до** перехода и с `except_user_id`, иначе проверка последнего администратора теряет смысл.
4. **Адрес ссылки — один источник.** Литерал адреса и имя параметра живут в
   `apps/web/security/sessions.py`; шаблоны не имеют права ни печатать адрес, ни собирать параметр.
5. **Объяснения — закрытые наборы.** Каждый код исхода, который маршрут подставляет в `?note=`,
   обязан иметь текст из карты; объяснение состояния учётной записи не смешивается с безликим
   отказом по роли и с ответом «объекта нет».

Живое поведение (значения ответов, `404`/`410`, отзыв сеансов, очередь одобрения) держат
`tests/integration/test_invitation_flow.py` и `tests/integration/test_web_admin_accounts.py`;
гонку guarded-`UPDATE`, уникальный индекс и `CHECK` — `tests/integration/test_invitations_db.py`
(job «миграции»).
"""

