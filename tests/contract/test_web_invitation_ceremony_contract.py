#: Порядок вызовов в обработчике приёма ссылки (`ADR-021` п. 4). Сверяется только относительный
#: порядок перечисленных здесь вызовов: обработчик содержит и служебные (разбор формы, журнал),
#: которые в контракт не входят.
_ACCEPTANCE_ORDER: Final[tuple[str, ...]] = (
    "ensure_same_origin",
    "enforce_scope",
    "_resolve_link",
    "ensure_login_syntax",
    "check_password_policy",
    "same_login",
    "user_by_login",
    "claim_invitation",
    "user_from_invitation",
    "commit",
)

#: Порядок закрывающего доступ действия (`ADR-020` п. 6).
_CLOSE_ACCESS_ORDER: Final[tuple[str, ...]] = (
    "active_admin_count",
    "ensure_not_last_admin",
    "suspend_account",
    "revoke_sessions",
    "commit",
)

#: Узлы определений функций: `isinstance` принимает объединение типов (PEP 604), и синхронная
#: функция с асинхронной рассматриваются одинаково — порядок вызовов сверяется по телу любого вида.
_FUNCTION_NODES = ast.FunctionDef | ast.AsyncFunctionDef


def _source(path: pathlib.Path) -> str:
    assert path.is_file(), f"файл слоя представления исчез: {path}"
    return path.read_text(encoding="utf-8")


def _function(path: pathlib.Path, name: str) -> _FUNCTION_NODES:
    """Определение функции по имени — ради проверки порядка вызовов в её теле."""
    дерево = ast.parse(_source(path), filename=str(path))
    for узел in дерево.body:
        if isinstance(узел, _FUNCTION_NODES) and узел.name == name:
            return узел
    raise AssertionError(f"в {path.name} нет функции {name!r}: порядок проверять нечем")


def _call_name(узел: ast.expr) -> str | None:
    if isinstance(узел, ast.Name):
        return узел.id
    if isinstance(узел, ast.Attribute):
        return узел.attr
    return None


def _call_order(path: pathlib.Path, name: str) -> list[str]:
    """Имена вызовов внутри функции — в порядке их появления в исходнике."""
    собранные: list[tuple[int, int, str]] = []
    for узел in ast.walk(_function(path, name)):
        if isinstance(узел, ast.Call):
            имя = _call_name(узел.func)
            if имя is not None:
                собранные.append((узел.lineno, узел.col_offset, имя))
    return [имя for _, _, имя in sorted(собранные)]


def _assert_order(вызовы: list[str], порядок: tuple[str, ...], что: str) -> None:
    """Требует, чтобы все вызовы из `порядок` встречались ровно по разу и именно в этом порядке."""
    позиции: list[int] = []
    for имя in порядок:
        assert (
            имя in вызовы
        ), f"{что}: обработчик не вызывает {имя!r} — контракт нарушен или имя переименовано"
        позиции.append(вызовы.count(имя))
        assert вызовы.count(имя) == 1, f"{что}: вызов {имя!r} встречается больше одного раза"
    места = [вызовы.index(имя) for имя in порядок]
    assert места == sorted(места), f"{что}: порядок вызовов нарушен, фактическая очередь — {вызовы}"


def _keyword(path: pathlib.Path, функция: str, вызов: str, параметр: str) -> ast.expr | None:
    """Значение именованного аргумента первого вызова с таким именем."""
    for узел in ast.walk(_function(path, функция)):
        if isinstance(узел, ast.Call) and _call_name(узел.func) == вызов:
            for аргумент in узел.keywords:
                if аргумент.arg == параметр:
                    return аргумент.value
    return None


def _literal_codes(path: pathlib.Path, имя_функции: str) -> set[str]:
    """Строковые литералы, переданные в вызовы `имя_функции` во всём модуле."""
    дерево = ast.parse(_source(path), filename=str(path))
    значения: set[str] = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Call) and _call_name(узел.func) == имя_функции:
            for аргумент in узел.args:
                if isinstance(аргумент, ast.Constant) and isinstance(аргумент.value, str):
                    значения.add(аргумент.value)
    return значения


def _шаблоны() -> dict[str, str]:
    return {путь.name: _source(путь) for путь in sorted(_TEMPLATES.glob("*.html"))}


def test_приём_ссылки_идёт_по_порядку_от_источника_до_фиксации() -> None:
    """Обработчик приёма ссылки вызывается в порядке `ADR-021` п. 4.

    Каждый сдвиг ломает конкретное:

    * `ensure_same_origin` раньше всего — иначе межсайтовый запрос истрачивает одноразовую ссылку,
      не создав учётной записи, и человек узнает об этом, когда ссылку уже не принять;
    * `enforce_scope` до обращения к выпуску — иначе счётчик частоты не отличал бы перебор
      значений ссылки от безобидного просмотра страницы (§8.3);
    * `_resolve_link` до проверок формы — иначе `POST` без значения ссылки превращается в форму
      открытой регистрации, которую §1.2 запрещает, и ответ начал бы описывать поля формы;
    * проверки полей до `claim_invitation` — иначе опечатка в пароле сжигает выпуск;
    * `user_from_invitation` и `commit` после заявки — иначе учётная запись появляется по ссылке,
      которую заявить не удалось.
    """
    _assert_order(
        _call_order(_INVITATIONS_ROUTE, "invite_submit"), _ACCEPTANCE_ORDER, "приём приглашения"
    )


def test_после_заявки_выпуска_домен_знает_что_заявка_уже_выиграна() -> None:
    """`user_from_invitation(..., claimed=True)` — единственный допустимый вызов после заявки.

    Причина не в стиле: после guarded-`UPDATE` живого слоя состояние строки намеренно
    несинхронизировано (`synchronize_session=False`), а в офлайн-зеркале оно уже `used`. Обычный
    вызов второй раз проверил бы открытость и отказал законному обработчику — на офлайн-половине
    отказ появился бы сразу, на живой нет, и разница ловилась бы только в CI (`ADR-021` п. 4).

    Значением аргумента обязан быть ровно литерал `True`: переменная или приведение означали бы,
    что на другом пути проверка открытости возвращается, и ровно тот отказ, ради которого флаг
    введён, вернётся обратно.
    """
    значение = _keyword(_INVITATIONS_ROUTE, "invite_submit", "user_from_invitation", "claimed")
    assert значение is not None, "домен после заявки ссылки вызывается без `claimed`"
    assert isinstance(значение, ast.Constant), "`claimed` обязан быть литералом, а не выражением"
    assert (
        значение.value is True
    ), "`claimed` обязан быть литералом True: иначе проверка открытости вернётся в домен"


def test_приём_ссылки_фиксируется_один_раз() -> None:
    """В обработчике приёма ровно одна фиксация транзакции.

    Две — это либо заявленная ссылка без учётной записи (человек приходит, а доступа нет; выпуск
    при этом истрачен), либо учётная запись, зафиксированная до заявки (доступ, которого по записи
    приглашения нет). Офлайн-зеркало ни одной из этих половин не показывает: у него нет отката,
    поэтому порядок держится по исходному коду, а живая половинка — `test_invitations_db.py`.
    """
    вызовы = _call_order(_INVITATIONS_ROUTE, "invite_submit")
    assert вызовы.count("commit") == 1, f"фиксаций {вызовы.count('commit')}, а должна быть одна"


def test_закрывающее_действие_считает_администраторов_до_перехода() -> None:
    """Порядок `_close_access`: счёт администраторов → переход → отзыв сеансов → фиксация.

    Счёт, снятый после перехода, теряет смысл: `state` уже изменён, и тот же запрос вернул бы ноль
    при любом раскладе — проверка последнего живого администратора перестала бы ловить ровно тот
    случай, ради которого заведена (`ADR-020` п. 6). Отзыв сеансов до перехода означал бы «доступа
    нет, а состояние ещё активное», фиксация до отзыва — «заблокирована, но ходит» (§8.3 требует
    немедленного применения отзыва).

    Отдельно проверяется `except_user_id` у счёта: без него блокировка одного из двух живых
    администраторов считала бы обоих и отказывала зря.
    """
    _assert_order(
        _call_order(_ADMIN_ROUTE, "_close_access"), _CLOSE_ACCESS_ORDER, "закрывание доступа"
    )
    исключение = _keyword(_ADMIN_ROUTE, "_close_access", "active_admin_count", "except_user_id")
    assert исключение is not None, "счёт живых администраторов снят без `except_user_id`"


def test_блокировка_и_архивирование_исполняются_одним_порядком() -> None:
    """У блокировки и архивирования один помощник закрывания, а не две копии порядка.

    Два обработчика, каждый со своим порядком шагов, расходятся при первой же правке: в одной
    половинке перестаёт отзываться сеанс или считаться администратор. Проверка требует, чтобы оба
    маршрута вызывали общего помощника ровно один раз и не дублировали отзыв рядом с ним.
    """
    for функция in ("suspend_submit", "archive_submit"):
        вызовы = _call_order(_ADMIN_ROUTE, функция)
        assert (
            вызовы.count("_close_access") == 1
        ), f"{функция}: закрывание доступа сделано не общим помощником"
        assert (
            "revoke_sessions" not in вызовы
        ), f"{функция}: отзыв сеансов продублирован рядом с помощником"
        assert (
            "ensure_not_last_admin" not in вызовы
        ), f"{функция}: проверка последнего администратора продублирована в маршруте"


def test_адрес_ссылки_собирается_в_одном_месте_и_не_печатается_в_шаблонах() -> None:
    """Литерал адреса и имя параметра ссылки живут в одном модуле представления.

    Значение ссылки — носитель доступа (§8.4). Если адрес начнут собирать в двух местах, они
    разойдутся: страница выпуска покажет ссылку, которую маршрут не принимает, а значение уедет в
    журнал периметра сегментом пути — Caddy вымарывает только ключи query (`ADR-021` п. 3).
    Поэтому шаблоны не должны содержать ни литерала адреса, ни сборки параметра, а значение
    показывается ровно один раз — на странице выпуска.
    """
    шаблоны = _шаблоны()
    assert шаблоны, "шаблоны приложения не найдены — проверять нечего"
    for имя, текст in шаблоны.items():
        assert INVITE_PATH not in текст, f"{имя}: шаблон содержит литерал адреса приглашения"
        assert f"{INVITE_LINK_KEY}=" not in текст, f"{имя}: шаблон собирает параметр ссылки сам"

    выпуск = шаблоны["admin_invitation_issued.html"]
    assert выпуск.count("{{ link }}") == 1, "значение ссылки показывается больше одного раза"

    сборки = [
        путь.name for путь in (_INVITATIONS_ROUTE, _ADMIN_ROUTE) if "invite_link(" in _source(путь)
    ]
    assert сборки == [
        "admin_users.py"
    ], "сборка адреса ссылки появилась в маршруте приёма — литералы разошлись бы при правке"
    assert "def invite_link(" in _source(
        _ADDRESS_MODULE
    ), "сборка адреса ссылки исчезла из модуля сеансов"


def test_страница_приглашения_не_отправляет_токен_сеанса() -> None:
    """Форма приёма не содержит поля токена — и не должна.

    Исключение зафиксировано `ADR-021` п. 1: у приглашённого человека нет сеанса, а токен
    `ADR-008` выводится из пары «значение куки + `id` сеанса», то есть вывод для него не определён.
    Пустое поле хуже его отсутствия: человек видел бы поле, которое ничего не защищает, а слой
    сравнивал бы пустое значение с тем, чего не существует.

    Проверка держит и `action=""`: значение ссылки обязано оставаться только в адресе страницы, а
    не копироваться в тело ответа — иначе оно попадает в журнал и в историю браузера второй раз.
    """
    шаблон = _шаблоны()["invite.html"]
    assert (
        'name="csrf_token"' not in шаблон
    ), "форма приёма получила токен сеанса, которого не бывает"
    assert 'action=""' in шаблон, "форма уносит значение ссылки из адреса страницы"


def test_каждый_код_исхода_раздела_имеет_текст_объяснения() -> None:
    """Все коды, которые раздел подставляет в `?note=`, есть в карте объяснений.

    Маршрут отвечает кодом в адресе перенаправления, а человек видит строкой из `ACTION_NOTES`. Код
    без записи в карте — молчаливый раздел без объяснения: администратор нажал кнопку и не узнал
    исхода (§9.3). Проверяются литералы всех обработчиков раздела; обратное направление (запись в
    карте без кода) безвредно и не проверяется.
    """
    коды = _literal_codes(_ADMIN_ROUTE, "_redirect")
    неизвестные = коды - set(ACTION_NOTES)
    assert not неизвестные, f"коды исхода без объяснения: {sorted(неизвестные)}"
    assert коды, "раздел не возвращает ни одного объяснения — контракт сломан"


def test_объяснения_покрывают_закрытые_наборы_домена() -> None:
    """Ключи объяснений совпадают с закрытыми наборами — доменными и адресными.

    Иначе разговор идёт о разных множествах: домен добавляет состояние (§4.1) или исход выпуска, а
    человек получает пустую строку либо запасную формулировку «вне описанного набора» там, где
    нужно внятное объяснение (§9.3).

    Разделение намеренное, и держится проверкой именно оно:

    * состояния учётной записи — `users.ACCESS_CODES` плюс `users.NO_ACCOUNT_CODE`: «записи нет» —
      не состояние, а отсутствие строки (сеанс жив, а запись убрали архивированием или правкой
      таблицы — `ADR-017` п. 4), и объяснение такому случаю тоже нужен;
    * закрытая ссылка — `invitations.INVITATION_UNUSABLE_CODES` (`expired`, `used`, `revoked`;
      ответ `410`) плюс адресные причины `unknown` и `malformed` (ответ `404`): их задаёт разбор
      значения ссылки, а не домен, и в доменный набор они не входят сознательно (комментарий перед
      `UNUSABLE_EXPLANATIONS` в модуле маршрута). Смешение наборов лишает ответ различия «такой
      ссылки нет» и «этой ссылкой нельзя воспользоваться», а оно определяет, попросить ли новую
      ссылку или позвать администратора.
    """
    закрытые_состояния = set(ACCESS_CODES) | {NO_ACCOUNT_CODE}
    assert (
        set(ACCOUNT_STATE_EXPLANATIONS) == закрытые_состояния
    ), "объяснения состояния учётной записи разошлись с набором кодов допуска"

    доменные = set(INVITATION_UNUSABLE_CODES)
    адресные = _адресные_причины()
    assert доменные <= set(UNUSABLE_EXPLANATIONS), "доменный исход выпуска остался без объяснения"
    assert (
        set(UNUSABLE_EXPLANATIONS) == доменные | адресные
    ), "объяснения закрытой ссылки разошлись с доменными исходами и причинами разбора адреса"
    assert not доменные & адресные, "адресная причина стала доменным кодом: код ответа разъедется"


def _адресные_причины() -> set[str]:
    """Причины, которые возвращает разбор значения ссылки (`_Link(reason=...)`).

    Список берётся из исходника маршрута: это не заимствованный у домена перечень, а ровно те
    коды, которые обработчик физически умеет подставить в страницу с `404`.
    """
    причины: set[str] = set()
    for узел in ast.walk(_function(_INVITATIONS_ROUTE, "_resolve_link")):
        if isinstance(узел, ast.Call) and _call_name(узел.func) == "_Link":
            for аргумент in узел.keywords:
                значение = аргумент.value
                if (
                    аргумент.arg == "reason"
                    and isinstance(значение, ast.Constant)
                    and isinstance(значение.value, str)
                    and значение.value
                ):
                    причины.add(значение.value)
    return причины


def test_три_вида_отказа_не_смешиваются() -> None:
    """Отказ по роли, объяснение состояния и «объекта нет» — три разных ответа.

    Безликий `403` защищает от простановки ликов чужих учётных записей (§8.7, `AC-identity-01`);
    объяснение состояния говорит человеку про **его** запись (§9.3); «объекта нет» (`404`) отвечает
    на действие над строкой, которой нет. Смешать их — значит либо начать объяснять чужие учётные
    записи, либо перестать объяснять свои. Поэтому тексты сверяются раздельно и ни один из них не
    должен встречаться внутри объяснений состояния.
    """
    assert DENIAL_BODY["detail"] == DENIAL_DETAIL
    assert OBJECT_GONE_BODY["detail"] == OBJECT_GONE_DETAIL
    assert DENIAL_DETAIL not in OBJECT_GONE_DETAIL
    assert OBJECT_GONE_DETAIL not in DENIAL_DETAIL
    for код, текст in ACCOUNT_STATE_EXPLANATIONS.items():
        assert DENIAL_DETAIL not in текст, f"объяснение {код} вобрало текст отказа по роли"
        assert OBJECT_GONE_DETAIL not in текст, f"объяснение {код} вобрало текст «объекта нет»"


