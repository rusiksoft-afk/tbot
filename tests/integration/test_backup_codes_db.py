    запросы, _ = captured
    запросы.clear()

    with pytest.raises(BackupCodeError):
        SqlStore(db).insert_backup_code_hashes(user.id, (хэши[0], хэши[0]))
    assert not _вставки(запросы), "повтор внутри пачки дошёл до базы"
