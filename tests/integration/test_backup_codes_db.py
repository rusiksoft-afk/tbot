"""Живой PostgreSQL и `backup_codes`: пачка только хэшами, одноразовость расхода, аннулирование
неиспользованных остатков (TZ §8.2, `ADR-016` п. 3, 5, 7, задача `T-104`, срез `R5b`).

Офлайновая половинка — репозиторий в памяти (`tests/integration/web_support.py`, `MemoryStore`):
тот же набор предикатов, запускаемый на dev-машине, где PostgreSQL нет. Здесь проверяется ровно то,
чего память доказать не может:

* **в таблице лежат только хэши, и ни одно значение кода не уходит ни в SQL, ни в связанные
  значения** (§8.4, §8.8). В памяти утверждение «значение не попадает в вывод» пусто: там нет ни
  SQL, ни `pg_stat_statements`, ни журнала параметров. На базе это отдельная проверка, и она не
  должна быть зелёной на пустом списке запросов — поэтому та же фикстура обязана найти в
  связанных значениях **хэши**;
* **`CHECK ck_backup_codes_code_hash_sha256` и `uq_backup_codes_user_id_code_hash`** держат форму
  хэша и «10 разных» (§8.2). Без CHECK «битая» строка в `code_hash` неотличима от «кода нет»
  (`ADR-016` п. 7); без уникального индекса повторный выпуск создал бы вторую строку с тем же
  значением, и расход «первой» оставил бы доступ второй;
* **частичный индекс `ix_backup_codes_user_id_unused` и предикат `used_at IS NULL` в самом
  запросе**. Без предиката страница резервного кода различает «такого кода нет» и «такой код уже
  потрачен» — бесплатный оракул для того, кто подсмотрел экран при выпуске пачки (`ADR-016` п. 3,
  п. 5). В памяти предикат скопирован руками, и там «правило есть» неотличимо от «правила нет»;
* **одноразовость расхода — один `UPDATE` с условием** (`ADR-016` п. 7), обязательная
  `test_backup_code_single_use`: два входа с одним кодом на двух настоящих соединениях. В памяти
  два «параллельных» входа физически не приходят, поэтому форма «нашёл — пометил» прошла бы там
  так же зелёно — тот же дефект, что уже закрывали для TOTP-кода (`ADR-015` п. 5);
* **момент расхода ставит база** (`SET used_at = now()`), а не часы контейнера: семидневный срок
  `ADR-016` п. 6 производен от пары `created_at`/`used_at`, и если одна дата берётся из часов базы,
  а другая из часов процесса, перевыпуск пачки перестал бы сниматься с обязательства перевыпустить,
  а через семь суток вход блокировался бы у учётки, которая сделала всё правильно;
* **повторная генерация аннулирует только неиспользованные строки и ничего не удаляет** (§8.2).
  Израсходованные держат `used_at` — единственный след начала семидневного срока: сдвинуть его
  означало бы перенести срок задним числом, удалить строку — снять и обязательство перевыпустить,
  и блокировку входа по просрочке (`ADR-016` п. 6, п. 11). Проверен и порядок вызовов: аннулирование
  **после** вставки задевает новую пачку, и это опасность, а не стилистическое замечание.

Запуск: `TBOT_DB_URL` на базу, развёрнутую до `upgrade head` (так и стоит в job'е `migrations`).
Без переменной группа пропускается целиком (на dev-машине базы нет), при заданной, но недоступной
базе — падает, а не пропускается.
"""

