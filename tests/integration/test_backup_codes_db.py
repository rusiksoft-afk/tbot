# ─── расход: одноразовость как свойство перехода ───────────────────────────────────────────────


def test_backup_code_single_use(db: Session, engine: Engine) -> None:
    """Две попытки израсходовать один код на двух соединениях — ровно один успех (§8.2).

    Обязательная проверка среза `R5b` (`ADR-016` п. 10). Форма «нашёл неиспользованный → пометил
    использованным» зелёная на любом офлайн-репозитории и двойная под параллельными входами: оба
    запроса читают одно и то же состояние `used_at IS NULL` и помечают строку дважды. На базе
    переход закрывает один `UPDATE` с условием: строка блокируется на время перехода, а вторая
    попытка перечитывает состояние уже после первой и не находит подходящей строки (`rowcount = 0`).

    Оба входа обязаны **одновременно** оказаться внутри перехода, иначе проверка сводится к
    последовательным запросам и прошла бы на не-атомарной реализации. Для этого барьер стоит между
    поиском и расходом: к моменту, когда оба его прошли, у обоих открыт транзакт и выполнен поиск.
    """
    user = _учётка(db, suffix="single")
    _коды, хэши = _пачка(db, user)
    хэш = хэши[0]
    фабрика = sessionmaker(bind=engine, expire_on_commit=False)

    оба_у_расхода = threading.Barrier(2)

    def попытка() -> bool:
        session = фабрика()
        try:
            слой = SqlStore(session)
            строка = слой.find_unused_backup_code(user_id=user.id, code_hash=хэш)
            if строка is None:
                # Строки не нашлось (сама по себе это уже провал одноразовости). Барьер при этом
                # обязан быть снят, иначе второй вход дождётся таймаута, и настоящая причина
                # отказа исчезнет за `BrokenBarrierError`.
                оба_у_расхода.abort()
                return False
            # Оба входа дошли до расхода: транзакты открыты, поиск выполнен обоими.
            оба_у_расхода.wait(timeout=20)
            успех = слой.spend_backup_code(code_id=строка.id, user_id=user.id)
            session.commit()
            return успех
        finally:
            session.close()

    with ThreadPoolExecutor(max_workers=2) as пул:
        будущие = [пул.submit(попытка), пул.submit(попытка)]
        исходы = [будущее.result() for будущее in будущие]

    assert sum(исходы) == 1, (
        f"один резервный код израсходован {sum(исходы)} раз(а) при двух параллельных входах: "
        f"{исходы} — guarded-`UPDATE` не атомарен, и §8.2 «одноразовые» не выполняется"
    )

    строки = _строки_из_базы(engine, user.id)
    assert _израсходованные(строки) == 1, "в таблице больше одной израсходованной строки"
    assert _неиспользованные(строки) == BACKUP_CODE_COUNT - 1
    with_расходом = [row[0] for row in строки if row[2] is not None]
    assert with_расходом, "ни одна строка не помечена израсходованной"

    # Третья попытка — отказ: код потрачен, и для вызывающего это неотличимо от «кода нет».
    слой = SqlStore(db)
    assert слой.find_unused_backup_code(user_id=user.id, code_hash=хэш) is None
    assert слой.spend_backup_code(code_id=with_расходом[0], user_id=user.id) is False
    слой.commit()
    assert _израсходованные(_строки_из_базы(engine, user.id)) == 1


