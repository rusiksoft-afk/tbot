def _учётка(db: Session, *, suffix: str) -> User:
    user = new_user(
        login=f"{_LOGIN_PREFIX}{suffix}{uuid.uuid4().hex[:6]}",
        password=TEST_PASSWORD,
        role="operator",
        state="active",
    )
    db.add(user)
    db.commit()
    return user


def _пачка(
    db: Session, user: User, *, количество: int = BACKUP_CODE_COUNT
) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Пачка через слой доступа: значения остаются у вызывающего, в таблицу идут только хэши.

    Тот же путь, что у маршрута выпуска (`R5c`): `new_backup_codes` → `hash_backup_code` →
    `insert_backup_code_hashes`. Значения возвращаются, чтобы проверки могли искать их во
    всём, что ушло в базу: если хоть одно попало в SQL или в связанные значения — проверка
    красная.
    """
    коды = new_backup_codes(количество)
    хэши = tuple(hash_backup_code(код) for код in коды)
    SqlStore(db).insert_backup_code_hashes(user.id, хэши)
    db.commit()
    return коды, хэши


def _строки_из_базы(engine: Engine, user_id: UUID) -> list[tuple[UUID, str, datetime | None]]:
    """Снимок `backup_codes` учётки вторым соединением: что реально лежит в таблице.

    `used_at` читается из базы, а не из объекта текущего запроса: после guarded-`UPDATE` с
    `synchronize_session=False` объект в identity map намеренно не обновлён, поэтому «объект в
    памяти поменялся» засчитан быть не может.
    """
    with engine.connect() as соединение:
        rows = соединение.execute(
            select(BackupCode.id, BackupCode.code_hash, BackupCode.used_at).where(
                BackupCode.user_id == user_id
            )
        ).all()
    return [(UUID(str(row[0])), str(row[1]), row[2]) for row in rows]


def _неиспользованные(строки: list[tuple[UUID, str, datetime | None]]) -> int:
    return sum(1 for _id, _hash, used_at in строки if used_at is None)


def _израсходованные(строки: list[tuple[UUID, str, datetime | None]]) -> int:
    return sum(1 for _id, _hash, used_at in строки if used_at is not None)


def _вставки(запросы: list[str]) -> list[str]:
    return [sql for sql in запросы if "INSERT INTO backup_codes" in sql]


def _выборки(запросы: list[str]) -> list[str]:
    return [sql for sql in запросы if "FROM backup_codes" in sql]


def _обновления(запросы: list[str]) -> list[str]:
    # Сравнение идёт по верхней границе регистра, потому что текст запроса нормализуется
    # (`lstrip().upper()`): писать `startswith("UPDATE backup_codes")` после `upper()` —
    # собственный дефект проверки: фильтр не находит ничего, цикл по пустому списку проходит,
    # и проверка превращается в пустую (замер: первый прогон CI, §1.42).
    return [sql for sql in запросы if sql.lstrip().upper().startswith("UPDATE BACKUP_CODES")]


def _формы_значения(код: str) -> tuple[str, ...]:
    """Формы одного значения, которые принимает `normalize_backup_code`.

    Искать значение в запросах стоит во всех них, а не только в каноне: канон — то, что видит база,
    а нижний регистр и две показные формы (группы по 5 знаков через дефис и через пробел) — то, что
    набирает человек. Любая из этих строк, попавшая в параметр запроса, — второй экземпляр секрета
    входа (§8.4).
    """
    return (
        код,
        код.lower(),
        f"{код[:5]}-{код[5:]}",
        f"{код[:5]} {код[5:]}",
    )


