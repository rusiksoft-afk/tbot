def test_частичный_индекс_и_уникальный_индекс_существуют(db: Session) -> None:
    """Предикат `used_at IS NULL` и уникальность пары `(user_id, code_hash)` — из ревизии `0002`.

    Проверка начинается с индексов, а не с вставки: если предикат исчез из индекса, остальные
    проверки группы продолжат проходить по другой причине (фильтр остался бы в `WHERE`, просто
    читался бы сканом всех строк учётки), а правило «10 разных» сломалось бы молча — повторный
    выпуск создал бы вторую строку с тем же значением, и расход первой оставил бы доступ второй.
    """
    определения: dict[str, str | None] = {}
    for имя in (_PARTIAL_INDEX, _UQ_HASH):
        определения[имя] = db.execute(
            text(
                "SELECT indexdef FROM pg_indexes "
                "WHERE tablename = 'backup_codes' AND indexname = :name"
            ),
            {"name": имя},
        ).scalar_one_or_none()

    остаток = определения[_PARTIAL_INDEX]
    assert остаток is not None, f"индекс неиспользованных кодов {_PARTIAL_INDEX} не найден"
    assert "used_at IS NULL" in остаток, (
        "у индекса неиспользованных нет предиката: поиск по хэшу и аннулирование остатков "
        f"читали бы все строки учётки, и «индекс есть» ничего не значит: {остаток}"
    )

    уникальный = определения[_UQ_HASH]
    assert уникальный is not None, f"уникальный индекс «10 разных» {_UQ_HASH} не найден"
    assert "UNIQUE" in уникальный.upper(), f"индекс «10 разных» не уникальный: {уникальный}"
    assert "user_id" in уникальный, f"в индексе «10 разных» нет `user_id`: {уникальный}"
    assert "code_hash" in уникальный, (
        f"индекс покрывает не пару `(user_id, code_hash)`: одно и то же значение двух учётных "
        f"записей стало бы конфликтом: {уникальный}"
    )


def test_пачка_ложится_одной_вставкой_и_в_таблице_только_хэши(
    db: Session, engine: Engine, captured: tuple[list[str], list[str]]
) -> None:
    """Выпуск пачки: 10 строк, все неиспользованные, `created_at` даёт база, форма хэша — из CHECK.

    Проверяются четыре вещи, и все четыре на живом ответе базы, а не на объектах в памяти:

    * строк ровно `BACKUP_CODE_COUNT` и все с пустым `used_at` — «10 шт.» §8.2;
    * в `code_hash` лежат именно хэши предъявленных значений (`hash_backup_code`), а не значения
      и не что-то производное от показа: сверка по канону обязана попадать в ту же строку;
    * `created_at` заполнен базой (`server_default now()`) и не позже текущего момента базы — на
      нём держится семидневный срок `ADR-016` п. 6;
    * пачка уходит одним `INSERT`, а не десятью: десять обращений означали бы «половина пачки
      вставлена» при отказе на шестой строке, а человек видел бы «коды выпущены» без кодов.
    """
    user = _учётка(db, suffix="insert")
    запросы, _ = captured
    запросы.clear()

    коды, хэши = _пачка(db, user)

    строки = _строки_из_базы(engine, user.id)
    assert (
        len(строки) == BACKUP_CODE_COUNT
    ), f"в таблице {len(строки)} строк вместо {BACKUP_CODE_COUNT}: §8.2 «Резервные коды: 10 шт.»"
    assert _неиспользованные(строки) == BACKUP_CODE_COUNT, "свежая пачка не вся неиспользованная"
    assert {row[1] for row in строки} == set(хэши), (
        "в `code_hash` лежат не те хэши: канон сверки разошёлся с выпущенными значениями, и "
        "человек со своим кодом получил бы отказ"
    )
    assert {hash_backup_code(код) for код in коды} == set(хэши)
    assert all(is_sha256_hex(row[1]) for row in строки), "форма хэша разошлась с CHECK колонки"

    вставки = _вставки(запросы)
    assert len(вставки) == 1, (
        f"пачка из {BACKUP_CODE_COUNT} кодов легла {len(вставки)} обращениями `INSERT`: "
        "построчная вставка оставляет частичное состояние пачки при отказе"
    )
    assert "code_hash" in вставки[0]

    пара = db.execute(
        text("SELECT max(created_at), now() FROM backup_codes WHERE user_id = :u"),
        {"u": user.id},
    ).one()
    created: datetime | None = пара[0]
    база_сейчас: datetime = пара[1]
    assert created is not None, "`created_at` не заполнен: семидневный срок неоткуда считать"
    assert timedelta(0) <= база_сейчас - created < timedelta(minutes=5), (
        f"`created_at` ({created}) не выглядит моментом базы ({база_сейчас}): серверный "
        "`server_default now()` не работает, и срок начнёт считаться по часам процесса"
    )


def test_битый_хэш_не_может_появиться_в_строке_ни_через_слой_ни_через_базу(
    db: Session, engine: Engine, captured: tuple[list[str], list[str]]
) -> None:
    """«Битая» строка в `code_hash` различима потому, что её не пускают ни слой, ни база.

    `ADR-016` п. 7 требует, чтобы строка другой формы не выглядела как «кода нет». Сделать такую
    строку различимой post factum нельзя: по самому хэшу не восстановить, что его считали не по
    канону. Поэтому правило держат два места, и проверяются оба: слой доступа отказывает **до**
    обращения к базе (`is_sha256_hex`), а база отказывает через `CHECK ck_...code_hash_sha256` —
    то есть штатным путём битой строки в таблице не бывает ни при каком порядке вызовов.

    Отдельно проверяется, что отказ слоя не оставил ни строк, ни запроса: иначе «отказали»
    означало бы «вставили половину пачки».
    """
    user = _учётка(db, suffix="badhash")
    запросы, _ = captured
    запросы.clear()

    for битый in BAD_HASHES:
        with pytest.raises(BackupCodeError):
            SqlStore(db).insert_backup_code_hashes(user.id, (битый,))
    with pytest.raises(BackupCodeError):
        SqlStore(db).insert_backup_code_hashes(user.id, ())

    assert not _вставки(запросы), "отказ по форме хэша дошёл до базы: пахнет частичной вставкой"
    assert _строки_из_базы(engine, user.id) == [], "после отказов в таблице остались строки"
    db.rollback()

    # Та же форма хэша в обход слоя: `CHECK` обязан отказать и прямому `INSERT`. Иначе «битая
    # строка» остаётся достижимой правкой строки, и различие из `ADR-016` п. 7 недостижимо.
    for битый in BAD_HASHES[:3]:
        with pytest.raises(IntegrityError) as ошибка:
            db.execute(
                text("INSERT INTO backup_codes (id, user_id, code_hash) " "VALUES (:id, :u, :h)"),
                {"id": uuid.uuid4(), "u": user.id, "h": битый},
            )
        assert _CHECK_HASH in str(ошибка.value), (
            f"отказ пришёл не из ограничения формы хэша {_CHECK_HASH}: базу битая строка "
            f"пропускает: {ошибка.value}"
        )
        db.rollback()
    assert _строки_из_базы(engine, user.id) == [], "после отказов базы в таблице остались строки"

    # Штатный путь после всех отказов работает: отказы не сломали саму вставку.
    хэш = hash_backup_code(new_backup_codes(1)[0])
    SqlStore(db).insert_backup_code_hashes(user.id, (хэш,))
    db.commit()
    строки = _строки_из_базы(engine, user.id)
    assert len(строки) == 1, "штатная вставка после отказов не прошла или прошла дважды"
    assert строки[0][1] == хэш, "штатная вставка записала другой хэш"


def test_дубликат_в_пачке_отклоняется_до_базы_а_между_пачками_его_держит_индекс(
    db: Session, engine: Engine, captured: tuple[list[str], list[str]]
) -> None:
    """Повтор внутри пачки — отказ приложения, повтор между пачками — отказ уникального индекса.

    §8.2: «10 разных». Слой доходит до базы с готовым набором хэшей, и `UniqueViolation` посреди
    запроса означал бы откат транзакта на половине вставленных строк. Между пачками слой дубликат
    не видит (таблицу он не читает), и его держит `uq_backup_codes_user_id_code_hash` — проверка
    обязана убедиться, что индекс работает, а не только что фильтр есть в коде.
    """
    user = _учётка(db, suffix="dup")
