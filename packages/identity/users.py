#: Сценарий входа TZ §9: «неверный пароль (5 попыток) → блокировка с объяснением». Тот же
#: счётчик, что и §8.2 для кодов 2FA («5 неудачных кодов подряд»).
MAX_FAILED_ATTEMPTS: Final = 5

#: Срок блокировки входа. §8.2 задаёт 15 минут для кодов 2FA; для неудачных паролей срок в ТЗ
#: не был назван и выбран заказчиком таким же (ask `633f8d2b`, 2026-11-21), чтобы на обе
#: блокировки пользователь получал один и тот же ответ.
LOCK_DURATION: Final = timedelta(minutes=15)


class LoginLockedError(RuntimeError):
    """Вход заблокирован. `until` — момент, после которого вход снова возможен.

    Сообщение объясняет блокировку человеку (TZ §9: «счётчик попыток не показывается, но блокировка
    объясняется»), поэтому в нём нет числа оставшихся попыток — только срок.
    """

    def __init__(self, until: datetime) -> None:
        super().__init__(
            f"вход заблокирован до {until.isoformat()}; попытка ввода пароля до этого момента "
            "не выполняется"
        )
        self.until = until


# ─── логин как значение: формат, а не регистр (`T-105`) ──────────────────────────────────────

#: Верхняя граница длины логина. Колонка `users.login` — `citext` без CHECK (§4.1), поэтому
#: границу держит приложение. Она не косметика: логин печатается в списках (§9.3 п. 4 и п. 6),
#: попадает в метку аккаунта `otpauth://`-ссылки привязки (`totp_provisioning_uri`) и в
#: экранируемый HTML; без границы одна строка учётной записи сделала бы длинное значение в
#: любом из этих мест.
LOGIN_MAX_LEN: Final = 64

#: Минимальная длина. Три знака — наименьшее, что различает учётные записи в списке и не читается
#: как опечатка или как обрезанное значение; правила формата в ТЗ нет (§4.1 колонку не ограничивает),
#: поэтому минимум — решение агента, а не цитата из контракта.
LOGIN_MIN_LEN: Final = 3

#: Разрешённый алфавит. Только ASCII-безопасные знаки без `$` и без символов, которые значимы в
#: URL и в `otpauth://` (`/ ? # & = % @ + пробел`), — регистр разрешён, потому что равенство
#: логинов держит `citext` в схеме, а не приведение в домене (`ensure_role` в `authorization.py`
#: поступил бы так же: нормализация породила бы второй источник правды о том, что такое «тот же
#: логин"). Кириллица в алфавит не входит намеренно: `citext` сравнивает её по своему правилу,
#: а `casefold()` в домене — по своему, и расхождение двух правил на не-ASCII знаках означало бы
#: «приглашение адресовано одному логину, а учётная запись создана под другим».
LOGIN_RE: Final = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")


class LoginFormatError(ValueError):
    """Логин не подходит под формат: слишком короткий, слишком длинный, посторонние знаки.

    Тип — `ValueError`, а не доменная ошибка отказа (`AccessDeniedError`): это ошибка значения,
    которое передал вызывающий (форма, приглашение), а не состояние данных, которое сервис решает.
    """


def ensure_login_syntax(login: str) -> str:
    """Проверить формат логина и вернуть его же, ничего не меняя.

    Возврат «того же значения» — тот же приём, что `ensure_role`: проверка не должна
    незаметно чинить входные данные. Пустая строка после `strip()` — отдельная ветка, а не
    «слишком короткий»: форме с незаполненным полем нужен ответ про поле, а не про алфавит.

    Вызывается на границах, где логин появляется извне: приглашение, адресованное по логину
    (`new_invitation`), и принятие приглашения (`user_from_invitation`). В `new_user` эта
    проверка не стоит намеренно: у `new_user` есть и другие вызывающие (seed первой учётной
    записи, тесты домена), и решение о формате логина принимает тот, кто принимает значение от
    человека, а не тот, кто его записывает.
    """
    value = login.strip()
    if not value:
        raise LoginFormatError("логин пуст: значение поля не заполнено")
    if len(value) < LOGIN_MIN_LEN:
        raise LoginFormatError(
            f"логин короче {LOGIN_MIN_LEN} знаков: {value!r} — значение похоже на обрезанное"
        )
    if len(value) > LOGIN_MAX_LEN:
        raise LoginFormatError(
            f"логин длиннее {LOGIN_MAX_LEN} знаков: длина {len(value)} (колонка citext CHECK не держит)"
        )
    if not LOGIN_RE.fullmatch(value):
        raise LoginFormatError(
            f"логин {value!r} содержит недопустимые знаки: разрешены буквы, цифры и `._-`,"
            " первый знак — буква или цифра"
        )
    return value


def same_login(left: str, right: str) -> bool:
    """Одно ли это имя с учётом регистра (`citext` в схеме, §4.1).

    Сравнение — `casefold()`, и оно согласовано с алфавитом `LOGIN_RE`: на ASCII `casefold()` и
    правило `citext` дают один результат, поэтому доменное сравнение и уникальный индекс
    `uq_users_login` не могут разойтись. Для значений вне алфавита сравнение не определено —
    их отсекает `ensure_login_syntax`, а не эта функция.
    """
    return left.casefold() == right.casefold()


# ─── состояния учётной записи (§4.1, §1.2; `T-105`, `ADR-020`) ────────────────────────────────

#: Состояние, которое открывает доступ в консоль (§1.2: «`admin` одобряет учётную запись →
#: доступ открыт»). Единственное: состояний «почти активно» §4.1 не знает, и вводить их нельзя —
#: их пришлось бы перебирать в каждом маршруте.
CONSOLE_STATE: Final = "active"

#: Состояния принятого приглашения до шага одобрения: пароль установлен, второй фактор можно
#: привязывать, доступа в консоль нет. Именно это и есть «приглашение без одобрения не даёт ни
#: сессии, ни прав» (`REQ-identity-02`) в применимой форме: сессия шага `'password'`/`'totp'`
#: нужна, чтобы вообще дойти до привязки TOTP (§1.2 порядок «пароль → TOTP → одобрение»), а
#: прав она не даёт никаких, кроме обслуживания собственной учётной записи.
ONBOARDING_STATES: Final[frozenset[str]] = frozenset({"invited", "awaiting_approval"})

#: Состояния, которые закрывают вход целиком: вход администратором заблокирован (§9.3 п. 6) либо
#: учётная запись архивирована (§4.1 «удаление — только архивированием»). Оба отвечают одинаково
#: (§8.8: отказ не должен быть оракулом), поэтому различать их кодом входа незачем.
CLOSED_STATES: Final[frozenset[str]] = frozenset({"suspended", "archived"})

#: Закрытая таблица переходов (§1.2, §4.1; обоснование каждого ребра — `ADR-020` п. 3).
#: Пустое множество означает терминальное состояние: `archived` никуда не переводится, потому что
#: «разархивировать» — это второе одобрение, которого в §1.2 нет.
STATE_TRANSITIONS: Final[dict[str, frozenset[str]]] = {
    # Приглашение принято (пароль установлен): следующий шаг — привязка 2FA, и только она
    # ставит учётную запись в очередь одобрения (§1.2 «привязывает TOTP → admin одобряет").
    "invited": frozenset({"awaiting_approval", "archived"}),
    # Ожидание одобрения: либо одобрили, либо отказали архивированием. `suspended` из этого
    # состояния недоступен: блокировка снимает уже открытый доступ, а открывать было нечего.
    "awaiting_approval": frozenset({"active", "archived"}),
    "active": frozenset({"suspended", "archived"}),
    # Разблокировка возвращает ровно то состояние, из которого блокировали: `active`. Это
    # возможно потому, что в `suspended` учётная запись попадает только из `active`.
    "suspended": frozenset({"active", "archived"}),
    "archived": frozenset(),
}

#: Коды, которые возвращают предикаты отказа. Значение состояния вне домена §4.1 даёт отдельный
#: код — тот же приём, что `DENIAL_ROLE_OUTSIDE_DOMAIN` в `authorization.py`: неизвестное значение
#: нельзя молча решить как «разрешено» или как «заблокировано» по вкусу вызывающего.
ACCESS_CODES: Final[frozenset[str]] = frozenset(
    {"invited", "awaiting_approval", "suspended", "archived", "outside_domain"}
)

#: Отдельный код для «состояние не прочитано» (строки учётной записи нет). Не входит в
#: `ACCESS_CODES`: этот случай про отсутствие объекта, а не про значение поля.
NO_ACCOUNT_CODE: Final = "no_account"


class AccountStateError(RuntimeError):
    """Переход состояния невозможен или значение вне домена §4.1.

    Это ошибка вызывающего (или испорченных данных), а не пользователя: отказ пользователя
    выглядит как объяснение состояния, а этот случай обязан попасть в журнал процесса.
    """


class AccountAccessError(RuntimeError):
    """Состояние учётной записи закрывает доступ.

    `code` — из закрытого `ACCESS_CODES`: по нему интерфейс выбирает объяснение, а журнал
    различает «ждёт одобрения», «заблокирована» и «данные повреждены» (`outside_domain`). В
    сообщении состояния нет: ответ наружу собирает слой представления, и он же решает, что
    показывать (§9: состояние внятное; §8.8: без утечки чужих данных).
    """

    def __init__(self, code: str) -> None:
        super().__init__(f"доступ закрыт состоянием учётной записи (код: {code})")
        self.code = code


def ensure_account_state(value: str) -> str:
    """Проверить, что состояние входит в домен §4.1, и вернуть его же (без нормализации).

    CHECK-ограничение `ck_users_state` отклонит такое же значение на `INSERT`/`UPDATE`, но
    ценой `IntegrityError` посреди учётной операции и с текстом, который человек в интерфейсе
    не прочитает (`ADR-017` п. 4 тот же довод применяет к ролям).
    """
    if value not in USER_STATES:
        raise AccountStateError(
            f"состояние {value!r} вне закрытого набора {sorted(USER_STATES)} (TZ §4.1)"
        )
    return value


def state_allows_login(state: str) -> bool:
    """Даёт ли состояние право вводить пароль (шаги `'password'` и `'totp'`).

    Значение вне домена отвечает `False` — отказ, а не ошибка: на входе у нас нет права даже
    называть состояние, а «неизвестное состояние» и «доступ закрыт» для посетителя должны
    отвечать одинаково.
    """
    return state in ONBOARDING_STATES or state == CONSOLE_STATE


def login_closed_reason(user: User | None) -> str | None:
    """Почему вход закрыт, либо `None`, если состояние вход не закрывает.

    Возвращает код, а не исключение: для слоя входа «состояние закрыто» — то же событие, что
    неверный пароль (ответ обязан быть неотличим, §8.8), и вызывающему нужен код для журнала, а
    не путь с пробросом исключения сквозь ветку перебора.

    `None`-объект — случай «строки учётной записи нет»: код `no_account`. В нормальном входе его
    быть не может (поиск по логину), но вызывающий обязан обработать его так же, как закрытое
    состояние, иначе «учётной записи нет» станет различимым ответом.
    """
    if user is None:
        return NO_ACCOUNT_CODE
    state = user.state
    if state in CLOSED_STATES:
        return state
    if state_allows_login(state):
        return None
    return "outside_domain"


def ensure_console_access(user: User) -> None:
    """Проверить, что состояние открывает доступ в консоль (`state='active'`).

    Второй слой поверх шага входа: сессия `'full'` уже означает «введён второй фактор», но не
    означает «учётная запись одобрена и не заблокирована». Порядок важен: проверка состояния
    обязана наступить до любого обращения к данным, ради которых маршрут существует
    (`ADR-017` п. 3) — иначе отказ стал бы оракулом существования объекта.

    Разблокировка и одобрение применяются к живому сеансу немедленно именно потому, что
    решение принимается на каждом запросе, а не один раз при входе (тот же довод, что у
    `enforce_role`: кэш состояния в процессе дал бы окно, в котором заблокированный человек
    оставался бы вошедшим до перезапуска `web`).
    """
    state = user.state
    if state == CONSOLE_STATE:
        return
    if state in ONBOARDING_STATES or state in CLOSED_STATES:
        raise AccountAccessError(state)
    raise AccountAccessError("outside_domain")


def move_account_state(user: User, *, to: str) -> None:
    """Перевести учётную запись в состояние, если переход разрешён таблицей.

    Единая точка смены `state`: имена публичных действий (`approve_account`,
    `suspend_account`, `unsuspend_account`, `archive_account`) тонкие обёртки над ней, поэтому
    правило «куда можно» живёт в одном месте и не разносится по обработчикам.

    Атомарности здесь нет сознательно, и это надо помнить вызывающим из `apps/web`: функция
    решает, *разрешён* ли переход, а не *выиграл* ли он гонку. Два параллельных одобрения или
    «одобрение против отзыва приглашения» обязан разрешать guarded-`UPDATE` слоя доступа с
    условием по прежнему состоянию — ровно как `ADR-016` п. 7 сделал с резервными кодами и
    `ADR-013` — с шагом кода. Где именно это нужно, записано в `docs/HANDOFF.md §2`.

    `updated_at` при этом ведёт ORM (`onupdate=now()` в модели): отдельной отметки о смене
    состояния схема не держит, и заводить её без требования нельзя — см. `ADR-020` п. 6 про
    отсутствие DDL в этом срезе.

    Времени у перехода нет сознательно: отметки («когда одобрили») ставит тот переход, у которого
    отметка есть (`approve_account`), и хранить «когда заблокировали» отдельной колонкой означало
    бы второй источник правды о состоянии рядом с самим состоянием.
    """
    ensure_account_state(to)
    current = user.state
    ensure_account_state(current)
    if to not in STATE_TRANSITIONS[current]:
        raise AccountStateError(
            f"переход состояния {current!r} → {to!r} не определён (§1.2, ADR-020 п. 3)"
        )
    user.state = to


def _ensure_state_is(user: User, *, expected: str, action: str) -> None:
    """Проверить исходное состояние действия администратора.

    Нужно там, где таблица переходов не различает вызовы: в `active` ведут и одобрение
    (`awaiting_approval`), и разблокировка (`suspended`), и без этой проверки неверный вызов
    молча стал бы вторым решением, которого администратор не принимал.
    """
    if user.state != expected:
        raise AccountStateError(
            f"{action} можно учётную запись в состоянии {expected!r}, сейчас: {user.state!r} (§1.2)"
        )


def approve_account(user: User, *, approved_by: UUID, now: datetime | None = None) -> None:
    """Одобрить учётную запись (§1.2 шаг 2): `awaiting_approval` → `active`.

    Отметки `approved_by`/`approved_at` ставятся только здесь: §4.1 держит их как «кто одобрил и
    когда», и значение вне перехода означало бы «одобрено, но не активно» или «активно, но не
    одобрено» — два состояния вместо одного факта.

    Одобрение возможно только из `awaiting_approval`, и это не бюрократия: в очередь одобрения
    учётную запись ставит подтверждённая привязка 2FA (§1.2 порядок «пароль → TOTP → одобрение»),
    поэтому одобрить то, что второй фактор ещё не привязало, — значит выдать доступ учётной
    записи, у которой второго фактора нет (сессия `'full'` без привязки не выпускается, но
    следующая попытка входа такой учётной записи уже не упрётся в «сначала привяжи»).

    `approved_by` — UUID одобрившего; ссылка FK `RESTRICT` не даёт удалить администратора,
    одобрившего чужую учётную запись, поэтому след действия переживает его собственную
    архивацию. Собственный `id` в этом параметре — осмысленное значение только для первой
    учётной записи (bootstrap, `ADR-020` п. 5): другого администратора в системе ещё нет.
    """
    move_account_state(user, to=CONSOLE_STATE)
    moment = _moment(now)
    user.approved_by = approved_by
    user.approved_at = moment


def suspend_account(user: User) -> None:
    """Заблокировать вход (§9.3 п. 6 «блокировка»): `active` → `suspended`.

    Исходное состояние проверяется явно, а не только таблицей переходов: `move_account_state`
    отвечает на вопрос «разрешён ли переход в эту точку», а вызов обязан отвечать и на «из какой
    точки»: в `active` ведут и одобрение, и разблокировка, поэтому неверный вызов без такой
    проверки стал бы решением, которого администратор не принимал.

    Счётчик неудач и `locked_until` эта функция не трогает: блокировка перебора (`T-101`) и
    блокировка администратором — разные состояния, и «разблокировать» человека после
    административной блокировки не должна возможность одной неудачной попытки ввода пароля.

    Живые сессии при этом отзывались не здесь, а вызывающим слоем: `revoke_sessions` живёт в
    `packages/identity/sessions.py`, который импортирует этот модуль, поэтому обратный импорт
    создал бы цикл. Требование немедленности (§8.3) закрывают два слоя: отзыв в мутации
    администратора и `ensure_console_access` на каждом запросе.
    """
    _ensure_state_is(user, expected="active", action="блокировать")
    move_account_state(user, to="suspended")


def unsuspend_account(user: User) -> None:
    """Снять блокировку (§9.3 п. 6 «разблокировка»): `suspended` → `active`.

    Возврат именно в `active` оправдан таблицей переходов: в `suspended` учётная запись могла
    попасть только из `active`, то есть была одобрена раньше. Отметки `approved_by`/`approved_at`
    при этом не меняются: они отвечают на вопрос «кто одобрил доступ», а не «когда его
    включили снова» — повторное одобрение стёрло бы автора первого решения.
    """
    _ensure_state_is(user, expected="suspended", action="разблокировать")
    move_account_state(user, to=CONSOLE_STATE)


class LastAdministratorError(AccountStateError):
    """Закрытие доступа оставило бы систему без единого живого администратора.

    Отдельный класс — чтобы слой представления умел объяснить причину словами «вы последний
    администратор, сначала передайте права другому», а не общим «переход невозможен». При этом
    это подкласс `AccountStateError`, поэтому обработчик, который ловит только его, тоже
    удерживает отказ: забыть про проверку нельзя молча, можно только не сказать причину.
    """


def ensure_not_last_admin(candidate: User, *, active_admins_left: int) -> None:
    """Не давать закрыть доступ единственному администратору системы (`ADR-020` п. 6).

    Проверка обязана быть в домене, а не в шаблоне кнопки: блокировка и архивирование применяются
    к живому человеку, и единственный `admin`, ушедший в `suspended` или `archived`, оставил бы
    систему без того, кто способен включить её обратно. Восстановление тогда возможно только
    правкой таблицы руками под ролью-владельцем — то есть операцией, у которой нет ни журнала,
    ни отработанного порядка (`ADR-006`, `ADR-018`).

    `active_admins_left` — счёт **до** перехода, уже без этой учётной записи: его даёт запрос
    `Store.active_admin_count(except_user_id=...)`. Именно вызывающий обязан передать число до
    перехода, потому что после `suspend_account` поле `state` уже изменено и пересчитать его тем
    же запросом нельзя — второй запрос вернул бы ноль при любом раскладе.

    Считаются только `active` (а не все строки с ролью `admin`): архивированный или заблокированный
    администратор пригласить кого-то не может, поэтому «есть ещё один admin в `archived`» правом
    не является. Роль проверяется здесь же, а не в вызывающем коде: для `operator` переход никогда
    не лишает систему администратора, и проверять счёт для него — значит отказать зря.
    """
    if candidate.role != ROLE_ADMIN:
        return
    if active_admins_left < 0:
        raise ValueError("число администраторов не может быть отрицательным")
    if active_admins_left == 0:
        raise LastAdministratorError(
            f"{candidate.login}: это последняя учётная запись с ролью {ROLE_ADMIN!r} в состоянии "
            f"{CONSOLE_STATE!r}; закрытие доступа оставило бы систему без администратора (§1.2, §4.1)"
        )


def archive_account(user: User) -> None:
    """Архивировать учётную запись (§4.1 «удаление — только архивированием», конец).

    Так администратор отказывает ожидающему (§1.2) и так же выводят из состава того, кому
    доступ уже открывали: строка остаётся, потому что на неё ссылаются сессии, привязки,
    приглашения и журнал аудита (`users`-комментарий модели: «строка не удаляется»). Удаление
    строки сделало бы журнал и список отзывов незаполняемыми, а FK `RESTRICT` ему и не даёт.

    Переход разрешён из любого состояния, кроме `archived`, и терминален: «разархивировать»
    означало бы второе одобрение без второго шага (§1.2 его не описывает), то есть молча
    изобрести переход, которого в контракте нет.
    """
    move_account_state(user, to="archived")


def _moment(now: datetime | None) -> datetime:
    """«Сейчас» или переданное время — всегда осознанный UTC (§2.7)."""
    return ensure_aware(now)


def new_user(
    *,
    login: str,
    password: str,
    role: str,
    email: str | None = None,
    display_name: str | None = None,
    state: str = "invited",
    now: datetime | None = None,
) -> User:
    """Создать учётную запись прикладным слоем, а не конструктором ORM напрямую.

    Причина не в удобстве: у только что созданного объекта SQLAlchemy счётчик ещё не применён
    (`DEFAULT 0` вступает в силу при `INSERT`), и объект, созданный напрямую через `User(...)`,
    приходит с `failed_attempts is None` — доменная арифметика на нём падает. Поэтому точка входа
    одна, и она ставит счётчик явно.

    Пароль проходит §8.1 до создания объекта: политика применяется и здесь, и в
    `apply_new_password` — оба входа в домен обязаны её требовать.

    `state` по умолчанию — `invited` (§1.2: приглашение принято, шага одобрения ещё нет). Домен
    `role` проверяется здесь с `T-106` (`packages/identity/authorization.ensure_role`): ровно три
    роли (§1.1), и проверка обязана наступить до `INSERT`, потому что CHECK схемы отклонил бы
    значение только ценой `IntegrityError` посреди учётной операции. С `T-105` так же проверяется и
    `state` (`ensure_account_state`): правильные *переходы* между состояниями держит таблица
    `STATE_TRANSITIONS`, а допустимость самого значения — домен и CHECK `ck_users_state`.

    Формат логина здесь не проверяется сознательно: решение о формате принимает тот, кто принимает
    значение от человека (`ensure_login_syntax` вызывают границы, где логин приходит извне).
    """
    ensure_role(role)
    ensure_account_state(state)
    check_password_policy(password, login=login, email=email)
    return User(
        login=login,
        email=email,
        display_name=display_name,
        role=role,
        state=state,
        # хэш считается до создания объекта: переходного состояния «пользователь есть, а
        # корректного хэша ещё нет» быть не должно — CHECK-ограничение схемы отвергает пустое
        # значение, и поймали бы мы его только на INSERT (§4.1: `password_hash NOT NULL`).
        password_hash=hash_password(password),
        password_updated_at=_moment(now),
        failed_attempts=0,
        locked_until=None,
    )


def active_lock_until(user: User, *, now: datetime | None = None) -> datetime | None:
    """До какого момента вход заблокирован, либо `None`, если не заблокирован.

    Истёкшая блокировка — то же самое, что её отсутствие: отдельного признака «разблокирован» в
    схеме нет, и не должно быть (два источника правды).
    """
    moment = _moment(now)
    if user.locked_until is None:
        return None
    if user.locked_until <= moment:
        return None
    return user.locked_until


def ensure_login_allowed(user: User, *, now: datetime | None = None) -> None:
    """Проверить, что входить можно, до того как сравнивать пароль.

    Порядок обязателен: пока блокировка активна, пароль не проверяется вообще — иначе переборщик
    получает бесплатный канал для проверки угаданных паролей, а счётчик перестаёт иметь смысл.
    """
    until = active_lock_until(user, now=now)
    if until is not None:
        raise LoginLockedError(until)


def register_login_failure(user: User, *, now: datetime | None = None) -> datetime | None:
    """Зафиксировать неудачную попытку ввода пароля.

    Возвращает момент, до которого заблокирован вход, если блокировка наступила этой попыткой,
    иначе `None`. Вызывающий обязан записать событие журнала (`T-109`: неудачные попытки —
    обязательная запись, §8.7) и, позже, отправить уведомление.

    Счётчик при наступлении блокировки обнуляется намеренно: иначе после истечения срока ровно
    одна неудачная попытка блокировала бы вход снова, и пользователь получал бы вечную
    блокировку без объяснимой причины. Отсчёт после разблокировки начинается заново.

    Время проверяется до мутации: вызов с наивным `datetime` (§2.7) не должен менять счётчик
    — иначе половина вызова уже испорчена, а ошибка появляется где-то позже.
    """
    moment = _moment(now)
    user.failed_attempts += 1
    if user.failed_attempts < MAX_FAILED_ATTEMPTS:
        return None
    user.failed_attempts = 0
    user.locked_until = moment + LOCK_DURATION
    return user.locked_until


def register_login_success(user: User, *, now: datetime | None = None) -> None:
    """Зафиксировать успешный ввод пароля: снять счётчик неудач и снятую блокировку.

    Успех во время активной блокировки — ошибка вызывающего, а не пользователя: вход под
    заблокированной учётной записью обязан был быть отклонён в `ensure_login_allowed`. Поэтому
    здесь то же исключение, а не тихое снятие блокировки.
    """
    ensure_login_allowed(user, now=now)
    user.failed_attempts = 0
    user.locked_until = None


def clear_login_lock(user: User) -> None:
    """Снять блокировку вручную (страница администратора: «блокировка/разблокировка», §9).

    Вызывается вместе с записью в `audit_log` (§8.7) — действие администратора без записи журнала
    неотличимо от правки базы руками.
    """
    user.failed_attempts = 0
    user.locked_until = None


def apply_new_password(user: User, password: str, *, now: datetime | None = None) -> None:
    """Проверить пароль по §8.1 и установить хэш Argon2id.

    Логин и e-mail для правила «пароль = логин/домен» берутся из самой записи, а не из параметров:
    политика не должна зависеть от того, догадался ли вызывающий их передать.

    Блокировку перебора эта функция не снимает: снятие — отдельное действие (`clear_login_lock`),
    иначе блокировка превращалась бы в препятствие, которое обходится сменой пароля.

    Отзывы сессий и требование TOTP при смене пароля (§8.1) здесь не делаются: это уровни `T-102`
    (сессии) и `T-103` (TOTP), и соответствующий шаг будет в них, а не здесь.
    """
    # время проверяется до хэширования: 25 мс Argon2, потраченные на заведомо неверный вызов, —
    # мелочь рядом с состоянием «хэш поменялся, а отметки времени нет».
    moment = _moment(now)
    check_password_policy(password, login=user.login, email=user.email)
    user.password_hash = hash_password(password)
    user.password_updated_at = moment
