"""Учётная запись: вход, неудачи, блокировка перебора и состояния допуска
(TZ §8.1, §9; задачи `T-101` и `T-105`).

Модуль меняет объект ORM из `storage` и **не открывает соединение** с базой: коммит и запись в
`audit_log` остаются за вызывающим слоем (веб-вход — `T-102`, события журнала — `T-109`). Иначе
одна функция делала бы две разные вещи, а «неудачная попытка» не попала бы в журнал вместе со
сменой счётчика — и наоборот.

Почему счётчик неудач живёт в столбце базы, а не в памяти процесса:

* процессов, которые трогают вход, несколько (сейчас `web`, позже — API-маршруты), и в памяти они
  расходились бы;
* рестарт контейнера обнулял бы счётчик, а блокировка перебора, которая снимается рестартом, —
  не блокировка (TZ §13: «атака на вход, 100 запросов → блокировки»).

Чего здесь сознательно нет:

* временного бана по IP («3 неудачные попытки с одного IP за 5 минут», §8.2): это уровень периметра
  (fail2ban/Caddy, `docs/runbook/*`), а не уровень учётной записи, и в одной таблице `users` он не
  живёт;
* уведомление в Telegram при блокировке (тип события `AUTH_LOCKED`, TZ §10): канал оповещений —
  `notifications` (M4), здесь остаётся только факт блокировки и её срок;
* разблокировка «прошла по времени» отдельным процессом: истечение `locked_until` проверяется на
  входе, потому что хранить «разблокирован» отдельным флагом — значит иметь два источника правды.

С состояниями учётной записи (`state`, §4.1 и §1.2) модуль работает с `T-105`: закрытая таблица
переходов, отказ там, где перехода нет, и два предиката допуска (`login_closed_reason`,
`ensure_console_access`). Обоснование перечня переходов и следствия — `docs/adr/ADR-020`.
Чего в этом контуре нет: самих приглашений (`packages/identity/invitations.py` — ссылка, срок,
одноразовость), атомарности переходов (её держит guarded-`UPDATE` слоя доступа, как в
`ADR-016` п. 7 для резервных кодов) и отзыва сессий при блокировке (оркестрация — уровень
`apps/web`, потому что `packages/identity/sessions.py` импортирует этот модуль, а не наоборот).

Значения `MAX_FAILED_ATTEMPTS` и `LOCK_DURATION` — константы, не настройки: §8.2 задаёт 15 минут
для кодов 2FA, тот же срок заказчик выбрал для неудачных паролей (ask `633f8d2b`, 2026-11-21), и
делать из этого переключатель, который можно выключить конфигом, нельзя.
"""

from __future__ import annotations

import re
from datetime import datetime, timedelta
from typing import Final
from uuid import UUID

from packages.common.clock import ensure_aware
from packages.identity.authorization import ROLE_ADMIN, ensure_role
