# ─── параметры ссылки (§1.2) ──────────────────────────────────────────────────────────────────

#: §1.2: «срок действия 14 дней». Считается от выпуска и не продлевается: продлённый срок
#: превратил бы одноразовую ссылку в постоянный канал допуска, а «отзыв по действию
#: администратора» (§1.2) перестал бы быть единственным способом закрыть дверь.
INVITATION_TTL: Final = timedelta(days=14)

#: 256 случайных бит (§8.3 считает стойкость значений доступа именно так; для ссылки другого
#: основания нет: она даёт право создать учётную запись).
INVITATION_TOKEN_BITS: Final = 256
_TOKEN_BYTES: Final = INVITATION_TOKEN_BITS // 8

#: Форма значения ссылки: те же 43 символа base64url, что у куки сессии. Проверяется до похода в
#: базу — обрезанное или постороннее значение дало бы «приглашение не найдено» с другой причиной,
#: и отличить «ссылку испортили при переносе» от «такого приглашения никогда не было» было бы
#: нечем.
INVITATION_TOKEN_RE: Final = re.compile(r"[A-Za-z0-9_-]{43}")

#: Коды причин, по которым приглашение нельзя принять. Набор закрытый и проверяется тестом на
#: полноту: по нему слой представления выбирает объяснение, а журнал различает исходы
#: `REQ-identity-03` («результат» попытки).
INVITATION_UNUSABLE_CODES: Final[frozenset[str]] = frozenset({"expired", "used", "revoked"})

# ─── метка получателя (§1.2: «e-mail или логин») ──────────────────────────────────────────────

#: Верхняя граница e-mail-метки. CHECK в схемы на колонку нет (§4.1), а значение печатается в
#: списке приглашений (§9.3 п. 6) и попадает в правило «пароль = логин/домен» (§8.1):
#: неограниченное значение означало бы неограниченную строку в HTML и в сравнении пароля.
EMAIL_MAX_LEN: Final = 254

#: Минимальный разбор адреса: «что-то @ что-то . что-то». Это не RFC 5322 и не проверка
#: существования ящика — доставки в системе нет (см. шапку модуля). Проверка отвечает на один
#: вопрос: выглядит ли значение адресом, чтобы «кому выдано» в журнале и в списке не стало
#: мусорной строкой, и чтобы домен из него действительно был доменом для §8.1.
EMAIL_RE: Final = re.compile(r"[^@\s.][^@\s]*@[^@\s]+\.[A-Za-z]{2,}")

# ─── ошибки ───────────────────────────────────────────────────────────────────────────────────


class InvitationError(RuntimeError):
    """Ошибка приглашения вообще: общий предок, чтобы вызывающий умел перехватить класс целиком."""


class InvitationTargetError(InvitationError, ValueError):
    """Приглашение ни кому не адресовано: ни e-mail, ни логина (§1.2, CHECK `ck_invitations_target_present`).

    Наследуется от `ValueError`, потому что это ошибка переданных значений, а не состояния
    данных: её обязан ловить тот, кто собирал форму, а не обработчик отказа посетителю.
    """


class MalformedInvitationTokenError(ValueError):
    """Значение ссылки не похоже на выпущенное: другой алфавит, другая длина.

    Отдельный тип, а не `InvitationUnusableError`: у вызывающего нет права называть
    «неиспорченную ссылку, которой нет в базе» и «значение, которое нельзя было выпустить» одним
    ответом — первое означает чужую попытку, второе собственную ошибку.
    """


class InvitationUnusableError(InvitationError):
    """Приглашение нельзя принять. `code` — код причины (`INVITATION_UNUSABLE_CODES`).

    Различие причин **можно** показать человеку, который предъявил ссылку: чтобы спросить, нужно
    угадать 256 случайных бит, то есть спрашивающий уже держит ссылку в руках. Другое дело —
    значения
    входа (сессия, резервный код), где различие причин было бы оракулом: там ответ один на все
    исходы (`ADR-016` п. 5). Здесь объяснение нужнее: «срок истёк» и «ссылку отозвали» ведут к
    разным действиям администратора, а просить человека угадывать, какое из двух случилось,
    значит заставлять его звонить.
    """

    code: ClassVar[str] = "unusable"

    def __init__(self, at: datetime | None, detail: str) -> None:
        at_text = "момент не записан" if at is None else at.isoformat()
        super().__init__(f"{detail} (граница: {at_text})")
        self.at = at


class InvitationExpiredError(InvitationUnusableError):
    """Истёк срок 14 дней (§1.2). Просрочка выводится из `expires_at`, отдельного состояния нет."""

    code: ClassVar[str] = "expired"

    def __init__(self, at: datetime) -> None:
        super().__init__(at, "срок действия приглашения истёк (§1.2, 14 дней)")


class InvitationUsedError(InvitationUnusableError):
    """Ссылку уже использовали: учётная запись создана (§1.2 «одноразовая»)."""

    code: ClassVar[str] = "used"

    def __init__(self, at: datetime | None) -> None:
        super().__init__(at, "приглашение уже использовано (§1.2, ссылка одноразовая)")


class InvitationRevokedError(InvitationUnusableError):
    """Приглашение отозвал администратор (§1.2 «отзыв по действию администратора»)."""

    code: ClassVar[str] = "revoked"

    def __init__(self, at: datetime | None) -> None:
        super().__init__(at, "приглашение отозвано администратором (§1.2)")


class InvitationStateError(InvitationError):
    """Переход внутри приглашения невозможен: значение `state` вне домена или отзыв использованного."""


# ─── отзыв: что означает состояние строки для действия администратора ─────────────────────────

#: Коды исхода отзыва (§1.2 «отзыв по действию администратора», `ADR-020` п. 4).
#: Набор закрыт и отделён от `INVITATION_UNUSABLE_CODES`: «нельзя принять ссылку» и «нельзя
#: отозвать выпуск» — разные вопросы. Просроченный, но ещё `pending` выпуск отзывать **можно**
#: (переход `pending → revoked`), поэтому срока здесь нет вовсе: он относится к приёму ссылки,
#: а не к отзыву.
REVOCATION_OUTCOMES: Final[frozenset[str]] = frozenset(
    {"revocable", "already_revoked", "used", "outside_domain"}
)


def revocation_outcome(record: Invitation) -> str:
    """Что текущее состояние строки означает для отзыва — кодом из `REVOCATION_OUTCOMES`.

    Функция ничего не меняет и нужна представлению (`T-105`, срез `R7b`): сам переход делает
    guarded-`UPDATE` слоя доступа (`Store.revoke_invitation_row`, `WHERE state = 'pending'`),
    а чем является для человека «строка уже не открыта» — ошибкой, «уже отозвано» или отказом,
    решает домен, а не обработчик. Иначе правило «отзыв использованного запрещён» переехал бы в
    разметку и разошёлся бы с `revoke_invitation` при первой же правке (`ADR-020` п. 1:
    «маршруты не знают правил перехода»).

    Порядок чтения состояния тот же, что у `ensure_invitation_open`: сначала состояние, потом всё
    остальное. `outside_domain` — постороннее значение колонки (`ck_invitations_state` в живой базе
    его не пропускает, значит это испорченные данные): представление обязано ответить на него
    отказом, а не «ну не отозвано же».
    """
    state = record.state
    if state not in INVITATION_STATES:
        return "outside_domain"
    if state == "revoked":
        return "already_revoked"
    if state == "used":
        return "used"
    return "revocable"


# ─── значение ссылки: выпуск и хэш ─────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class IssuedInvitation:
    """Выпущенное приглашение: строка `invitations` и одноразовое значение ссылки.

    `secret` существует ровно один момент — между выпуском и показом администратору (§9.3 п. 6:
    администратор копирует ссылку). `repr` маскируется по той же причине, что `IssuedSession`:
    печать структуры данных — самый частый способ унести материал доступа в журнал.
    """

    record: Invitation
    secret: str

    def __repr__(self) -> str:
        return (
            f"IssuedInvitation(invitation_id={self.record.id}, state={self.record.state!r}, "
            "secret='<скрыто>')"
        )


def invitation_secret() -> str:
    """Новое значение ссылки: 256 случайных бит, base64url без «=»."""
    return secrets.token_urlsafe(_TOKEN_BYTES)


def ensure_invitation_secret(secret: str) -> None:
    """Проверить форму значения ссылки до обращения к базе."""
    if not INVITATION_TOKEN_RE.fullmatch(secret):
        raise MalformedInvitationTokenError(
            "значение ссылки не соответствует формату: ожидаем 43 символа base64url"
        )


def invitation_token_hash(secret: str) -> str:
    """SHA-256 от значения ссылки в hex (64 символа) — то, что живёт в `invitations.token_hash`.

    Хэшируются ровно те байты, что пришли человеку (UTF-8 от строки), иначе выпуск и приём
    разойдутся. Форма проверяется здесь же: просумев хэш обрезанного значения, мы получили бы
    «приглашения нет» вместо «ссылку испортили».
    """
    ensure_invitation_secret(secret)
    return hashlib.sha256(secret.encode("utf-8")).hexdigest()


def ensure_email_syntax(email: str) -> str:
    """Проверить e-mail-метку и вернуть её же (без нормализации регистра, §4.1 `citext`)."""
    value = email.strip()
    if not value:
        raise InvitationTargetError("e-mail не заполнен")
    if len(value) > EMAIL_MAX_LEN:
        raise InvitationTargetError(f"e-mail длиннее {EMAIL_MAX_LEN} знаков: длина {len(value)}")
    if not EMAIL_RE.fullmatch(value):
        raise InvitationTargetError(
            f"e-mail {value!r} не похож на адрес: нужно `домен@хост.зона` без пробелов"
        )
    return value


# ─── выпуск приглашения (§9.3 п. 6: «создание приглашения») ───────────────────────────────────


def new_invitation(
    *,
    created_by: UUID,
    role: str,
    email: str | None = None,
    login: str | None = None,
    now: datetime | None = None,
) -> IssuedInvitation:
    """Выпустить приглашение и вернуть строку схемы вместе со значением ссылки.

    Роль назначает приглашение, а не выбирает приглашённый (§1.1: роли выдаёт `admin`). Поэтому
    `role` проверяется здесь же, до `INSERT`: `ck_invitations_role` отклонил бы её ценой
    `IntegrityError` посреди административной операции, а человек увидел бы текст базы
    (`ADR-017` п. 4 тот же довод применяет к ролям учётной записи).

    Ровно один адресат обязателен: §1.2 пишет «e-mail или логин», и CHECK
    `ck_invitations_target_present` требует заполненности. Оба сразу — тоже осмысленно (письмо
    с указанием логина), и домен это не запрещает; непереносимо только «ни одного».

    Значение ссылки возвращается и нигде, кроме этого возврата, не появляется: в `record` лежит
    хэш. Момент выпуска (`now`) задаёт `expires_at` по прикладным часам, а `created_at` ведёт база
    (`server_default now()`): они могут разойтись на доли секунды, и это намеренно — срок считается
    от значения, которое видно в той же строке, а не от второй колонки, которую сравнивать не с чем.
    """
    moment = ensure_aware(now)
    ensure_role(role)
    secret = invitation_secret()

    target_email: str | None = None
    target_login: str | None = None
    if email is not None:
        target_email = ensure_email_syntax(email)
    if login is not None:
        # `LoginFormatError` не перекручивается: это ошибка значения, и вызывающий обязан
        # показать её как ошибку поля формы, а не как отказ приглашения.
        target_login = ensure_login_syntax(login)
    if target_email is None and target_login is None:
        raise InvitationTargetError(
            "приглашение ни кому не адресовано: нужен e-mail или логин (§1.2)"
        )

    record = Invitation(
        email=target_email,
        login=target_login,
        role=role,
        token_hash=invitation_token_hash(secret),
        state="pending",
        expires_at=moment + INVITATION_TTL,
        created_by=created_by,
    )
    # `secret` — то самое значение, от которого посчитан `token_hash`: второго способа получить
    # его у вызывающего нет, а `IssuedInvitation.secret` обязан с ним совпадать (проверка в тесте).
    return IssuedInvitation(record=record, secret=secret)


# ─── состояние приглашения: можно ли принять ──────────────────────────────────────────────────


def invitation_is_open(record: Invitation, *, now: datetime | None = None) -> bool:
    """Открыто ли приглашение: `pending`, не использовано, не отозвано и в сроке."""
    try:
        ensure_invitation_open(record, now=now)
    except InvitationUnusableError:
        return False
    return True


def ensure_invitation_open(record: Invitation, *, now: datetime | None = None) -> None:
    """Проверить, что приглашение можно принять; иначе — `InvitationUnusableError` с кодом причины.

    Порядок проверок фиксирован: сначала **состояние** (`used`, `revoked`), потом **срок**. Порядок
    не косметика: использованная ссылка, у которой истёк срок, обязана отвечать «уже
    использовано», а не «истекло» — второе намекнуло бы, что можно выпустить заново по той же
    ссылке, и подтолкнуло бы администратора к повторному выпуску дубля.

    Значение `state` вне домена §4.1 даёт `InvitationStateError`, а не «нельзя принять
    молча»: постороннее значение в колонке — повреждение данных, и оно обязано быть слышно
    (тот же приём, что `role_rank` в `ADR-017`).

    Граница срока — строгая: `expires_at <= сейчас` значит «истекло». Ровно в момент `expires_at`
    ссылка уже не действует, и это тот же выбор, что `ADR-009`/сессии сделали для границ
    живости: «граница включена» для срока смерти — всегда ложь.
    """
    moment = ensure_aware(now)
    state = record.state
    if state not in INVITATION_STATES:
        raise InvitationStateError(
            f"состояние приглашения {state!r} вне закрытого набора {sorted(INVITATION_STATES)}"
        )
    if state == "used":
        raise InvitationUsedError(record.used_at)
    if state == "revoked":
        raise InvitationRevokedError(None)
    if record.expires_at <= moment:
        raise InvitationExpiredError(record.expires_at)


def revoke_invitation(record: Invitation) -> None:
    """Отозвать приглашение (§1.2 «отзыв по действию администратора», §9.3 п. 6).

    Отзываются только `pending`. Повторный отзыв уже отозванного — состояние «уже отозвано», и
    оно возвращается без ошибки: действие администратора, которое ничего не меняет, дешевле
    описать идемпотентно, чем заставить интерфейс обрабатывать отказ ради отказа.

    Отзыв **использованного** приглашения запрещён, и это не бюрократия, а свойство учётной
    записи: по этой ссылке уже создали учётную запись и, возможно, вошли в систему. Поменять
    `state` обратно означало бы стереть факт выдачи доступа, то есть снять с журнала
    (`REQ-identity-03`) единственное, что он мог бы показать. Закрывать доступ в этом случае
    должен другой переход — состояние учётной записи (`suspend_account`, `archive_account`).

    Атомарность перехода та же, что у всех остальных: интерфейс обязан опираться на
    guarded-`UPDATE` слоя доступа (`WHERE state = 'pending'`), иначе «отзыв» проиграет гонку
    параллельному принятию ссылки и будет нарисован поверх уже созданной учётной записи.

    Исход читается через `revocation_outcome` — то же самое правило, по которому слой
    представления выбирает ответ: одна формулировка на домен и на представление, иначе
    «что такое отзывать» разошлось бы в двух местах.
    """
    outcome = revocation_outcome(record)
    if outcome == "already_revoked":
        return
    if outcome == "outside_domain":
        raise InvitationStateError(
            f"состояние приглашения {record.state!r} вне закрытого набора "
            f"{sorted(INVITATION_STATES)}"
        )
    if outcome == "used":
        raise InvitationStateError(
            "использованное приглашение не отзывается: учётная запись по нему уже создана (§1.2)"
        )
    record.state = "revoked"


# ─── принятое приглашение: какая учётная запись от него появляется ─────────────────────────────


def user_from_invitation(
    record: Invitation,
    *,
    login: str,
    password: str,
    now: datetime | None = None,
    claimed: bool = False,
) -> User:
    """Собрать учётную запись по приглашению: роль из приглашения, состояние `invited`.

    Функция **не** отмечает приглашение использованным и не трогает строку `invitations` вообще:
    право решить «ссылка истрачена» у guarded-`UPDATE` слоя доступа, а не у того, кто построил
    объект (шапка модуля). Поэтому порядок в обработчике среза `apps/web` обязан быть таким:
    найти по хэшу → проверить открытость (`ensure_invitation_open`) → заявить ссылку
    атомарным `UPDATE` → построить учётную запись → `add` + `commit` (`ADR-020` п. 4).

    Параметр `claimed` — про этот порядок, и он не косметика. Заявка ссылки меняет строку на
    `used`, а обязательный порядок требует строить учётную запись **после** заявки. Значит
    повторять после заявки обычную проверку открытости нельзя ни в одной половинке проверки:

    * в живой базе вызывающий держит объект, прочитанный до перехода, а `claim_invitation`
      намеренно идёт с `synchronize_session=False` (тот же приём, что у `claim_totp_step` и
      `spend_backup_code`: `SELECT` перед `UPDATE` добавил бы окно между чтением и переходом).
      То есть после заявки этот объект — устаревшее значение, и решение по нему принято быть
      не может;
    * в офлайн-зеркале (`MemoryStore`) строка и есть тот же объект, поэтому заявка меняет его
      состояние на `used`, и обычная проверка открытости отказала бы законному обработчику
      «приглашение уже использовано».

    Поэтому `claimed=True` означает «вызывающий выиграл guarded-`UPDATE` с `rowcount = 1`», и
    открытость в этом режиме уже решена дважды: явным `ensure_invitation_open` до заявки и
    условием `state = 'pending' AND expires_at > :now` внутри самого перехода. Режим `False`
    (значение по умолчанию) сохраняет прежнюю защиту для вызывающих без заявки: функция отказывает
    сама и не оставляет способа выдать учётную запись по ссылке, которую домен считает истёкшей,
    использованной или отозванной. Кто вправе передать `claimed=True`, описано в `ADR-021`.

    Роль берётся из приглашения (§1.1), e-mail — из приглашения (§1.2), состояние — `invited`
    (§4.1: «приглашение есть, шага одобрения ещё нет»). Логин: если приглашение адресовано по
    логину, приглашённый не может выбрать другой (`same_login` — сравнение по `citext`-правилу,
    §4.1); если только по e-mail, логин выбирает приглашённый, и тогда его формат проверяет
    `ensure_login_syntax`.

    `LoginFormatError` и `PasswordPolicyError` не переводятся в доменные отказы: обе означают
    «значение поля не подходит» и должны дойти до формы как ошибка поля, а не как отказ допуска.
    """
    if not claimed:
        ensure_invitation_open(record, now=now)
    presented = ensure_login_syntax(login)
    if record.login is not None and not same_login(presented, record.login):
        raise InvitationTargetError(
            "приглашение адресовано другому логину: выбрать своё имя нельзя (§1.2)"
        )
    return new_user(
        login=presented,
        password=password,
        role=record.role,
        email=record.email,
        state="invited",
        now=now,
    )
