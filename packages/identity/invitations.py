"""Приглашения закрытого допуска: ссылка, срок 14 дней, одноразовость, отзыв
(TZ §1.2, `REQ-identity-02`/`REQ-identity-03`, задача `T-105`, срез `R7a`).

Задача держит ровно одно правило системы: учётная запись не появляется сама. Строка `users`
возможна только как следствие приглашения, а полный доступ возможен только как следствие
одобрения (`ADR-020`). Этот модуль отвечает за первую половину — **приглашение**: значение
ссылки, её срок, состояние и то, какую учётную запись оно имеет право создать. Одобрение,
блокировка и архивирование — состояния учётной записи, `packages/identity/users.py`.

Значение ссылки: 256 случайных бит, base64url без «=» (43 символа) — та же форма, что у значения
куки сессии (`SESSION_TOKEN_RE` в `packages/identity/sessions.py`), и по той же причине: значение
попадает в URL и в буфер обмена, алфавит base64url не требует экранирования, а постоянная длина
делает обрезку заметной. В базе живёт только SHA-256 от него (`invitations.token_hash`,
`uq_invitations_token_hash`), поэтому утечка дампа не отдаёт готовую ссылку допуска.

Ссылку доставляет **администратор вне системы**. Почтовой рассылки в стеке нет (§10 описывает
Telegram-канал управления, а не e-mail-транспорт), и выдумывать её здесь нельзя: адрес
`invitations.email` — метка получателя («кому это выдано»), а не канал доставки. Отсюда
следствие, которое надо держать в голове при правке этого модуля: проверка «ссылка дошла до
адресата» неотделима от администратора, который её передал, и никакого подтверждения по e-mail
система не выполняет.

Чего здесь сознательно нет:

* **самой записи «приглашение использовано»**. Одноразовость — свойство перехода, а не значения,
  и держать её надо guarded-`UPDATE` слоя доступа с условием по прежнему состоянию (тот же
  приём, что `ADR-016` п. 7 для расхода резервного кода и `ADR-013` для шага TOTP-кода):
  «прочитали `state`, решили, записали» под двумя параллельными принятиями дало бы две учётные
  записи на одну ссылку. Здесь — `user_from_invitation`, которая строит учётную запись, и
  `ensure_invitation_open`, которая отказывает на закрытом приглашении; где именно стоит
  атомарный `UPDATE`, решает срез `apps/web` (перечень — `docs/HANDOFF.md §2`);
* **сроков в колонках «истекло»**. Просроченное приглашение — не состояние: `state` остаётся
  `pending`, а просрочка выводится из `expires_at` и часов. Отдельный признак дал бы два
  источника правды ровно в тот момент, когда их сравнивает тот, кто принимает ссылку (тот же
  выбор, что `packages/identity/sessions.py` сделал для сессий);
* **записей `audit_log`** о выпуске, отзыве и попытках использования (§1.2 `REQ-identity-03`:
  «все попытки использования фиксируются в audit log (IP, user-agent, результат)»). Имена
  событий, поля и цепочка хэшей относятся к `T-109` (перенос зафиксирован `ADR-009`); в этом
  срезе факт попытки несёт только строка журнала процесса, а IP и user-agent — уровень
  `apps/web`.
"""

from __future__ import annotations

import hashlib
import re
import secrets
from dataclasses import dataclass
