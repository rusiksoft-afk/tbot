"""Роли и авторизация на уровне сервиса: три роли, наследование, отказ без утечки (TZ §1.1, `T-106`).

`REQ-identity-01` требует ровно три роли, наследования `viewer ⊂ operator ⊂ admin` и проверки
роли **на уровне сервиса, а не шаблона**. Этот модуль держит первые два пункта и половину третьего:
он не знает ни про HTTP, ни про сеанс, ни про репозиторий — он отвечает на вопросы «что значит роль»,
«достаточна ли роль» и «какой ответ обязан быть у отказа». Зависимость маршрута вызывает отсюда
единственную функцию (`ensure_account_role`), поэтому «проверка роли в шаблоне» остаётся
невозможной по построению: в шаблоне нет ни объекта роли, ни ответа отказа.

Почему наследование выражено рангом, а не набором разрешений. `REQ-identity-01` формулирует
наследование как включение множеств возможностей (`viewer ⊂ operator ⊂ admin`), то есть роль
«старше» другой ровно тогда, когда умеет всё, что умеет младшая. Пока у ролей нет перечня
возможностей (страниц оператора и администратора строятся `T-105`, `T-108`, `T-603»), линейный
ранг — единственная форма, которая не выдумывает этот перечень заранее и при этом проверяема:
сравнение рангов вместо `role == "admin"` закрывает и будущие уровни, и сам факт наследования.
Если перечень возможностей всё-таки понадобится (одна возможность у `viewer`, но не у `operator`),
ранг заменится на неё, и менять придётся этот модуль и проверки к нему, а не каждый маршрут.

Почему отказ — один объект с закрытым набором причин. `AC-identity-01` требует `403` **без утечки**
списка пользователей, а матрица §8.8 требует «`operator` к чужим данным → 403/404 без утечки»;
тот же принцип уже принят для резервных кодов (`ADR-016` п. 5: «чужой», «потраченный» и
«никогда не выпущенный» отвечают одинаково). Если бы отказ роли и отказ по отсутствующей учётной
записи были разными исключениями с разными ответами, ответ начал бы сообщать, *что именно* не
так, — и подбором стало бы различимо, существует ли учётная запись или объект. Поэтому здесь один
класс отказа, а различие причин живёт в поле `reason`, которое читает только журнал процесса.

Чего этот модуль сознательно не решает (подробно — `docs/adr/ADR-017` п. 10):

* **состояние учётной записи** (`users.state`: `invited`, `awaiting_approval`, `suspended`,
  `archived`). `state` — не роль: правило §1.2 «приглашение без одобрения не даёт ни сеанса, ни
  прав» относится к `T-105`, и проверять `state` здесь значило бы решить чужую задачу молча;
* **роли уровня базы данных** (`deploy/postgres/roles.sql`, `ADR-006`): это другой слой, и смена
  его модели требует отдельного решения заказчика, а не этого файла;
* **права на отдельные объекты** (`accounts`, `strategies`): своих объектов у ролей ещё нет, а
  правило владения здесь выражено одним предикатом (`owner_matches`), чтобы вторая проверка
  совпала с предикатом репозитория, а не заменила его.
"""

from __future__ import annotations

from typing import Final
from uuid import UUID

from packages.storage.models import User

# ─── закрытый набор ролей (§1.1) ──────────────────────────────────────────────────────────────

#: Роль владельца системы: пользователи, приглашения, роли, IP-allowlist, kill-switch, журналы
#: (§1.1). Значение — ровно то же literal-значение, которое принимает CHECK `ck_users_role`
#: (ревизия `0002`) и `CheckConstraint` в `packages/storage/models.py`: расхождение ловит
#: проверка `tests/unit/test_authorization_roles.py`, потому что молча разошедшийся набор
#: означал бы «роль есть в коде, но база её отвергает» или наоборот.
ROLE_ADMIN: Final = "admin"

#: Роль владельца счёта (§1.1): свои стратегии, свои счета и токены, свои отчёты, свою
#: Telegram-привязку; чужих пользователей не видит.
ROLE_OPERATOR: Final = "operator"

#: Роль наблюдателя (§1.1): просмотр и экспорт разрешённого набора, ни одной торговой операции;
#: вход всё равно с TOTP (§8.2), то есть роль не ослабляет второй фактор.
ROLE_VIEWER: Final = "viewer"

#: Лестница ролей по возрастанию уровня — форма наследования `viewer ⊂ operator ⊂ admin` из
#: `REQ-identity-01`. Порядок значим: `role_rank` считается индексом в этом кортеже, и переставить
#: элементы местами значит поменять права, а не порядок перечисления.
ROLE_LADDER: Final[tuple[str, ...]] = (ROLE_VIEWER, ROLE_OPERATOR, ROLE_ADMIN)

#: Закрытый набор ролей: ровно три (§1.1 «Система реализует ровно три роли»).
ROLES: Final[frozenset[str]] = frozenset(ROLE_LADDER)

#: Ранг роли по лестнице. Пустых «рангов по умолчанию» здесь нет: роль вне набора обязана падать
#: (`role_rank`), а не получать нулевой уровень — иначе опечатка в значении превратилась бы в
#: «права ниже», то есть в отказ, неотличимый от подделки, либо в права выше, в зависимости от
#: того, на какой конец лестницы поставили неизвестное значение.
ROLE_RANK: Final[dict[str, int]] = {role: rank for rank, role in enumerate(ROLE_LADDER)}

#: Требуемый уровень раздела «Профиль и безопасность» (§9.3 п. 4–5: «любая роль»). Уровень назван
#: именем младшей роли, а не словом «любая»: проверка обязана отвергнуть значение, которого в
#: наборе нет, поэтому «любая роль» = «не ниже `viewer`», и это одно и то же только пока набор
#: закрыт этими тремя значениями.
CONSOLE_TIER: Final = ROLE_VIEWER

#: Требуемый уровень раздела «Администрирование» (§9.3 п. 6–10).
ADMIN_TIER: Final = ROLE_ADMIN


# ─── отказы ───────────────────────────────────────────────────────────────────────────────────


class RoleOutsideDomainError(ValueError):
    """Роль вне закрытого набора (§1.1: «ровно три роли»).

    Отличие от `AccessDeniedError` принципиально: это не поведение пользователя, а испорченные или
    посторонние данные. Схема ограничивает значение CHECK-ограничением, поэтому такой роли в базе
    быть не может; если она всё-таки пришла (правка таблицы руками, будущая ревизия с новой ролью
    раньше, чем о ней узнал сервис), домен обязан сказать об этом прямо. На уровне HTTP этот случай
    всё равно обязан дать тот же отказ, что и все остальные (`ADR-017` п. 4), — иначе по различию
    ответов стало бы видно, что в базе лежит постороннее значение.
    """


class AccessDeniedError(RuntimeError):
    """Единый отказ допуска уровня сервиса.

    В ответ уходит только факт отказа: ни причины, ни требуемой роли, ни имени объекта. Причина
    (`reason`) обязана быть из закрытого набора `DENIAL_REASONS` и читается только журналом
    процесса: по ней оператор различает «человек без прав залез в админку» и «у сеанса пропала
    учётная запись», не подсовывая это различие посетителю.
    """

    def __init__(self, reason: str) -> None:
        if reason not in DENIAL_REASONS:
            raise ValueError(f"причина отказа вне закрытого набора: {reason!r}")
        super().__init__(f"доступ отклонён (причина: {reason})")
        self.reason = reason


#: Причина «роль есть, но ниже требуемой». Обычный случай: `operator` открыл страницу администратора.
DENIAL_ROLE: Final = "role"

#: Причина «роли учётной записи нет в закрытом наборе». Данные испорчены, права показать нельзя.
DENIAL_ROLE_OUTSIDE_DOMAIN: Final = "role_outside_domain"

#: Причина «учётной записи сеанса больше нет в таблице». Отдельной страницы у этого состояния нет
#: намеренно: страница, объясняющая «вас удалили», была бы утечкой про состояние учётной записи
#: тому, кто держит живую куку.
DENIAL_NO_ACCOUNT: Final = "no_account"

#: Закрытый набор причин. Расширять его можно только вместе с проверкой, что ответ остаётся
#: одинаковым для всех причин (`ADR-017` п. 4).
DENIAL_REASONS: Final[frozenset[str]] = frozenset(
    {DENIAL_ROLE, DENIAL_ROLE_OUTSIDE_DOMAIN, DENIAL_NO_ACCOUNT}
)


# ─── правила ──────────────────────────────────────────────────────────────────────────────────


def ensure_role(value: str) -> str:
    """Проверить, что роль входит в закрытый набор, и вернуть её же.

    Нормализации нет намеренно: `Admin`, `ADMIN` и `admin ` база CHECK-ограничением отвергает,
    поэтому приводить регистр в домене означало бы принять значение, которое `INSERT` всё равно
    отклонил бы, и получить два разных источника правды о том, что такое «та же роль». (Логин
    регистронезависим, и за это отвечает `citext` в схеме, а не этот модуль.)
    """
    if value not in ROLES:
        raise RoleOutsideDomainError(
            f"роль {value!r} вне закрытого набора {sorted(ROLES)} (TZ §1.1: ровно три роли)"
        )
    return value


def role_rank(value: str) -> int:
    """Уровень роли по лестнице `viewer → operator → admin`."""
    ensure_role(value)
    return ROLE_RANK[value]


def role_allows(actual: str, required: str) -> bool:
    """Достаточна ли роль `actual` для уровня `required` (наследование, `REQ-identity-01`).

    `True` для пары (`admin`, `operator`) и есть то самое включение множеств: старшая роль
    проходит всю лестницу вниз. Роль вне набора не проходит ни один уровень — возвращается `False`,
    а не исключение: вызывающий обязан отказать, и делать отказ исключительным случаем правила
    нельзя (`ensure_account_role` превращает это в `AccessDeniedError` с отдельной причиной).
    """
    try:
        return ROLE_RANK[actual] >= ROLE_RANK[required]
    except KeyError:
        return False


def ensure_role_at_least(actual: str, required: str) -> None:
    """Проверка роли с отказом: `AccessDeniedError(DENIAL_ROLE)` или `..._OUTSIDE_DOMAIN`."""
    ensure_role(required)
    try:
        ensure_role(actual)
    except RoleOutsideDomainError as exc:
        raise AccessDeniedError(DENIAL_ROLE_OUTSIDE_DOMAIN) from exc
    if not role_allows(actual, required):
        raise AccessDeniedError(DENIAL_ROLE)


def ensure_account_role(user: User | None, *, required: str) -> str:
    """Единственная точка проверки роли для слоя входа: вернула роль — пускать можно.

    Порядок проверок задан `ADR-017` п. 3 и он не косметика: отсутствующая строка учётной записи
    проверяется раньше роли, иначе «роли нет» стало бы способом отличить «сеанс живой, а учётки
    больше нет» от «роль не та» — а это ровно та утечка, которую запрещает §8.8 и `AC-identity-01`.

    `None` — не «пустая роль», а состояние «строчки нет»: сеанс мог пережить архивацию или ручную
    правку таблицы. Возвращаемое значение — роль; обработчику она нужна ровно в одном месте
    (показать человеку его собственную роль на странице профиля, §9.3 п. 4).
    """
    if user is None:
        raise AccessDeniedError(DENIAL_NO_ACCOUNT)
    ensure_role_at_least(user.role, required)
    return user.role


def owner_matches(principal_owner: UUID | None, object_owner: UUID | None) -> bool:
    """Принадлежит ли объект тому, кто выполняет запрос.

    Второй контур, а не замена первого: основной — предикат репозитория (`user_id` внутри самого
    `SELECT`, см. `SqlStore.session_of_user`), и матрица §8.8 требует, чтобы чужого объекта поиск
    не находил вовсе. Здесь сверяется то же самое уже после находки: если предикат репозитория
    когда-нибудь потеряется, маршруту не придётся об этом помнить — отказ наступит в слое.

    Значение `None` с любой стороны означает «не совпало», а не «не проверяем»: `id` учётной записи
    у боевой строки не бывает пустым (колонка `NOT NULL`), поэтому пустое значение — это сломанные
    данные, и молча пропустить их нельзя.

    Ответ слоя обязан совпадать с ответом «объекта нет» (§8.8: «`operator` к чужим данным →
    403/404 без утечки»): вызывающий не имеет права сообщить, что объект существует, но чужой.
    """
    if principal_owner is None or object_owner is None:
        return False
    return principal_owner == object_owner
