"""`identity` — доступ: учётные записи, роли, сессии, 2FA, журнал (CAPABILITY_MAP №4, TZ §8).

Слой отвечает за правила допуска к системе: пароли и их политика, блокировка перебора,
приглашения, сессии, TOTP и резервные коды, роли и авторизация на уровне сервиса. Схема данных
при этом принадлежит `storage` (ORM-отображения таблиц), а не здесь: `identity` только меняет
поля объектов и проверяет правила. Импорт разрешён только «вниз» по Capability Map
(контракт `tests/contract/test_repo_layout.py`).

Границы по срезам (см. `tasks/todo.md`): `T-101` закрыт полностью (политика паролей, Argon2id,
блокировка после 5 неудач). `T-102` закрыт доменом сессий: срок, шаг входа, пересоздание и отзыв;
куки, CSRF, CSP и счётчик частоты запросов — второй срез `T-102` в `apps/web`. TOTP и резервные
коды (`T-103`, `T-104`) закрыты срезами `R4a`–`R5c`. Роли (`T-106`) — `packages/identity/
authorization.py` плюс второй контур в `apps/web`; приглашения и состояния учётной записи
(`T-105`) — срез `R7a`: `packages/identity/invitations.py` (ссылка, срок, одноразовость, отзыв)
и раздел состояний в `packages/identity/users.py`; HTTP-контур (`/admin/users`, страница
принятия приглашения, guarded-`UPDATE` перехода) — следующий срез `T-105`.
"""

