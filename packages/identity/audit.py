"""Журнал аудита: канонический вид записи, цепочка хэшей, реестр событий, разбор цепочки.

TZ §4.1 (`REQ-identity-04`), §8.7, задача `T-109`, оформление — `docs/adr/ADR-025`.

Что закреплено этим модулем:

* **канонический вид записи.** Хэш считается от байтов, которые можно получить из строки базы
  повторно тем же способом. Отсюда три нормализации: время — UTC с микросекундами, адрес —
  канонический текст колонки `INET` (psycopg3 читает её объектом `ipaddress`, а не строкой),
  `details` — JSON с отсортированными ключами (`jsonb` порядок ключей не сохраняет). Без этого
  одна и та же строка давала бы два разных хэша, и цепочка «ломалась» бы на проверке, а не на
  правке;
* **хэш привязан к предыдущему хэшу.** `hash = SHA-256(домен || канонический JSON записи ||
  hash_prev)` — §4.1 буквально требует «SHA-256 от канонического JSON записи + предыдущий хэш».
  Домен (`tbot-audit-v1`) входит в материал: иначе запись одной цепочки стала бы корректной
  в другой, если алгоритм когда-нибудь изменится;
* **`id` в материал не входит.** Его выдаёт база (`BIGINT GENERATED BY DEFAULT AS IDENTITY`,
  §4.1) *до* того, как приложение успело бы что-либо хэшировать, и требовать его было бы
  нельзя. Порядок цепочки задаётся им, а связь «две строки на одного же предка» держит
  частичный уникальный индекс `ix_audit_log_hash_prev_linked` (ревизия `0007`): он же закрывает
  и «продублировали запись на том же месте»;
* **реестр событий закрыт** (`AUDIT_ACTIONS`): имена берёт §8.7, а не маршрут. Открытый перечень
  означал бы, что каждый следующий срез изобретает своё имя, и «обязательные события» §8.7
  перестали бы сверяться с текстом ТЗ (проверка — `tests/unit/test_audit_chain.py`);
* **разрывы видит инструмент, а не только человек** (`verify_chain`): подделка содержимого,
  вырез строки, вставка строки, обрезанное начало и развилка дают разные коды — `make
  audit-verify` (вторая половина `AC-identity-04`) строится ровно на этом отчёте.

Чего здесь сознательно нет:

* **соединений, транзакций и запросов.** `packages/identity` не импортирует драйвер и не знает
  про транзакцию вызывающего слоя (то же правило, что у `packages/identity/sessions.py`;
  перечень запрещённых импортов держит `tests/contract/test_sessions_contract.py`, несогласованные
  зависимости ловит `tests/contract/test_identity_passwords.py`). Чтение «хвоста» цепочки и
  вставка — слой доступа (`apps/web/store.py`, срез `R2` этого же `T-109`);
* **блокировку хвоста.** Последовательная запись в цепочку — часть протокола добавления (`ADR-025` п. 6:
  `pg_advisory_xact_lock` внутри транзакции вызывающего слоя), а не свойство этих функций;
* **значения секретов.** В журнале живут идентификаторы, коды причин и длины; ключи вида
  `password`/`token`/`code_hash` отклоняются (`_DETAIL_KEY_DENYLIST`) — страховка по `ADR-004`
  и `ADR-019` (репозиторий публичный), а не граница: граница в том, что значения в журнал не
  пишут;
* **проверку прав.** Append-only держит база (`deploy/postgres/roles.sql`, `REQ-identity-04`),
  здесь — только разбор уже прочитанных строк.
"""

