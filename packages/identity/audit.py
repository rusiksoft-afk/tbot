def _normalized_key(key: object) -> str:
    if not isinstance(key, str):
        msg = f"ключ details обязан быть строкой, получено {type(key).__name__}"
        raise AuditRecordError(msg)
    return key.replace("_", "").replace("-", "").replace(" ", "").lower()


def _validate_details_value(value: object, *, path: str) -> None:
    """Рекурсивная проверка значения `details`.

    Два правила диктует не вкус, а обратимое чтение значения из `jsonb`:

    * нецелые числа отклоняются: `jsonb` хранит число как `numeric`, и значение вида `1e2`
      возвращается текстом `100.0`, то есть канонический JSON записи перестал бы совпадать
      с тем, что отхэшировало приложение; строка или целое возвращаются ровно в той форме,
      которую отхэшировали;
    * ключи не должны выглядеть как секреты (`ADR-004`, `ADR-019`).
    """
    if value is None or isinstance(value, bool):
        return
    if isinstance(value, str):
        return
    if isinstance(value, int):
        return
    if isinstance(value, float | Decimal):
        msg = f"{path}: нецелое число в details делает канонический JSON нестабильным ({value!r})"
        raise AuditRecordError(msg)
    if isinstance(value, Mapping):
        for key, item in value.items():
            normalized = _normalized_key(key)
            if normalized in _DETAIL_KEY_DENYLIST:
                msg = (
                    f"{path}: ключ {key!r} похож на значение секрета — в журнале его быть не должно"
                )
                raise AuditRecordError(msg)
            _validate_details_value(item, path=f"{path}.{key}")
        return
    if isinstance(value, list | tuple):
        for index, item in enumerate(value):
            _validate_details_value(item, path=f"{path}[{index}]")
        return
    msg = f"{path}: значение типа {type(value).__name__} не является JSON-совместимым"
    raise AuditRecordError(msg)


def _details_copy(details: Mapping[str, Any]) -> dict[str, Any]:
    """Глубокая копия JSON-значения: словарь попадёт и в `jsonb`, и в материал хэша.

    Копия обязательна: чужая правка после построения записи изменила бы строку, не изменив
    хэш, и проверка показала бы «подделку» там, где приложение само поменяло данные.
    """
    return cast("dict[str, Any]", json.loads(json.dumps(details, ensure_ascii=False)))


def _normalize_details(details: Mapping[str, Any] | None) -> dict[str, Any] | None:
    if details is None:
        return None
    _validate_details_value(details, path="details")
    return _details_copy(details)


def canonical_at(moment: datetime) -> str:
    """Время записи как канонический текст: UTC, микросекунды, смещение `+00:00`.

    Микросекунды печатаются всегда (`timespec="microseconds"`), иначе момент с нулевыми
    долями вернулся бы из базы другой строкой, чем та, что отхэшировало приложение.
    """
    return ensure_aware(moment).astimezone(UTC).isoformat(timespec="microseconds")


def canonical_ip(value: object) -> str:
    """Адрес как канонический текст колонки `INET`.

    psycopg3 читает `INET` объектом `ipaddress.IPv4Address`/`IPv6Address`, а пишет принимаем
    строку — форма записи (прописные буквы, ведущие нули, `::ffff:1.2.3.4`) обязана сходиться с
    формой чтения, иначе одна строка даст два разных хэша. IPv4-mapped приводится к IPv4: база
    хранит такие адреса раздельно (`AF_INET` против `AF_INET6` со смешанным выводом), и
    нормализация обязана быть идемпотентной.
    """
    if isinstance(value, ipaddress.IPv4Address | ipaddress.IPv6Address):
        address: ipaddress.IPv6Address | ipaddress.IPv4Address = value
    elif isinstance(value, str):
        try:
            address = ipaddress.ip_address(value.strip())
        except ValueError as error:
            msg = f"адрес журнала не является IP-адресом: {value!r}"
            raise AuditRecordError(msg) from error
    else:
        msg = f"адрес журнала обязан быть строкой или IP-адресом, получено {type(value).__name__}"
        raise AuditRecordError(msg)
    if isinstance(address, ipaddress.IPv6Address) and address.ipv4_mapped is not None:
        address = address.ipv4_mapped
    return str(address)


def _to_text(value: object) -> str | None:
    """`None` остаётся `None`; `UUID` и `int` становятся своим каноническим текстом."""
    if value is None:
        return None
    if isinstance(value, str):
        return value
    if isinstance(value, UUID | int):
        return str(value)
    msg = f"значение обязано быть строкой, UUID или целым, получено {type(value).__name__}"
    raise AuditRecordError(msg)


# ─── запись и её хэш ────────────────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class AuditRecord:
    """Смысловое содержимое строки журнала — то, что входит в хэш.

    Поля совпадают с колонками `audit_log` (§4.1), кроме `id` (его выдаёт база) и `hash` (его
    считает приложение). Нормализованные значения лежат уже в канонической форме: даты — UTC,
    адрес — текст `INET`, `details` — уже проверенный словарь.
    """

    at: datetime
    action: str
    actor: UUID | None = None
    entity: str | None = None
    entity_id: str | None = None
    details: Mapping[str, Any] | None = None
    ip: str | None = None
    request_id: UUID | None = None
    hash_prev: str | None = None

    def canonical_json(self) -> str:
        """Канонический JSON записи: ключи отсортированы, разделителей нет, UTF-8 как есть.

        `jsonb` порядок ключей не сохраняет, поэтому отсортированный вывод — единственная
        форма, которая совпадает с чтением той же строки из базы.
        """
        payload: dict[str, Any] = {
            "at": canonical_at(self.at),
            "action": self.action,
            "actor": str(self.actor) if self.actor is not None else None,
            "entity": self.entity,
            "entity_id": self.entity_id,
            "details": dict(self.details) if self.details is not None else None,
            "ip": self.ip,
            "request_id": str(self.request_id) if self.request_id is not None else None,
        }
        return json.dumps(payload, ensure_ascii=False, separators=(",", ":"), sort_keys=True)

    def content_hash(self) -> str:
        """SHA-256 от `домен || канонический JSON || hash_prev` (§4.1, `REQ-identity-04`).

        `hash_prev` входит отдельной частью, а не ключом JSON: так связь цепочки видна в самом
        рецептуре хэша, а не спрятана в одном поле из восьми.
        """
        material = _PART_SEPARATOR.join((CHAIN_DOMAIN, self.canonical_json(), self.hash_prev or ""))
        return hashlib.sha256(material.encode("utf-8")).hexdigest()


def make_record(
    *,
    action: str,
    at: datetime | None = None,
    actor: UUID | None = None,
    entity: object = None,
    entity_id: object = None,
    details: Mapping[str, Any] | None = None,
    ip: object = None,
    request_id: UUID | None = None,
    hash_prev: str | None = None,
) -> AuditRecord:
    """Собрать нормализованную запись журнала.

    `at` по умолчанию — «сейчас» (`packages/common.clock.utc_now`, §2.7): время обязано быть
    выставлено приложением, а не `server_default now()`, иначе момент, который отхэшировали, и
    момент, который лег в колонку, могли бы разойтись на микросекунды.

    `entity`/`entity_id` принимаются широким типом, чтобы вызывающий слой мог подать `UUID`
    объекта: в колонке `TEXT` (`§4.1`) он живёт своим каноническим текстом.
    """
    if action not in AUDIT_ACTIONS:
        msg = f"событие {action!r} нет в реестре `AUDIT_ACTIONS` (TZ §8.7)"
        raise AuditRecordError(msg)
    if hash_prev is not None and not _is_hex64(hash_prev):
        msg = "hash_prev обязан быть 64 шестнадцатеричными символами (колонка `hash_prev`)"
        raise AuditRecordError(msg)
    return AuditRecord(
        at=ensure_aware(at) if at is not None else utc_now(),
        action=action,
        actor=actor,
        entity=_to_text(entity),
        entity_id=_to_text(entity_id),
        details=_normalize_details(details),
        ip=canonical_ip(ip) if ip is not None else None,
        request_id=request_id,
        hash_prev=hash_prev,
    )


def _is_hex64(value: str) -> bool:
    return len(value) == _HEX64_LEN and all(char in "0123456789abcdef" for char in value)


def audit_row_values(record: AuditRecord) -> dict[str, Any]:
    """Значения колонок строки журнала по записи — один источник для ORM-объекта и для `INSERT`.

    Нужен ровно потому, что у слоя доступа два пути к одной таблице: ORM-объект (проверки и
    инструменты разбора) и конструктор `INSERT` (боевая вставка, где обязано быть видно число
    затронутых строк — `ADR-025` п. 6). Два списка колонок разошлись бы при первой же правке, и
    второй путь начал бы молча терять колонку, а с ней и часть материала хэша.

    `id` в наборе нет: колонку выдаёт база (§4.1), и в материал хэша она не входит (`ADR-025` п. 3).
    """
    return {
        "at": record.at,
        "actor": record.actor,
        "action": record.action,
        "entity": record.entity,
        "entity_id": record.entity_id,
        "details": dict(record.details) if record.details is not None else None,
        "ip": record.ip,
        "request_id": record.request_id,
        "hash_prev": record.hash_prev,
        "hash": record.content_hash(),
    }


def build_audit_entry(record: AuditRecord) -> AuditLogEntry:
    """Построить строку `audit_log` по записи: `hash` посчитан, `id` не выставлен.

    `id` остаётся пустым намеренно: колонка — `BIGINT GENERATED BY DEFAULT AS IDENTITY` (§4.1),
    её выдаёт база, и в материал хэша она не входит (`ADR-025` п. 3).

    Ни соединения, ни коммита здесь нет: запись вставляет и коммитит вызывающий слой — иначе
    состояние и событие журнала (§8.7) могли бы разойтись по разным транзакциям (то же
    правило, что у `packages/identity/sessions.py`).
    """
    return AuditLogEntry(**audit_row_values(record))


# ─── прочитанная строка и разбор цепочки ────────────────────────────────────────────────────


@dataclass(frozen=True)
class StoredRecord:
    """Строка журнала, прочитанная из базы: содержимое плюс то, что записано в колонках хэшей.

    `stored_hash` — значение колонки `hash`, а не пересчёт: сравнение «пересчитали» и «нашли» и
    есть смысл проверки (`AC-identity-04`).
    """

    row_id: int
    record: AuditRecord
    stored_hash: str


def read_stored_record(
    *,
    row_id: object,
    at: datetime,
    action: str,
    actor: object,
    entity: object,
    entity_id: object,
    details: object,
    ip: object,
    request_id: object,
    hash_prev: object,
    stored_hash: object,
) -> StoredRecord:
    """Собрать `StoredRecord` из прочитанных значений колонок (ORM-объект или кортеж `psycopg`).

    Нормализация та же, что при записи: адрес мог прийти объектом `ipaddress`, `details` —
    словарём из `jsonb`, `actor`/`request_id` — объектом `UUID`. Имена колонок — §4.1.
    """
    if not isinstance(row_id, int):
        msg = f"audit_log.id обязан быть целым, получено {type(row_id).__name__}"
        raise AuditRecordError(msg)
    if not isinstance(stored_hash, str) or not _is_hex64(stored_hash):
        msg = f"колонка hash строки {row_id} не содержит 64 шестнадцатеричных символа"
        raise AuditRecordError(msg)
    record = AuditRecord(
        at=ensure_aware(at),
        action=action,
        actor=_to_uuid(actor, where="actor"),
        entity=_to_text(entity),
        entity_id=_to_text(entity_id),
        details=_read_details(details, row_id=row_id),
        ip=canonical_ip(ip) if ip is not None else None,
        request_id=_to_uuid(request_id, where="request_id"),
        hash_prev=_to_text(hash_prev),
    )
    return StoredRecord(row_id=row_id, record=record, stored_hash=stored_hash)


def record_of_entry(entry: AuditLogEntry) -> StoredRecord:
    """`StoredRecord` из ORM-объекта (тот же набор колонок, что у §4.1)."""
    return read_stored_record(
        row_id=entry.id,
        at=entry.at,
        action=entry.action,
        actor=entry.actor,
        entity=entry.entity,
        entity_id=entry.entity_id,
        details=entry.details,
        ip=entry.ip,
        request_id=entry.request_id,
        hash_prev=entry.hash_prev,
        stored_hash=entry.hash,
    )


def _to_uuid(value: object, *, where: str) -> UUID | None:
    if value is None:
        return None
    if isinstance(value, UUID):
        return value
    if isinstance(value, str):
        try:
            return UUID(value)
        except ValueError as error:
            msg = f"{where}: значение не является UUID ({value!r})"
            raise AuditRecordError(msg) from error
    msg = f"{where}: ожидался UUID или его текст, получено {type(value).__name__}"
    raise AuditRecordError(msg)


def _read_details(value: object, *, row_id: int) -> Mapping[str, Any] | None:
    if value is None:
        return None
    if not isinstance(value, Mapping):
        msg = f"details строки {row_id} обязан быть JSON-объектом, получено {type(value).__name__}"
        raise AuditRecordError(msg)
    # Политика записи (запрет нецелых чисел и ключей, похожих на секреты) на чтении не
    # применяется намеренно: строку мог создать и прямой `INSERT` из восстановления дампа.
    # Такое значение должно быть видно как расхождение цепочки (`content_mismatch`), а не как
    # отказ разбора: иначе одна чужая строка обрывала бы проверку всего журнала.
    return _details_copy(cast("Mapping[str, Any]", value))


# ─── отчёт о разборе цепочки ────────────────────────────────────────────────────────────────

#: Коды находок. Каждый отдельный, потому что следствие у них разное: подделка содержимой —
#: «строку правили», обрезанное начало — «читаем не с начала журнала», развилка — «кто-то писал
#: в обход блокировки хвоста» (или дамп собран из двух копий).
IssueKind = Literal["content_mismatch", "broken_link", "missing_prefix", "duplicate_parent"]

#: Находки, делающие вердикт «цепочка нарушена» (`ADR-025` п. 7). Определение переехало сюда из
#: `scripts/audit_verify.py` срезом `R3.2`: его читают и ручная команда, и ежедневная
#: `integrity-check` процесса `jobs`. Два набора кодов разошлись бы при первой же правке, и
#: тогда автоматическая проверка стала бы ругаться на то, что ручная считает нормой (или
#: наоборот): расхождение кодов находок — тот же класс поломки, что и разные ключи замка.
#:
#: Объединение двух наборов обязано оставлять ровно четыре признака `IssueKind` — это держит
#: проверка `tests/integration/test_audit_verify.py`: появится пятый код, и проверка потребует
#: решить, меняет ли он вердикт.
FINDING_KINDS: Final[frozenset[IssueKind]] = frozenset(
    {"content_mismatch", "broken_link", "duplicate_parent"}
)
#: Находки, которые печатаются, но вердикт не меняют: начало цепи отсутствует после законной
#: уборки по §2.8 и у любой ограниченной выборки (`ADR-025` п. 7 и п. 8).
INFORMATIONAL_KINDS: Final[frozenset[IssueKind]] = frozenset({"missing_prefix"})

_ISSUE_TEXT: Final[dict[IssueKind, str]] = {
    "content_mismatch": "хэш строки не совпадает с её содержимым — строку меняли",
    "broken_link": "hash_prev строки не равен хэшу предыдущей строки — разрыв, вставка или развилка",
    "missing_prefix": "у первой строки выборки есть hash_prev — начало цепочки не прочитано",
    "duplicate_parent": "две строки ссылаются на один hash_prev — развилка цепочки",
}


@dataclass(frozen=True)
class ChainIssue:
    """Одна находка разбора: код, строка, относительно которой она найдена, и текст для человека."""

    kind: IssueKind
    row_id: int
    previous_id: int | None
    detail: str

    def describe(self) -> str:
        prefix = f"строка {self.row_id}" + (
            f" (после {self.previous_id})" if self.previous_id is not None else ""
        )
        return f"{prefix}: {self.detail}"


@dataclass(frozen=True)
class ChainReport:
    """Итог разбора: сколько строк посмотрели и что в них не так."""

    rows: int
    first_row_id: int | None
    last_row_id: int | None
    issues: tuple[ChainIssue, ...]

    @property
    def intact(self) -> bool:
        return not self.issues

    def summary(self) -> str:
        if self.rows == 0:
            return "цепочка пуста: строк журнала не прочитано"
        if not self.issues:
            return f"цепочка цела: {self.rows} строк, с {self.first_row_id} по {self.last_row_id}"
        head = f"цепочка нарушена: {self.rows} строк, находок {len(self.issues)}"
        return "\n".join([head, *(issue.describe() for issue in self.issues)])


def verify_chain(records: Sequence[StoredRecord], *, expect_genesis: bool = True) -> ChainReport:
    """Пересчитать хэши прочитанных строк и сверить связи цепочки.

    Порядок строк — по `id` (колонку выдаёт база, §4.1): именно он задаёт хронологию журнала,
    а не `at` (моменты двух процессов могут прийти вразнобой).

    Два сравнения разделены и не подменяют друг друга:

    * `content_mismatch` — пересчёт по колонкам строки не совпал со значением колонки `hash`
      (содержимое правили, не трогая хэш);
    * `broken_link` — значение `hash_prev` не равно колонке `hash` предыдущей строки (строку
      вырезали, вставили, переставили или открыли вторую ветку).

    `expect_genesis=False` нужен выборке «за период» (R3): у первой строки такой выборки
    предыдущий хэш есть по определению, и находка «начала нет» была бы ложной.

    Развилку (`duplicate_parent`) на живой базе создать не должен: её закрывает частичный
    уникальный индекс `ix_audit_log_hash_prev_linked` (ревизия `0007`). Проверка остаётся,
    потому что разбор запускают и на дампе, где индекс мог быть не восстановлен.
    """
    issues: list[ChainIssue] = []
    previous: StoredRecord | None = None
    seen_parents: dict[str, int] = {}
    for record in records:
        recomputed = record.record.content_hash()
        if recomputed != record.stored_hash:
            issues.append(
                ChainIssue(
                    kind="content_mismatch",
                    row_id=record.row_id,
                    previous_id=previous.row_id if previous else None,
                    detail=_ISSUE_TEXT["content_mismatch"],
                )
            )
        if record.record.hash_prev is not None:
            owner = seen_parents.get(record.record.hash_prev)
            if owner is not None:
                issues.append(
                    ChainIssue(
                        kind="duplicate_parent",
                        row_id=record.row_id,
                        previous_id=owner,
                        detail=_ISSUE_TEXT["duplicate_parent"],
                    )
                )
            seen_parents[record.record.hash_prev] = record.row_id

        if previous is None:
            if record.record.hash_prev is not None and expect_genesis:
                issues.append(
                    ChainIssue(
                        kind="missing_prefix",
                        row_id=record.row_id,
                        previous_id=None,
                        detail=_ISSUE_TEXT["missing_prefix"],
                    )
                )
        else:
            if previous.row_id >= record.row_id:
                msg = f"строки выборки идут не по id: {previous.row_id} перед {record.row_id}"
                raise AuditRecordError(msg)
            if record.record.hash_prev != previous.stored_hash:
                issues.append(
                    ChainIssue(
                        kind="broken_link",
                        row_id=record.row_id,
                        previous_id=previous.row_id,
                        detail=_ISSUE_TEXT["broken_link"],
                    )
                )
        previous = record

    first = records[0].row_id if records else None
    last = records[-1].row_id if records else None
    return ChainReport(
        rows=len(records), first_row_id=first, last_row_id=last, issues=tuple(issues)
    )


def findings_of(report: ChainReport) -> tuple[ChainIssue, ...]:
    """Находки, которые делают вердикт «цепочка нарушена» (`ADR-025` п. 7).

    Сам текст вердикта формулирует вызывающий, а не `ChainReport.summary()`: библиотека считает
    любое обращение нарушением цепочки, а `missing_prefix` находкой вердикта не является, поэтому
    общий текст дал бы «цепочка нарушена» рядом с кодом `0` (разбор — `ADR-025` п. 7).
    """
    return tuple(issue for issue in report.issues if issue.kind in FINDING_KINDS)


def informational_of(report: ChainReport) -> tuple[ChainIssue, ...]:
    """Находки, не влияющие на вердикт: сейчас это только `missing_prefix`.

    Отдельная функция нужна затем, чтобы вызывающий печатал их, не превращая в нарушение: у
    ежедневной проверки и у ручной команды общий случай — «цепочка цела, но начала не видно».
    """
    return tuple(issue for issue in report.issues if issue.kind in INFORMATIONAL_KINDS)


def chain_from_drafts(drafts: Iterable[AuditRecord]) -> list[StoredRecord]:
    """Достроить цепочку из «черновиков» (записи без `hash_prev`) — для проверок и инструмента.

    Единственный способ получить корректную цепочку — считать хэш по очереди: предыдущий хэш
    зависит от уже готовой предыдущей строки. Функция нужна и оффлайновой проверке
    (`tests/unit/test_audit_chain.py`), и `make audit-verify` при сверке дампа.
    """
    built: list[StoredRecord] = []
    previous_hash: str | None = None
    for index, draft in enumerate(drafts, start=1):
        record = AuditRecord(
            at=draft.at,
            action=draft.action,
            actor=draft.actor,
            entity=draft.entity,
            entity_id=draft.entity_id,
            details=draft.details,
            ip=draft.ip,
            request_id=draft.request_id,
            hash_prev=previous_hash,
        )
        digest = record.content_hash()
        built.append(StoredRecord(row_id=index, record=record, stored_hash=digest))
        previous_hash = digest
    return built
