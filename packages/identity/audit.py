# ─── алгоритм цепочки (`REQ-identity-04`, TZ §4.1) ──────────────────────────────────────────

#: Метка алгоритма. Она входит в материал хэша, потому что смена правил (например, формата
#: времени) обязана сделать старую цепочку не «переинтерпретируемой», а другой цепочкой.
CHAIN_DOMAIN: Final = "tbot-audit-v1"

#: Разделитель частей материала. Отделивает домен от JSON и JSON от `hash_prev`: склейка
#: «просто конкатенацией» позволила бы сдвинуть границу между частями без изменения хэша.
_PART_SEPARATOR: Final = "\n"

_HEX64_LEN: Final = 64


class AuditRecordError(ValueError):
    """Запись нельзя ни построить, ни корректно захэшировать (значение вне правил журнала)."""


