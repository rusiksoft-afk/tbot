"""Резервные коды входа: 10 значений, хэши SHA-256 и семидневный срок перевыпуска (`T-104`, TZ §8.2).

Модуль знает про значение кода ровно столько, чтобы его выдать и проверить, и не знает ничего про
HTTP, сеанс и базу. Строку `backup_codes` создаёт и меняет слой доступа (`apps/web/store.py`), и
одноразовость держит он же — guarded-`UPDATE` по тому же приёму, что `Store.claim_totp_step`
(`ADR-015` п. 5): «нашёл неиспользованный → пометил использованным» в два отдельных запроса
означает, что двумя параллельными входами один код будет израсходован дважды.

**Почему алфавит ровно такой (§8.2: «10 шт. по 10 символов, алфавит без похожих знаков»).**
Из 26 заглавных букв убраны `I`, `L` и `O`, из цифр — `0` и `1`: на экране телефона и в рукописном
вводе `I`≡`l`≡`1`, `O`≡`0`. Остаётся 31 знак (23 буквы + цифры 2–9), строчных букв нет вовсе — так
одно и то же значение не может быть набрано двумя разными способами внутри алфавита. Следствие по
стойкости: 31^10 ≈ 2^49,5. Это не «защита от подбора в онлайне» (там работает лимит §8.2 — 5 неудач
подряд и блокировка входа на 15 минут), это защита от подбора **офлайн** по украденным хэшам: 10
хэшей из пространства ~5·10^14 не перебираются, тогда как, например, алфавит из 16 знаков дал бы
только 2^40, а шесть знаков — 2^24, и это уже задача.

**Почему хэш — SHA-256 без соли, а не Argon2 (§8.1 требует Argon2id для паролей).** Так требует
§8.2, и схема это закрепляет: `CHECK (code_hash ~ '^[0-9a-f]{64}$')` принимает только 64 hex-символа,
а уникальный индекс `uq_backup_codes_user_id_code_hash` держит правило «10 разных» — с солью в
значении колонки тот же код двух разных выпусков дал бы два разных хэша, и индекс перестал бы что
либо значить. Колонки под соль в `backup_codes` нет, и Argon2-строка (`$argon2id$…`, 96+ символов)
в CHECK не пройдёт. Это осознанный компромисс, а не недосмотр: компенсирующие контроля — уже
названный лимит неудач, лента `totp_failures` и то, что из пространства 2^49,5 под подбором
оказывается не весь код учётной записи, а максимум 10 её значений.

**Почему ввод нормализуется.** Хэш считается по канонической форме — 10 символов верхнего регистра
без разделителей. Человек, который вводит код со строчными буквами или с дефисом (в показе коды
разбиваются группами), обязан попасть в тот же хэш: иначе он сожжёт попытку перебора «своим» кодом и
увидит отказ, которого не заслужил. Расширение признака «такой же код» при этом не меняет: вариантов
хэша не становится больше.

**Формат против «такого кода нет».** Отказ по формату (длина не 10, знак вне алфавита, пусто) не
сообщает ничего о том, существует ли значение у этой учётной записи, — его можно показать прямо и
полезно. А вот «формат верный, значения нет» обязано выглядеть одинаково для своего и чужого кода:
разница сделала бы из страницы оракул («э-э, такой код у тебя есть, но израсходован»).

**Почему срок перевыпуска — производный, а не колонка (§8.2: «сгенерировать новые в течение 7
дней, иначе учётная запись блокируется на вход»).** Дата последнего расхода и дата выпуска строк уже
лежат в `backup_codes` (`used_at`, `created_at`). Отдельная колонка означала бы два места одного
правила, которые расходятся при любом сбое между запросами, плюс новую ревизию схемы и новый набор
прав роли (`ADR-006`). Правило нужно ровно в одном месте — на входе, — и там оно читается из
строк.
"""

from __future__ import annotations

import hashlib
import hmac
import math
import re
import secrets
from collections.abc import Iterable
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Final

from packages.storage.models import BackupCode

# ─── параметры, заданные кодом (не настройкой): §8.2 называет числа ───────────────────────────

#: Сколько кодов выдаётся (§8.2: «Резервные коды: 10 шт.»).
BACKUP_CODE_COUNT: Final = 10

#: Длина одного кода (§8.2: «по 10 символов»).
BACKUP_CODE_LENGTH: Final = 10

#: Алфавит: A–Z без `I`, `L`, `O` и цифры 2–9. Порядок не случайный — строку показывают человеку,
#: и в ней буквы идут раньше цифр, чтобы «код не тот» не выглядел как опечатка в середине.
#: Убрано ровно то, что сливается при чтении с экрана и при наборе; строчных букв нет намеренно
#: (одна форма вместо двух).
BACKUP_CODE_ALPHABET: Final = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"

#: Что убирается из ввода перед сверкой, кроме пробелов любого вида: дефис и оба тире. Показ кодов
#: разбит группами (`display_backup_code`), человек переносит их с дефисом — и обязан попасть в тот
#: же канон.
BACKUP_CODE_SEPARATORS: Final = "-\u2013\u2014"

#: Срок, в течение которого после расхода кода надо выпустить новые (§8.2: «в течение 7 дней»).
#: Просрочка блокирует **вход**, не торговлю (§8.2 прямо разделяет).
RECOVERY_REGENERATION_WINDOW: Final = timedelta(days=7)

#: Число знаков в алфавите и нижняя граница энтропии одного кода в битах. Числа держатся отдельными
#: константами, потому что проверка стойкости обязана быть арифметикой, а не комментарием: сузить
#: алфавит на два знака — значит потерять ~7 бит, и это должно стать красным.
BACKUP_CODE_ALPHABET_SIZE: Final = len(BACKUP_CODE_ALPHABET)
BACKUP_CODE_ENTROPY_BITS: Final = math.log2(float(BACKUP_CODE_ALPHABET_SIZE) ** BACKUP_CODE_LENGTH)

_CODE_RE: Final = re.compile(rf"\A[{re.escape(BACKUP_CODE_ALPHABET)}]{{{BACKUP_CODE_LENGTH}}}\Z")
_SHA256_HEX_RE: Final = re.compile(r"\A[0-9a-f]{64}\Z")


class BackupCodeError(ValueError):
    """Операция с резервным кодом невозможна; текст отказа не содержит значения кода (§8.4)."""


class BackupCodeFormatError(BackupCodeError):
    """Предъявленное значение не может быть кодом: пустое, другой длины или со знаком вне алфавита.

    Отказ по формату безопасен показывать: он не отвечает на вопрос «есть ли такое значение у этой
    учётной записи». Значение в текст не подставляется: код — секрет входа, а сообщение об отказе
    уходит в журнал (`ADR-014` п. 6 тот же порядок держит для секрета привязки).
    """


class BackupCodeGenerationError(BackupCodeError):
    """Пачка не собралась: запрошено неразумное число кодов или значения повторяются."""


# ─── выдача ──────────────────────────────────────────────────────────────────────────────────


def new_backup_codes(count: int = BACKUP_CODE_COUNT) -> tuple[str, ...]:
    """Свежая пачка кодов открытым текстом: `count` разных значений (§8.2: «10 шт.», «10 разных»).

    Источник — `secrets` (криптостойкий), а не `random`: код входа нельзя получать из ПСЧ с
    предсказуемым состоянием. Повторы внутри пачки исключаются на месте: уникальный индекс
    `uq_backup_codes_user_id_code_hash` отверг бы дубликат только в базе и только ценой
    `UniqueViolation` посреди HTTP-запроса, а здесь дубликат замечен до выдачи — ровно та причина,
    по которой в модели стоит этот индекс (докстринг `BackupCode`).

    Значения возвращаются открытым текстом **один раз** — показать их обязан маршрут, и больше
    открыть их нельзя: в базе остаются только хэши (`ADR-014` п. 6 перенесён на резервные коды
    `ADR-016` п. 2).
    """
    if not 1 <= count <= 1000:
        raise BackupCodeGenerationError(
            f"запрошено {count} кодов: разумный диапазон — от 1 до 1000"
        )
    codes: list[str] = []
    seen: set[str] = set()
    attempts = 0
    # Вероятность повтора здесь пренебрежимо мала (пространство ~5·10^14), но петля обязана быть с
    # границей попыток: иначе дефект алфавита (например сужение до одного знака) превратился бы в
    # зависший запрос вместо отказа.
    while len(codes) < count and attempts < count * 20:
        attempts += 1
        code = "".join(secrets.choice(BACKUP_CODE_ALPHABET) for _ in range(BACKUP_CODE_LENGTH))
        if code not in seen:
            seen.add(code)
            codes.append(code)
    if len(codes) != count:
        raise BackupCodeGenerationError(
            f"не удалось собрать {count} разных кодов: алфавит слишком узкий"
        )
    return tuple(codes)


def normalize_backup_code(raw: str) -> str:
    """Предъявленная строка → канон, по которому считается хэш; или `BackupCodeFormatError`.

    Пробелы (включая переводы строк и табуляцию), дефис, короткое и длинное тире убираются,
    буквы переводятся в верхний регистр. Дальше значение обязано состоять ровно из
    `BACKUP_CODE_LENGTH` знаков алфавита.

    Знаки вне алфавита **не** заменяются похожими («O» → «0»): автозамена исправляет опечатку
    молча и создаёт коды, которые приложение принимает не так, как показывает. Пусть лучше будет
    явный отказ по формату.
    """
    compact = "".join(raw.split())
    for separator in BACKUP_CODE_SEPARATORS:
        compact = compact.replace(separator, "")
    candidate = compact.upper()
    if not candidate:
        raise BackupCodeFormatError("код пуст: резервный код — 10 символов")
    if not _CODE_RE.fullmatch(candidate):
        raise BackupCodeFormatError(
            f"код должен быть ровно из {BACKUP_CODE_LENGTH} знаков алфавита "
            f"{BACKUP_CODE_ALPHABET} (убраны I, L, O, 0 и 1)"
        )
    return candidate


def display_backup_code(code: str, *, group_size: int = 5) -> str:
    """Как показать код человеку: канон разбит группами по 5 знаков.

    Только показ: разделители не попадают ни в хэш, ни в сравнение (`normalize_backup_code` их
    убирает). Десять подряд идущих знаков читаются и сверяются хуже, чем две группы; при этом
    формат показа не должен стать форматом хранения.
    """
    if group_size < 1:
        raise BackupCodeError(f"некорректная ширина группы показа: {group_size}")
    return "-".join(code[i : i + group_size] for i in range(0, len(code), group_size))


# ─── сверка ──────────────────────────────────────────────────────────────────────────────────


def hash_backup_code(code: str) -> str:
    """Хэш кода в форме, которую принимает колонка `code_hash`: SHA-256, hex, нижний регистр.

    Хэш считается по канону, а не по предъявленной строке: «тот же код, набранный со строчных
    букв» обязан дать тот же хэш, иначе он не совпадёт с выпущенным значением и сожжёт попытку
    перебора. Канонизация выполняется здесь же, поэтому у вызывающего кода не появляется соблазн
    посчитать хэш от сырой формы.
    """
    canonical = normalize_backup_code(code)
    return hashlib.sha256(canonical.encode("ascii")).hexdigest()


def is_sha256_hex(value: str) -> bool:
    """Проверка формы хэша: ровно то, что требует `CHECK` схемы (`^[0-9a-f]{64}$`).

    Отдельная функция нужна не для красоты: прежде чем сравнивать с колонкой, слой доступа обязан
    понять, что строка не битая. Строка другой длины сравнивается всегда неудачно, и «битая»
    строка в таблице выглядела бы как «кода нет» — это ровно тот класс поломки, который должен
    быть различим в разборе, а не молча отвергнут.
    """
    return bool(_SHA256_HEX_RE.fullmatch(value))


def backup_code_matches(stored_hash: str, presented: str) -> bool:
    """Совпадает ли предъявленное значение с хэшем из строки `backup_codes`.

    Сравнение — `hmac.compare_digest` по hex-строкам. Оно не даёт преимущества взломщику: чтобы
    попасть в сравнение, надо уже знать предъявленное значение, а из времени сравнения hex-строк
    обратного вывода нет. Зато порядок остаётся безопасным по умолчанию, если кто-то решит, что
    «сравнение хэшей — не секретная операция».

    Ложь возвращается и когда форма хэша в строке битая, и когда предъявленное значение не может
    быть кодом: решение о том, что показывать человеку («формат не тот» против «кода нет»),
    принимает маршрут — он обязан вызвать `normalize_backup_code` сам и не выдавать разницу между
    своим и чужим значением.
    """
    if not is_sha256_hex(stored_hash):
        return False
    try:
        computed = hash_backup_code(presented)
    except BackupCodeFormatError:
        return False
    return hmac.compare_digest(computed, stored_hash)


# ─── семидневный срок (§8.2: расход → предупреждение → блокировка входа) ──────────────────────


@dataclass(frozen=True)
class RecoveryState:
    """Состояние резервных кодов учётной записи — для предупреждения и для решения о входе.

    Поля описаны так, чтобы маршрут не пересчитывал правило сам: `needs_regeneration` —
    обязательное предупреждение после расхода (§8.2), `login_blocked` — просрочка семидневного
    срока, которая блокирует вход, но не торговлю, `regeneration_deadline` — до какого момента
    время ещё есть (его и показывает страница). Пустой набор строк — не «всё хорошо», а «кодов
    никогда не выпускали»: резервного пути входа у такой учётной записи нет, и решение о том,
    показывать ли ссылку «использовать резервный код», маршрут принимает по этому признаку.
    """

    unused: int
    used: int
    last_used_at: datetime | None
    regeneration_deadline: datetime | None
    needs_regeneration: bool
    login_blocked: bool


def recovery_state(codes: Iterable[BackupCode], *, now: datetime) -> RecoveryState:
    """Состояние по строкам `backup_codes`: сколько осталось, когда срок и надо ли перевыпускать.

    Правило перевыпуска: после расхода любого кода учётная запись обязана выпустить новую пачку за
    `RECOVERY_REGENERATION_WINDOW`. Обязательство считается снятым, если после последнего расхода
    есть строка, созданная **не раньше** него (`created_at >= max(used_at)`) — то есть выпущенная
    уже после расхода. Строгое `>` здесь специально заменено на `>=`: микросекундная ничья между
    выпуском и расходом возможна только в одном переходе, и ошибиться в неё дороже в сторону
    блокировки входа, чем в сторону «предупреждение не показали».

    Просрочка — `now > last_used_at + 7 суток`: «в течение 7 дней» включает сам момент границы,
    поэтому блокировка наступает строго после неё.

    Расход из новой пачки отсчитывает срок заново: `max(used_at)` берётся по всем израсходованным
    строкам, а не по «последней пачке». Иначе пережившая расход пачка выглядела бы выполненным
    обязательством, и предупреждение пропало бы ровно там, где оно нужнее всего.

    Аргумент — `Iterable`, но внутри он один раз разворачивается в список: правило требует двух
    проходов (расход, потом «был ли выпуск после расхода»), а одноразовый итератор из слоя доступа
    на втором проходе дал бы пустоту — то есть «перевыпуск не нужен» и «кодов нет» одновременно.
    """
    rows = list(codes)
    unused = 0
    used = 0
    last_used: datetime | None = None

    for row in rows:
        if row.used_at is None:
            unused += 1
        else:
            used += 1
            if last_used is None or row.used_at > last_used:
                last_used = row.used_at

    reissued_after_spend = last_used is not None and any(
        row.used_at is None and row.created_at >= last_used for row in rows
    )
    needs_regeneration = last_used is not None and not reissued_after_spend
    deadline = None if last_used is None else last_used + RECOVERY_REGENERATION_WINDOW
    blocked = needs_regeneration and deadline is not None and now > deadline

    return RecoveryState(
        unused=unused,
        used=used,
        last_used_at=last_used,
        regeneration_deadline=deadline,
        needs_regeneration=needs_regeneration,
        login_blocked=blocked,
    )
