-- Правовая модель базы данных (T-009, REQ-identity-04, TZ §4.1 и §8.4).
--
-- Роли две: `tbot_app` — от неё работают `web`, `engine`, `jobs` **и `migrate`** (миграции идут
-- той же ролью, что и приложение: решение заказчика от 2026-11-21, ask `8d2be9bb`, вариант Б);
-- и роль-владелец схемы (`tbot` на площадке — её создаёт образ Postgres) — от неё идут
-- `roles.sql` и административные команды. Разделение нужно потому, что append-only к `audit_log`
-- формулируется правами базы: у владельца таблицы отзыв прав не работает (права владельца
-- неявные), поэтому приложение обязано ходить НЕ владельцем журнала.
--
-- Запускать после применения миграций: права выдаются по уже существующим таблицам, а исключение
-- для журнала выдаётся явно. После каждой ревизии, которая добавляет таблицу, файл тоже нужно
-- запускать повторно (он идемпотентен) — иначе новая таблица не получит прав.
--
-- Паролей здесь нет и быть не должно: значения — секреты (ADR-004), их вносит
-- `deploy/vps/secrets-setup.sh`; здесь только имена ролей и права.

BEGIN;

-- 0) Роль запуска: файл применяет роль-владелец схемы, а не приложение. Иначе п. 2.1
--    (`OWNER TO CURRENT_USER`) передал бы владение журналом самому приложению, а у владельца
--    отзыв прав не действует. Guard стоит первым намеренно: без него запуск ролью приложения
--    спотыкается только о `ALTER ROLE` в п. 1 («permission denied to alter role» — замер на
--    площадке 2026-11-21). Состояние базы от того же не портится (транзакт сворачивается), но
--    сообщение читается как поломка файла, а не как нарушенное правило запуска.
DO $guard$
BEGIN
    IF current_user = 'tbot_app' THEN
        RAISE EXCEPTION
            'roles.sql обязан запускаться ролью-владельцем схемы, не приложением (п. 0 файла прав)';
    END IF;
END
$guard$;

-- 1) Роль приложения. Создаётся без пароля и без права входа: пока шаг переключения не выдал
--    пароль и LOGIN, войти в неё нельзя, и это правильно. Повторный запуск файла права входа не
--    отзывает (иначе `roles.sql`, запущенный после переключения, отключил бы приложение).
DO $do$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tbot_app') THEN
        CREATE ROLE tbot_app NOLOGIN;
    END IF;
END
$do$;

ALTER ROLE tbot_app WITH NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

-- 2) Схема: приложение пользуется `public` и создаёт в нём объекты. Право `CREATE` нужно
--    `alembic`: в этом составе миграции запускаются ролью приложения, и без права на схему
--    первая же ревизия следующей задачи падает (`42501 permission denied for schema public` —
--    замер на площадке 2026-11-21). Право создавать объекты в схеме НЕ даёт прав на чужие
--    объекты: `ALTER TABLE`, `DROP TABLE` и `CREATE INDEX` по таблице владельца остаются отказом
--    по правам (проверка `test_приложение_не_правит_чужие_объекты`).
--    В PostgreSQL 15+ право CREATE на `public` есть только у владельца базы; строка ниже —
--    страховка от иного способа инициализации кластера.
GRANT USAGE, CREATE ON SCHEMA public TO tbot_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

-- 2.1) Таблицы реестра append-only принадлежат роли-владельцу, а не приложению. Право `CREATE`
--    из п. 2 нужно миграциям, а таблицу, созданную миграцией, миграция и владеет. Если такой
--    таблицей окажется следующая таблица журнала, `REVOKE` по ней ничего бы не отнял. Поэтому
--    каждая таблица реестра `APPEND_ONLY_TABLES` при каждом запуске файла возвращается текущему
--    владельцу схемы. Правило новой таблицы журнала: имя — в реестр
--    (`packages/storage/base.py`), `ALTER TABLE` — сюда, `REVOKE` — в п. 4; перечень сверяет
--    контрактный тест `tests/contract/test_db_roles.py`.
ALTER TABLE audit_log OWNER TO CURRENT_USER;

-- 3) Все таблицы текущей схемы: полный DML.
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO tbot_app;

-- 4) Журнал — только дописывание и чтение (REQ-identity-04). Явная выдача `SELECT`/`INSERT`
--    держится рядом с отзывом намеренно: после п. 2.1 журнал мог принадлежать приложению, и
--    права по п. 3 на него мог выдать не текущий владелец.
--    `TRUNCATE`, `REFERENCES` и `TRIGGER` отзываются, потому что журнал не должен
--    перестраиваться, становиться целью внешних ключей из новых таблиц или обвешиваться
--    триггерами, которые меняют правило «дописали — и больше не трогают».
GRANT SELECT, INSERT ON TABLE audit_log TO tbot_app;
REVOKE UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER ON TABLE audit_log FROM tbot_app;

-- 5) Таблицы, которые появятся в следующих ревизиях, получают полный DML автоматически.
--    Без этого новая таблица была бы невидима для приложения до ближайшего ручного `GRANT`.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO tbot_app;

-- Явные последовательности — только USAGE. У identity-колонки своя внутренняя последовательность
-- (например, `audit_log_id_seq`), отдельного права на неё не требуется: PostgreSQL проверяет
-- права на саму таблицу (`NextValueExpr` в движке вызывается без проверки прав последовательности).
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE ON SEQUENCES TO tbot_app;

-- 6) Членство: владелец может пересесть в роль приложения (`SET ROLE tbot_app`) и проверить права
--    без пароля — этим пользуются runbook и тест `test_audit_append_only_role`.
GRANT tbot_app TO CURRENT_USER;

COMMIT;
